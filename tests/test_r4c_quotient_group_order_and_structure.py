def test_exam_keys_are_recomputed_from_the_text():
    for seed in range(40):
        question = sup.exam(TOPIC, seed)
        m, n, a, b = _numbers(question.stem)
        coset_of, size, exponent, order = _quotient(m, n, a, b)
        pa, pb, pc, pd = question.parts
        point = tuple(int(v) for v in re.search(r"element \((\d+), (\d+)\) \+ H", pc.prompt).groups())
        assert int(pa.answer) == len({coset_of[(0, 0)]}) * len({((j * a) % m, (j * b) % n) for j in range(m * n)})
        assert int(pb.answer) == size
        assert int(pc.answer) == order(point)
        assert pd.answer == [size // exponent, exponent]


def test_exam_follow_through_for_the_quotient_order():
    s = sup.skill(SKILL_ID)
    checked = 0
    for seed in range(40):
        question = sup.exam(TOPIC, seed)
        m, n = _numbers(question.stem)[:2]
        wrong = int(question.parts[0].answer) + 1
        if (m * n) % wrong:
            continue
        sent = {p.label: p.answer_text for p in question.parts} | {"a": str(wrong), "b": str(m * n // wrong)}
        result = grade(s, question, sent)
        assert result.parts["b"].marks == 1 and result.parts["b"].follow_through is True, (seed, sent)
        checked += 1
    assert checked >= 8
