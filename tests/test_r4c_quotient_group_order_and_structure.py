"""Tests `uc2-quotient-group-order-and-structure`: each quotient is built as a set of cosets from the numbers in the
question text, and its order, element orders and invariant factors are read off by brute force."""

from __future__ import annotations

import math
import re
from functools import lru_cache
from itertools import product

import mathgen.generators.r4c_quotient_group_order_and_structure_build  # noqa: F401  (registers the topics)
