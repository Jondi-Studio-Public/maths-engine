from tests import r4c_support as sup

TOPIC = "r4c_quotient_group_order_and_structure"
SKILL_ID = "uc2-quotient-group-order-and-structure"


@lru_cache(maxsize=None)
def _quotient(m, n, a, b):
    """(cosets as a dict element -> coset id, size of the quotient, exponent of the quotient)."""
    subgroup, x = set(), (0, 0)
    while x not in subgroup:
        subgroup.add(x)
        x = ((x[0] + a) % m, (x[1] + b) % n)
    coset_of = {}
    for g in product(range(m), range(n)):
        coset_of[g] = min(((g[0] + h[0]) % m, (g[1] + h[1]) % n) for h in subgroup)
    reps = set(coset_of.values())

    def order(g):
        k, y = 1, g
        while coset_of[y] != (0, 0):
            y = ((y[0] + g[0]) % m, (y[1] + g[1]) % n)
            k += 1
        return k

    exponent = 1
    for g in reps:
        k = order(g)
        exponent = exponent * k // math.gcd(exponent, k)
    return coset_of, len(reps), exponent, order


def _numbers(text):
    return [int(v) for v in re.search(r"Z_(\d+) × Z_(\d+)", text).groups()] + [
        int(v) for v in re.search(r"(?:generated by |H = ⟨|The element )\((\d+), (\d+)\)", text).groups()
    ]


def test_wiring():
    sup.check_wiring(SKILL_ID, TOPIC, "number")


def test_easy_element_order_in_the_cyclic_quotient():
    for seed in range(80):
        question = sup.q(TOPIC, "easy", seed)
        n, k, a = (
            int(v)
            for v in (
                *re.search(r"Z_(\d+) / ⟨(\d+)⟩", question.text).groups(),
                re.search(r"(\d+) \+ ⟨", question.text).group(1),
            )
        )
        subgroup = {(k * j) % n for j in range(n)}
        least = next(j for j in range(1, n + 1) if (j * a) % n in subgroup)
        assert int(question.answer) == least, (seed, question.text)


def test_medium_quotient_order_by_cosets():
    for seed in range(60):
        question = sup.q(TOPIC, "medium", seed)
        m, n, a, b = _numbers(question.text)
        assert int(question.answer) == _quotient(m, n, a, b)[1], (seed, question.text)


def test_hard_counts_elements_killed_by_k():
    for seed in range(80):
        question = sup.q(TOPIC, "hard", seed)
        m, n, a, b = _numbers(question.text)
        k = int(re.search(r"(\d+)(?:g|\(g \+ H\))", question.text).group(1))
        coset_of, size, exponent, _ = _quotient(m, n, a, b)
        killed = {coset_of[g] for g in coset_of if coset_of[((k * g[0]) % m, (k * g[1]) % n)] == (0, 0)}
        assert int(question.answer) == len(killed), (seed, question.text)
        assert len(killed) != math.gcd(k, size), (seed, "the answer must differ from the cyclic guess")


