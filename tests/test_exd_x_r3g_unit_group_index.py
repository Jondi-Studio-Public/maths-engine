"""Tests for the multi-part exam source `exd_x_r3g_unit_group_index` (units mod n: |G|, |H|, index, outside)."""

from __future__ import annotations

import math
import re

from tests import exd_x_r3g_support as sup

TOPIC = "exd_x_r3g_unit_group_index"
SKILL = "ucv1-finite-subgroup-test"


def _facts(q):
    n = int(re.search(r"(?:modulo |Z/)(\d+)", q.text).group(1))
    g = int(re.search(r"(?:generated by |⟨|element )(\d+)", q.text).group(1))
    return n, g


def _derive(q):
    """Brute force: list the units, then multiply g by itself until the product returns to 1."""
    n, g = _facts(q)
    units = [u for u in range(1, n) if math.gcd(u, n) == 1]
    seen, value = [], g % n
    while value not in seen:
        seen.append(value)
        value = value * g % n
    assert value == 1 or 1 in seen
    subgroup = set(seen)
    assert 1 in subgroup and all(x * y % n in subgroup for x in subgroup for y in subgroup)
    return len(units), len(subgroup), len(units) // len(subgroup), len(units) - len(subgroup)


