def test_follow_through_from_wrong_orders():
    def replies(q):
        pairs = [
            (int(da), int(db))
            for da in q.parts[0].distractors
            for db in q.parts[1].distractors
            if int(db) > 1 and int(da) % int(db) == 0 and int(da) // int(db) > 1 and int(da) != int(db)
        ]
        if not pairs:
            return None
        a, b = pairs[0]
        replies_ = {"a": str(a), "b": str(b), "c": str(a // b), "d": str(a - b)}
        if len(set(replies_.values())) < 4:
            return None
        return replies_, {"c", "d"}, {"a", "b"}

    sup.check_follow_through(SKILL, TOPIC, replies, n=300, at_least=5)


def test_follow_through_from_a_wrong_order_of_the_subgroup_only():
    def replies(q):
        size, order, index, outside = _derive(q)
        wrong = int(q.parts[1].distractors[0])
        if size % wrong:
            return None
        return {**sup.canonical(q), "b": str(wrong), "c": str(size // wrong), "d": str(size - wrong)}, {"c", "d"}, {"b"}

    sup.check_follow_through(SKILL, TOPIC, replies, n=300, at_least=5)
