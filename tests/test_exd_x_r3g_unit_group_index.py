def test_keys_match_independent_derivation_over_300_seeds():
    bad = []
    for q in sup.questions(TOPIC):
        want = dict(zip("abcd", map(str, _derive(q))))
        if sup.canonical(q) != want:
            bad.append((q.text, sup.canonical(q), want))
    assert bad == [], bad[:2]


def test_the_subgroup_is_proper_and_non_trivial():
    for q in sup.questions(TOPIC, 100):
        size, order, index, outside = _derive(q)
        assert order >= 3 and index >= 2 and size == order * index


