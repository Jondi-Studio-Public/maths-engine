def test_exam_keys_are_recomputed_from_the_text():
    for seed in range(150):
        question = sup.exam(TOPIC, seed)
        n = int(re.search(r"Z_(\d+)", question.stem).group(1))
        h = int(re.search(r"⟨(\d+)⟩", question.stem).group(1))
        subgroup = _additive_subgroup(n, h)
        a, b, c, d = question.parts
        b0 = int(re.search(r"coset (\d+) \+ H", c.prompt).group(1))
        coset = sorted((b0 + x) % n for x in subgroup)
        assert int(a.answer) == len(subgroup)
        assert int(b.answer) == n // len(subgroup) == len({min((x + y) % n for y in subgroup) for x in range(n)})
        assert int(c.answer) == coset[0]
        assert d.answer == coset


def test_exam_follow_through_for_the_index():
    def replies(question):
        return {p.label: p.answer_text for p in question.parts} | {"a": str(int(question.parts[0].answer) + 1)}

    def expected(question, sent):
        n = int(re.search(r"Z_(\d+)", question.stem).group(1))
        wrong = int(sent["a"])
        return None if n % wrong else str(n // wrong)

    from mathgen.engine import grade

    s = sup.skill(SKILL_ID)
    checked = 0
    for seed in range(80):
        question = sup.exam(TOPIC, seed)
        sent = replies(question)
        value = expected(question, sent)
        if value is None or value == question.parts[1].answer_text:
            continue
        result = grade(s, question, sent | {"b": value})
        assert result.parts["b"].marks == 1 and result.parts["b"].follow_through is True, (seed, sent, value)
        checked += 1
    assert checked >= 15
