"""Tests `uc2-cosets-and-index`: each coset is rebuilt from the question TEXT (sums modulo n, products modulo n, and
SymPy permutations for S_4), the typed set grader on every key and distractor, and the four-part exam chain."""

from __future__ import annotations

import re
from math import gcd

from sympy.combinatorics import Permutation

import mathgen.generators.r4a_cosets_and_index_build  # noqa: F401  (registers the topics)
from tests import r4a_support as sup

TOPIC = "r4a_cosets_and_index"
SKILL_ID = "uc2-cosets-and-index"


def _additive_subgroup(n, h):
    return sorted({(k * h) % n for k in range(n)})


def _multiplicative_subgroup(n, h):
    return sorted({pow(h, k, n) for k in range(n)})


def test_wiring():
    sup.check_wiring(SKILL_ID, TOPIC, "set")


def test_easy_key_is_the_additive_coset():
    for seed in range(100):
        question = sup.q(TOPIC, "easy", seed)
        n = int(re.search(r"Z_(\d+)", question.text).group(1))
        h = int(re.search(r"⟨(\d+)⟩", question.text).group(1))
        a = int(re.search(r"coset (\d+) \+ H", question.text).group(1))
        subgroup = _additive_subgroup(n, h)
        assert 3 <= len(subgroup) < n
        assert question.answer == sorted((a + x) % n for x in subgroup), (seed, question.text)
        assert a % n not in subgroup


def test_medium_key_is_the_multiplicative_coset():
    for seed in range(100):
        question = sup.q(TOPIC, "medium", seed)
        n = int(re.search(r"units of Z_(\d+)", question.text).group(1))
        h = int(re.search(r"⟨(\d+)⟩", question.text).group(1))
        g = int(re.search(r"coset (\d+)H", question.text).group(1))
        assert gcd(h, n) == gcd(g, n) == 1
        subgroup = _multiplicative_subgroup(n, h)
        assert question.answer == sorted((g * x) % n for x in subgroup), (seed, question.text)
        assert g not in subgroup


def test_hard_key_is_the_left_coset_with_sympy():
    for seed in range(100):
        question = sup.q(TOPIC, "hard", seed)
        written = re.search(r"generated by ((?:\([\d ]+\))+) and", question.text).group(1)
        cycles = [[int(v) - 1 for v in chunk.split()] for chunk in re.findall(r"\(([\d ]+)\)", written)]
        g = Permutation([int(v) - 1 for v in re.search(r"g = \(([\d, ]+)\)", question.text).group(1).split(",")])
        gen = Permutation(cycles, size=4)
        subgroup = [gen**k for k in range(gen.order())]
        # SymPy multiplies left to right (p*q applies p first), so "g after h" is h*g
        left = sorted(tuple(v + 1 for v in (h * g).array_form) for h in subgroup)
        right = sorted(tuple(v + 1 for v in (g * h).array_form) for h in subgroup)
        assert sorted(tuple(x) for x in question.answer) == left, (seed, question.text)
        assert left != right


