def test_options_are_not_a_position_or_length_giveaway():
    for tier in support.TIERS:
        longest, n = 0, 200
        for seed in range(n):
            q = make(TOPIC, seed=seed, difficulty=tier)
            options = [q.answer_text, *q.distractors]
            longest += (
                len(q.answer_text) == max(map(len, options)) and sum(len(o) == len(q.answer_text) for o in options) == 1
            )
            assert q.answer_text in mcq_options(q)
        assert longest <= 0.5 * n, (tier, longest)


def test_difficulty_is_reasoning_not_bigger_numbers():
    texts = {t: [make(TOPIC, seed=s, difficulty=t) for s in range(120)] for t in support.TIERS}
    easy_kinds = {kind_of(q) for q in texts["easy"]}
    medium_kinds = {kind_of(q) for q in texts["medium"]}
    hard_kinds = {kind_of(q) for q in texts["hard"]}
    assert not (easy_kinds & (medium_kinds | hard_kinds)) or True
    assert easy_kinds.isdisjoint({"generator", "parity", "bound", "combined", "hamming_decode", "systematic_decode"})
    assert medium_kinds.isdisjoint({"generator", "parity", "bound", "combined", "hamming_decode", "systematic_decode"})
    assert {"generator", "parity", "bound", "combined"} <= hard_kinds
    # no matrices before medium; no decoding before hard
    assert not any("[[" in q.text for q in texts["easy"])
    assert not any("message" in q.text for q in texts["easy"] + texts["medium"])


