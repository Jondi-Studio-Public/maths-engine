def test_exam_keys_match_independent_derivation():
    distances = Counter()
    for seed in range(120):
        q = make(EXAM, seed=seed, difficulty="exam")
        (g,) = matrices(q.stem)
        k, n = len(g), len(g[0])
        words = rows_to_words(g)
        assert [g[i][:k] for i in range(k)] == [[int(i == j) for j in range(k)] for i in range(k)]
        assert int(q.parts[0].answer_text) == len(words) == 2**k
        assert Fraction(q.parts[1].answer_text) == Fraction(k, n)
        d = min_pair_distance(words)
        distances[d] += 1
        assert int(q.parts[2].answer_text) == d == min(sum(w) for w in words if any(w))
        assert int(q.parts[3].answer_text) == (d - 1) // 2 == correctable(words, n)
        (h,) = matrices(q.parts[4].prompt)
        r = bits(re.search(r"r = ([01]+)", q.parts[4].prompt).group(1))
        assert len(words) == len(kernel_words(h))
        best, near = nearest(words, r)
        assert best == 1 and len(near) == 1
        assert decimal(near[0][:k]) == int(q.parts[4].answer_text)
    assert len(distances) >= 2, distances


