def test_easy_conjugates_in_the_dihedral_group():
    for seed in range(60):
        question = sup.q(TOPIC, "easy", seed)
        n = int(re.search(r"D_(\d+)", question.text).group(1))
        d = re.search(r"H = ⟨r\^(\d+), s⟩", question.text)
        d = int(d.group(1)) if d else n
        r = Permutation(list(range(1, n)) + [0])
        s = Permutation([(-i) % n for i in range(n)])
        group = list(PermutationGroup([r, s]).generate())
        h = frozenset(PermutationGroup([r**d, s]).generate())
        assert len(group) == 2 * n
        assert int(question.answer) == len({frozenset(g**-1 * x * g for x in h) for g in group}), (seed, question.text)


def test_medium_conjugates_in_s4():
    for seed in range(60):
        question = sup.q(TOPIC, "medium", seed)
        _, conjugates, _ = _facts(_generators(question.text, 4), 4)
        assert int(question.answer) == conjugates, (seed, question.text)


def test_hard_normaliser_in_s5():
    for seed in range(40):
        question = sup.q(TOPIC, "hard", seed)
        h, conjugates, normaliser = _facts(_generators(question.text, 5), 5)
        assert int(question.answer) == normaliser == 120 // conjugates, (seed, question.text)
        assert normaliser % len(h) == 0


