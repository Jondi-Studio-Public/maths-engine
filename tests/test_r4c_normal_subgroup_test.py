def test_exam_keys_are_recomputed_from_the_text():
    for seed in range(40):
        question = sup.exam(TOPIC, seed)
        h, conjugates, normaliser = _facts(_generators(question.stem, 5), 5)
        a, b, c = (int(p.answer) for p in question.parts)
        assert (a, b, c) == (len(h), normaliser, conjugates), (seed, question.stem)
        assert conjugates > 1


def test_exam_follow_through_for_the_conjugate_count():
    s = sup.skill(SKILL_ID)
    checked = 0
    for seed in range(40):
        question = sup.exam(TOPIC, seed)
        wrong = int(question.parts[1].answer) * 2
        if 120 % wrong:
            continue
        sent = {p.label: p.answer_text for p in question.parts} | {"b": str(wrong), "c": str(120 // wrong)}
        result = grade(s, question, sent)
        assert result.parts["c"].marks == 2 and result.parts["c"].follow_through is True, (seed, sent)
        checked += 1
    assert checked >= 10
