"""Tests `uc2-normal-subgroup-test`: conjugate counts and normaliser orders are redone with SymPy permutations from the
generators written in the question text; plus the contract checks every skill gets."""

from __future__ import annotations

import re
from functools import lru_cache

from sympy.combinatorics import Permutation, PermutationGroup

import mathgen.generators.r4c_normal_subgroup_test_build  # noqa: F401  (registers the topics)
from mathgen.engine import grade
from tests import r4c_support as sup

TOPIC = "r4c_normal_subgroup_test"
SKILL_ID = "uc2-normal-subgroup-test"


def _generators(text, n):
    segment = re.search(r"(?:generated by |H = ⟨)((?:\([\d ]+\))+(?:, (?:\([\d ]+\))+)*)", text).group(1)
    gens = []
    for chunk in segment.split(", "):
        cycles = [[int(v) - 1 for v in c.split()] for c in re.findall(r"\(([\d ]+)\)", chunk)]
        gens.append(Permutation(cycles, size=n))
    return gens


@lru_cache(maxsize=None)
def _symmetric(n):
    return list(
        PermutationGroup([Permutation(list(range(1, n)) + [0]), Permutation([1, 0] + list(range(2, n)))]).generate()
    )


def _facts(gens, n):
    h = frozenset(PermutationGroup(gens).generate())
    conjugates, normaliser = set(), 0
    for g in _symmetric(n):
        image = frozenset(g**-1 * x * g for x in h)
        conjugates.add(image)
        normaliser += image == h
    return h, len(conjugates), normaliser


