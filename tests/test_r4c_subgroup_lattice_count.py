def test_easy_counts_subgroups_of_z_n_containing_the_generator():
    for seed in range(60):
        question = sup.q(TOPIC, "easy", seed)
        n = int(re.search(r"Z_(\d+)", question.text).group(1))
        k = int(re.search(r"⟨(\d+)⟩", question.text).group(1))
        subgroups = {frozenset(range(0, n, d)) for d in range(1, n + 1) if n % d == 0}
        held = frozenset((k * j) % n for j in range(n))
        assert int(question.answer) == sum(1 for h in subgroups if held <= h), (seed, question.text)


def test_medium_counts_dihedral_subgroups_of_the_order():
    for seed in range(40):
        question = sup.q(TOPIC, "medium", seed)
        n = int(re.search(r"D_(\d+)", question.text).group(1))
        k = int(re.search(r"(?:subgroups of order|have order) (\d+)", question.text).group(1))
        assert int(question.answer) == sum(1 for h in _dihedral_subgroups(n) if len(h) == k), (seed, question.text)


def test_hard_counts_subgroups_of_the_product():
    seen = set()
    for seed in range(80):
        question = sup.q(TOPIC, "hard", seed)
        m, n = (int(v) for v in re.search(r"Z_(\d+) × Z_(\d+)", question.text).groups())
        seen.add((m, n))
        assert int(question.answer) == len(_product_subgroups(m, n)), (seed, question.text)
    assert len(seen) >= 8


