def _subgroups(elements, mul, identity):
    """All subgroups of a finite group generated by at most two elements (enough for these groups)."""

    def close(gens):
        out, frontier = {identity}, [identity]
        while frontier:
            x = frontier.pop()
            for g in gens:
                y = mul(x, g)
                if y not in out:
                    out.add(y)
                    frontier.append(y)
        return frozenset(out)

    cyclic = {}
    for a in elements:
        cyclic.setdefault(close([a]), a)
    found = set(cyclic)
    for a in cyclic.values():
        for b in cyclic.values():
            found.add(close([a, b]))
    return found


@lru_cache(maxsize=None)
def _dihedral(n):
    # element (i, f): the map x -> (-1)^f x + i of Z_n; composition (i, f) after (j, g)
    elements = [(i, f) for i in range(n) for f in (0, 1)]

    def mul(a, b):
        (i, f), (j, g) = a, b
        return ((i + (-1) ** f * j) % n, (f + g) % 2)

    return elements, mul


@lru_cache(maxsize=None)
def _dihedral_subgroups(n):
    elements, mul = _dihedral(n)
    return _subgroups(elements, mul, (0, 0))


@lru_cache(maxsize=None)
def _product_subgroups(m, n):
    elements = list(product(range(m), range(n)))
    return _subgroups(elements, lambda a, b: ((a[0] + b[0]) % m, (a[1] + b[1]) % n), (0, 0))


def _is_normal(h, n):
    elements, mul = _dihedral(n)

    def inv(x):
        return next(y for y in elements if mul(x, y) == (0, 0))

    return all(mul(mul(g, x), inv(g)) in h for g in elements for x in h)


