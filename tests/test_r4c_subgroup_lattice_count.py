def test_exam_counts_by_brute_force():
    for seed in range(40):
        question = sup.exam(TOPIC, seed)
        n = int(re.search(r"D_(\d+)", question.stem).group(1))
        subgroups = _dihedral_subgroups(n)
        rotations = {(i, 0) for i in range(n)}
        a, b, c, d = (int(p.answer) for p in question.parts)
        assert a == sum(1 for h in subgroups if h <= rotations)
        assert b == sum(1 for h in subgroups if not h <= rotations)
        assert c == len(subgroups)
        assert d == sum(1 for h in subgroups if _is_normal(h, n)), (seed, n)


def test_exam_follow_through_for_the_total():
    def replies(question):
        return {p.label: p.answer_text for p in question.parts} | {"a": str(int(question.parts[0].answer) + 2)}

    def expected(question, sent):
        return str(int(sent["a"]) + int(sent["b"]))

    s = sup.skill(SKILL_ID)
    checked = 0
    for seed in range(40):
        question = sup.exam(TOPIC, seed)
        sent = replies(question)
        result = grade(s, question, sent | {"c": expected(question, sent)})
        assert result.parts["c"].marks == 1 and result.parts["c"].follow_through is True, (seed, sent)
        checked += 1
    assert checked == 40
