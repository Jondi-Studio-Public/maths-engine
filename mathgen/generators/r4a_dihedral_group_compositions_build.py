"""Generates `r4a_dihedral_group_compositions` questions (easy, medium, hard) and the exam chain
`exd_x_r4a_dihedral_group_compositions`.

``uc2-dihedral-group-compositions`` (``abstract-algebra``, answer ``ordered_list``): products in the dihedral group D_n of
order 2n, generated by a rotation r (r^n = e) and a reflection s (s² = e) with s r = r^(-1) s. Every element is r^i s^j
with 0 ≤ i < n and j in {0, 1}, so the answer is the pair [i, j], the one normal form the ordered-list grader compares.

* easy: the product of two elements in normal form, the first of which is a reflection (so s has to be moved past r^c).
* medium: a word of five to six factors, each r^k or s, reduced to normal form.
* hard: a conjugate g x g⁻¹ with g a rotation and x a reflection, or a commutator x y x⁻¹ y⁻¹ of two general elements.
* exam: two reflections x = r^a s and y = r^b s: (a) the product xy in normal form, (b) its order, (c) the index of
  ⟨xy⟩ in D_n (follows through from (b)), (d) the order of the commutator x y x⁻¹ y⁻¹ (follows through from (b)).

Each key is computed from the rule r^a s^b · r^c s^d = r^(a + (-1)^b c) s^(b + d) and checked against the same product of
permutations of the vertices of the n-gon (r: x → x + 1, s: x → -x, composed right to left), which is a second route.
"""

from __future__ import annotations

from math import gcd

from ..core import attempts, check, generator, phrase
from ._r4a_alg_kit import number_part, pair_options, pair_part, plain_latex


class _D:
    """An element r^i s^j of D_n."""

    def __init__(self, n, i, j):
        self.n, self.i, self.j = n, i % n, j % 2

    def __mul__(self, other):
        n = self.n
        return _D(n, self.i + (-1) ** self.j * other.i, self.j + other.j)

    def inverse(self):
        return _D(self.n, -self.i, 0) if self.j == 0 else _D(self.n, self.i, 1)

    def key(self):
        return [self.i, self.j]

    def as_map(self):
        """The element as a permutation of Z_n (tuple of images): s^j then r^i, composed right to left."""
        n = self.n
        return tuple((self.i + (-x if self.j else x)) % n for x in range(n))


def _compose_maps(f, g):
    return tuple(f[g[x]] for x in range(len(g)))


def _gen_map(n, kind):
    return tuple((x + 1) % n for x in range(n)) if kind == "r" else tuple((-x) % n for x in range(n))


def _word_map(n, word):
    """The permutation of a word in 'r' and 's' (rightmost letter acts first)."""
    out = tuple(range(n))
    for letter in reversed(word):
        out = _compose_maps(_gen_map(n, letter), out)
    return out


def elem_text(e):
    parts = []
    if e.i:
        parts.append("r" if e.i == 1 else f"r^{e.i}")
    if e.j:
        parts.append("s")
    return " ".join(parts) if parts else "e"


def _factor_text(e):
    return elem_text(e)


def _pair_text(i, j):
    return f"({i}, {j})"


_CONVENTION = "Write the answer in the form r^i s^j with 0 ≤ i < {n} and j = 0 or 1, and give it as the pair (i, j)."
_SETUP = (
    "In the dihedral group D_{n} of order {m}, r is a rotation with r^{n} = e, s is a reflection with s^2 = e, and "
    "s r = r^(-1) s. "
)


def _setup(n):
    return _SETUP.format(n=n, m=2 * n)


def _conv(n):
    return _CONVENTION.format(n=n)


def _check_against_maps(n, left, right, product):
    check(
        _compose_maps(left.as_map(), right.as_map()) == product.as_map(),
        "the product differs from the product of the vertex permutations",
    )


_EASY_STEMS = (
    "{setup}Find the product ({x})({y}). {conv}",
    "{setup}Simplify ({x})({y}). {conv}",
)


def _easy(rng):
    for _ in attempts(500, "two elements whose product shows the reflection rule"):
        n = rng.randint(5, 12)
        x = _D(n, rng.randrange(1, n), 1)
        y = _D(n, rng.randrange(1, n), rng.randrange(2))
        z = x * y
        naive = (x.i + y.i) % n
        if z.i != naive and (y * x).key() != z.key() and z.key() != x.key() and z.key() != y.key():
            break
    _check_against_maps(n, x, y, z)
    cands = [
        ([naive, (x.j + y.j) % 2], "dihedral-reflection-not-moved-past-rotation"),
        ((y * x).key(), "dihedral-product-order-reversed"),
        ([(-x.i + y.i) % n, (x.j + y.j) % 2], "dihedral-sign-flip-on-wrong-factor"),
        ([z.i, (z.j + 1) % 2], "dihedral-reflection-count-wrong"),
    ]
    options = pair_options(z.key(), cands, 3)
    return dict(
        text=phrase(rng, _EASY_STEMS, setup=_setup(n), x=_factor_text(x), y=_factor_text(y), conv=_conv(n)),
        answer_kind="ordered_list",
        answer=z.key(),
        answer_text=_pair_text(*z.key()),
        working=[
            f"s r^k = r^(-k) s, so ({elem_text(x)})({elem_text(y)}) = r^({x.i} {'-' if x.j else '+'} {y.i}) s^({x.j} + {y.j}).",
            f"Reducing modulo {n} and 2 gives r^{z.i} s^{z.j}.",
        ],
        distractors=options,
    )


_MED_STEMS = (
    "{setup}Simplify the word {word}. {conv}",
    "{setup}Reduce the product {word} to a single element. {conv}",
)


def _medium(rng):
    for _ in attempts(1000, "a word that reduces to something other than its naive exponent count"):
        n = rng.randint(5, 11)
        length = rng.randint(5, 6)
        factors = []
        for _ in range(length):
            factors.append("s" if rng.random() < 0.45 else f"r{rng.randrange(1, n)}")
        if sum(1 for f in factors if f == "s") < 2 or any(a == b == "s" for a, b in zip(factors, factors[1:])):
            continue
        value = _D(n, 0, 0)
        for f in factors:
            value = value * (_D(n, 0, 1) if f == "s" else _D(n, int(f[1:]), 0))
        naive_i = sum(int(f[1:]) for f in factors if f != "s") % n
        naive_j = sum(1 for f in factors if f == "s") % 2
        if value.i != naive_i:
            break
    letters = "".join("s" if f == "s" else "r" * int(f[1:]) for f in factors)
    check(_word_map(n, letters).__eq__(value.as_map()), "the word differs from the product of vertex permutations")
    word = " ".join("s" if f == "s" else f"r^{f[1:]}" for f in factors)
    # a learner who reads the word right to left
    back = _D(n, 0, 0)
    for f in reversed(factors):
        back = back * (_D(n, 0, 1) if f == "s" else _D(n, int(f[1:]), 0))
    cands = [
        ([naive_i, naive_j], "dihedral-reflection-not-moved-past-rotation"),
        (back.key(), "dihedral-product-order-reversed"),
        ([value.i, (value.j + 1) % 2], "dihedral-reflection-count-wrong"),
        ([(-value.i) % n, value.j], "dihedral-sign-flip-on-wrong-factor"),
    ]
    options = pair_options(value.key(), cands, 3)
    steps, run = [], _D(n, 0, 0)
    for f in factors:
        run = run * (_D(n, 0, 1) if f == "s" else _D(n, int(f[1:]), 0))
        steps.append(elem_text(run))
    return dict(
        text=phrase(rng, _MED_STEMS, setup=_setup(n), word=word, conv=_conv(n)),
        answer_kind="ordered_list",
        answer=value.key(),
        answer_text=_pair_text(*value.key()),
        working=[
            "Multiply from the left, moving each s to the right with s r^k = r^(-k) s: " + " → ".join(steps) + "."
        ],
        distractors=options,
    )


_HARD_CONJ = (
    "{setup}Find g x g^(-1), where g = {g} and x = {x}. {conv}",
    "{setup}Compute the conjugate of x = {x} by g = {g}, that is g x g^(-1). {conv}",
)
_HARD_COMM = (
    "{setup}Find the commutator x y x^(-1) y^(-1) where x = {x} and y = {y}. {conv}",
    "{setup}Compute x y x^(-1) y^(-1) for x = {x} and y = {y}. {conv}",
)


def _hard(rng):
    if rng.random() < 0.5:
        for _ in attempts(500, "a rotation conjugating a reflection"):
            n = rng.randint(5, 12)
            g = _D(n, rng.randrange(1, n), 0)
            x = _D(n, rng.randrange(n), 1)
            z = g * x * g.inverse()
            if z.key() != x.key() and (g.inverse() * x * g).key() != z.key():
                break
        _check_against_maps(n, g * x, g.inverse(), z)
        cands = [
            (x.key(), "dihedral-assumes-conjugation-fixes-element"),
            ((g.inverse() * x * g).key(), "dihedral-conjugation-by-inverse"),
            ([(g.i + x.i) % n, 1], "dihedral-reflection-not-moved-past-rotation"),
            ([(-z.i) % n, 1], "dihedral-sign-flip-on-wrong-factor"),
        ]
        return dict(
            text=phrase(rng, _HARD_CONJ, setup=_setup(n), g=elem_text(g), x=elem_text(x), conv=_conv(n)),
            answer_kind="ordered_list",
            answer=z.key(),
            answer_text=_pair_text(*z.key()),
            working=[
                f"g^(-1) = {elem_text(g.inverse())}. Moving the reflection through the rotation, g x g^(-1) = r^({g.i}) (r^{x.i} s) r^(-{g.i}) = r^{z.i} s.",
            ],
            distractors=pair_options(z.key(), cands, 3),
        )
    for _ in attempts(1000, "two elements that do not commute"):
        n = rng.randint(5, 12)
        x = _D(n, rng.randrange(n), rng.randrange(2))
        y = _D(n, rng.randrange(n), rng.randrange(2))
        z = x * y * x.inverse() * y.inverse()
        if (
            (x * y).key() != (y * x).key()
            and z.key() != [0, 0]
            and (x * y * y.inverse() * x.inverse()).key() != z.key()
        ):
            break
    check(
        _compose_maps(_compose_maps(x.as_map(), y.as_map()), _compose_maps(x.inverse().as_map(), y.inverse().as_map()))
        == z.as_map(),
        "commutator differs from vertex permutations",
    )
    cands = [
        ([0, 0], "dihedral-assumes-elements-commute"),
        ((x * y).key(), "dihedral-commutator-stops-at-product"),
        ((x * y * x * y).key(), "dihedral-inverse-taken-as-self"),
        ([(-z.i) % n, z.j], "dihedral-sign-flip-on-wrong-factor"),
    ]
    return dict(
        text=phrase(rng, _HARD_COMM, setup=_setup(n), x=elem_text(x), y=elem_text(y), conv=_conv(n)),
        answer_kind="ordered_list",
        answer=z.key(),
        answer_text=_pair_text(*z.key()),
        working=[
            f"x^(-1) = {elem_text(x.inverse())} and y^(-1) = {elem_text(y.inverse())}.",
            f"Multiplying out and reducing gives r^{z.i} s^{z.j}.",
        ],
        distractors=pair_options(z.key(), cands, 3),
    )


@generator(
    "r4a_dihedral_group_compositions",
    level=19,
    presets={"easy": dict(tier="easy"), "medium": dict(tier="medium"), "hard": dict(tier="hard")},
)
@plain_latex
def r4a_dihedral_group_compositions(rng, tier="easy"):
    """Products in a dihedral group; the tiers are described in the module docstring."""
    if tier == "easy":
        return _easy(rng)
    if tier == "medium":
        return _medium(rng)
    check(tier == "hard", f"unknown tier {tier!r}")
    return _hard(rng)


