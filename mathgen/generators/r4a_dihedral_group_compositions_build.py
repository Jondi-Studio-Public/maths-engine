@generator("exd_x_r4a_dihedral_group_compositions", level=19, presets={"exam": dict(tier="exam")})
@plain_latex
def exd_x_r4a_dihedral_group_compositions(rng, tier="exam"):
    """Exam chain: the product of two reflections, its order, the index of its subgroup and its commutator's order."""
    check(tier == "exam", f"unknown tier {tier!r}")
    for _ in attempts(1000, "two reflections whose product has a non-trivial order"):
        n = rng.choice([8, 9, 10, 12, 14, 15, 16, 18])
        x = _D(n, rng.randrange(n), 1)
        y = _D(n, rng.randrange(n), 1)
        p = x * y
        o = n // gcd(n, p.i) if p.i else 1
        comm = x * y * x.inverse() * y.inverse()
        oc = n // gcd(n, comm.i) if comm.i else 1
        if p.i and o >= 3 and oc >= 2 and 2 * n // o != 2:
            break
    _check_against_maps(n, x, y, p)
    check(p.j == 0 and comm.j == 0, "a product of two reflections should be a rotation")
    order_by_powers = next(k for k in range(1, 2 * n + 1) if (_D(n, p.i * k, 0)).i == 0)
    check(order_by_powers == o, "order of the rotation differs from repeated multiplication")
    comm_order = next(k for k in range(1, 2 * n + 1) if (_D(n, comm.i * k, 0)).i == 0)
    check(comm_order == oc and comm.key() == [(2 * p.i) % n, 0], "the commutator should be the square of xy")
    index = 2 * n // o
    return dict(
        text=(_setup(n) + f"Let x = {elem_text(x)} and y = {elem_text(y)}, and let H be the subgroup generated by xy."),
        parts=[
            pair_part(
                f"Find xy. {_conv(n)}",
                p.key(),
                2,
                [f"xy = r^{x.i} s r^{y.i} s = r^{x.i} r^(-{y.i}) s s = r^{p.i}."],
                [
                    ([(x.i + y.i) % n, 0], "dihedral-reflection-not-moved-past-rotation"),
                    ((y * x).key(), "dihedral-product-order-reversed"),
                    ([p.i, 1], "dihedral-reflection-count-wrong"),
                    ([(y.i - x.i) % n, 0], "dihedral-product-order-reversed"),
                ],
            ),
            number_part(
                "Find the order of xy.",
                o,
                2,
                [f"xy = r^{p.i} has order {n}/gcd({n}, {p.i}) = {o}."],
                [
                    (p.i, "dihedral-order-read-as-exponent"),
                    (n, "dihedral-order-of-rotation-taken-as-n"),
                    (2, None),
                    (n // gcd(n, p.i) * 2, None),
                ],
                sensible_range=(0, None),
            ),
            number_part(
                "Find the index of H in D_%d." % n,
                index,
                2,
                [f"|D_{n}| = {2 * n} and |H| = {o}, so the index is {2 * n}/{o} = {index}."],
                [
                    (o, "index-confused-with-subgroup-order"),
                    (2 * n, "index-of-trivial-subgroup-confusion"),
                    (n // o, "dihedral-index-uses-n-not-2n"),
                ],
                follow_through=f"{2 * n}/part_b",
                sensible_range=(0, None),
            ),
            number_part(
                "Find the order of the commutator x y x^(-1) y^(-1).",
                oc,
                3,
                [
                    "x^(-1) = x and y^(-1) = y, so the commutator is xyxy = (xy)^2.",
                    f"(xy)^2 has order {o}/gcd({o}, 2) = {oc}.",
                ],
                [
                    (o, "dihedral-commutator-order-as-product-order"),
                    (1, "dihedral-assumes-elements-commute"),
                    (2, None),
                    (o * 2, None),
                ],
                follow_through="part_b/(2 - (part_b - 2*floor(part_b/2)))",
                sensible_range=(0, None),
            ),
        ],
    )
