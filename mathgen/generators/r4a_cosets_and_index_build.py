"""Generates `r4a_cosets_and_index` questions (easy, medium, hard) and the exam chain `exd_x_r4a_cosets_and_index`.

``uc2-cosets-and-index`` (``abstract-algebra``, answer ``set``): list the elements of a coset and use cosets to find an
index. The answer is the set of elements of the coset, so the order they are typed in does not matter.

* easy: in the additive group Z_n, the coset a + H of the subgroup H = ⟨h⟩ where h is not the smallest generator of H
  (for example ⟨30⟩ in Z_36), so H must be identified before the coset can be listed.
* medium: in the group of units of Z_n under multiplication, the coset gH of the subgroup H = ⟨h⟩.
* hard: in S_4, with permutations composed right to left, the left coset gH of a cyclic subgroup H, chosen so that the
  right coset Hg is a different set; elements are typed in one-line notation, for example (2, 1, 3, 4).
* exam: in Z_N with H = ⟨h⟩: (a) the order of H, (b) the index of H (follows through from (a)), (c) the least
  non-negative element of the coset b + H, (d) the coset b + H as a set.

Each coset is found by forming every product (or sum) a∘x for x in H, and checked against the congruence description of
the coset (additive case) or against the partition of the group into cosets (units and S_4): every element lies in
exactly one coset and all cosets have the order of H.
"""

from __future__ import annotations

from math import gcd

from ..core import attempts, check, generator
from ..grading.typed import set_answer_text
from ._r4a_alg_kit import compose, cycles, identity, number_part, product_text, set_part, struct_options, with_latex

_CONVENTION_NUMBERS = "Give the coset as a set of residues in the range given, for example {1, 7, 13}."


def _span_additive(n, h):
    out, x = [], 0
    for _ in range(n):  # the multiples of h return to 0 within n steps
        out.append(x)
        x = (x + h) % n
        if x == 0:
            break
    return sorted(out)


def _opts(key, candidates, keep=3):
    value = sorted(key)
    text = set_answer_text(value)
    cands = [(sorted(v), tag) for v, tag in candidates if v is not None and sorted(v) != value]
    return struct_options("set", value, text, cands, set_answer_text, keep)


def _set_question(text, key, working, candidates):
    value = sorted(key)
    options = _opts(key, candidates)
    check(len(options) >= 2, "too few distractors")
    return dict(
        text=text,
        answer_kind="set",
        answer=value,
        answer_text=set_answer_text(value),
        working=working,
        distractors=options,
    )


def _easy(rng):
    for _ in attempts(500, "a subgroup of Z_n not given by its smallest generator"):
        n = rng.choice([12, 18, 20, 24, 28, 30, 36, 40, 42, 45, 48])
        d = rng.choice([x for x in range(2, n // 2 + 1) if n % x == 0 and 3 <= n // x <= 9])
        h = rng.choice([k * d for k in range(2, n // d) if gcd(k, n // d) == 1])
        a = rng.randrange(1, n)
        if a % d == 0:
            continue
        break
    big_h = _span_additive(n, h)
    check(big_h == [x for x in range(n) if x % d == 0], "the subgroup differs from the multiples of the gcd")
    key = sorted((a + x) % n for x in big_h)
    check(key == [x for x in range(n) if x % d == a % d], "the coset differs from its congruence description")
    index = n // d
    cands = [
        (sorted((a * x) % n for x in big_h), "coset-multiplied-not-added"),
        ([x for x in range(n) if x % index == a % index], "coset-modulus-index-confusion"),
        (sorted((-a + x) % n for x in big_h), "coset-representative-sign-slip"),
        (key[:-1], "coset-element-missing"),
        (sorted((a + 1 + x) % n for x in big_h), "coset-representative-off-by-one"),
        (sorted((a - 1 + x) % n for x in big_h), "coset-representative-off-by-one"),
    ]
    setup, ask = rng.choice(
        [
            (
                f"In the group Z_{n} under addition modulo {n}, let H = ⟨{h}⟩ be the subgroup generated by {h}. ",
                f"List the elements of the coset {a} + H, as residues from 0 to {n - 1}.",
            ),
            (
                f"Let H = ⟨{h}⟩ be the subgroup of Z_{n} (addition modulo {n}) generated by {h}. ",
                f"Write out the coset {a} + H as a set of residues from 0 to {n - 1}.",
            ),
            (
                f"The integers modulo {n}, Z_{n}, form a group under addition, and H = ⟨{h}⟩ is the subgroup generated by {h}. ",
                f"Which residues from 0 to {n - 1} make up the coset {a} + H?",
            ),
        ]
    )
    stem = f"{setup}{ask} {_CONVENTION_NUMBERS}"
    return _set_question(
        stem,
        key,
        [
            f"H is generated by gcd({h}, {n}) = {d}, so H = {{multiples of {d}}} and has {len(big_h)} elements.",
            f"{a} + H is every residue congruent to {a % d} modulo {d}: {set_answer_text(key)}.",
        ],
        cands,
    )


def _units(n):
    return [x for x in range(1, n) if gcd(x, n) == 1]


def _span_mult(n, h):
    out, x = [], 1
    for _ in range(n):  # powers of a unit return to 1 within n steps
        out.append(x)
        x = (x * h) % n
        if x == 1:
            break
    return sorted(out)


def _medium(rng):
    for _ in attempts(500, "a proper subgroup of a unit group with a coset away from it"):
        n = rng.choice([15, 16, 20, 21, 24, 28, 30, 35, 36, 40, 45])
        units = _units(n)
        h = rng.choice([u for u in units if u != 1])
        big_h = _span_mult(n, h)
        if not 2 <= len(big_h) <= len(units) // 2:
            continue
        g = rng.choice([u for u in units if u not in big_h])
        key = sorted((g * x) % n for x in big_h)
        inv = pow(g, -1, n)
        other = sorted((inv * x) % n for x in big_h)
        if other == key or len(big_h) < 3:
            continue
        break
    # the cosets of H partition the units, each with |H| elements
    cosets = {tuple(sorted((u * x) % n for x in big_h)) for u in units}
    check(sorted(x for c in cosets for x in c) == units, "the cosets do not partition the unit group")
    check(all(len(c) == len(big_h) for c in cosets), "a coset has the wrong size")
    cands = [
        (sorted((g + x) % n for x in big_h), "coset-computed-with-addition"),
        (other, "coset-inverse-representative"),
        (big_h, "coset-is-the-subgroup-itself"),
        (key[1:], "coset-element-missing"),
        (
            next(
                (
                    sorted((u * x) % n for x in big_h)
                    for u in units
                    if u not in big_h and u != g and sorted((u * x) % n for x in big_h) != key
                ),
                None,
            ),
            "coset-of-wrong-representative",
        ),
    ]
    stem = rng.choice(
        [
            f"The units of Z_{n} form a group G under multiplication modulo {n}. Let H = ⟨{h}⟩ be the subgroup of G "
            f"generated by {h}. List the elements of the coset {g}H = {{{g}x : x in H}}, as residues from 1 to {n - 1}. "
            f"{_CONVENTION_NUMBERS}",
            f"Under multiplication modulo {n}, the units of Z_{n} form a group G, and H = ⟨{h}⟩ is the subgroup of G "
            f"generated by {h}. Write out the coset {g}H = {{{g}x : x in H}} as residues from 1 to {n - 1}. {_CONVENTION_NUMBERS}",
            f"Let G be the group of units of Z_{n} under multiplication modulo {n}, with H = ⟨{h}⟩ ≤ G. Which residues "
            f"from 1 to {n - 1} make up the coset {g}H = {{{g}x : x in H}}? {_CONVENTION_NUMBERS}",
        ]
    )
    return _set_question(
        stem,
        key,
        [
            f"H = {set_answer_text(big_h)}, from the powers of {h} modulo {n}.",
            f"Multiplying each element of H by {g} modulo {n} gives {set_answer_text(key)}.",
        ],
        cands,
    )


def _s4_generators():
    """Every non-identity permutation of {1, 2, 3, 4} with its cycle notation as text, "(1 2)(3 4)"."""
    from itertools import permutations

    out = []
    for p in permutations(range(1, 5)):
        p = tuple(p)
        if p != identity(4):
            out.append((p, product_text(cycles(p))))
    return out


_S4_SUBGROUPS = _s4_generators()


def _span_perm(gen):
    out, x = [identity(len(gen))], gen
    while x != identity(len(gen)):
        out.append(x)
        x = compose(gen, x)
    return out


def _all_perms4():
    from itertools import permutations

    return [tuple(p) for p in permutations(range(1, 5))]


def _tuple_text(p):
    return "(" + ", ".join(map(str, p)) + ")"


def _hard(rng):
    for _ in attempts(500, "a non-normal cyclic subgroup of S_4 and an element with gH != Hg"):
        gen, gen_text = rng.choice(_S4_SUBGROUPS)
        big_h = _span_perm(gen)
        g = rng.choice(_all_perms4())
        left = sorted(compose(g, h) for h in big_h)
        right = sorted(compose(h, g) for h in big_h)
        if g in big_h or left == right:
            continue
        break
    # all left cosets of H partition S_4 into sets of the order of H
    cosets = {tuple(sorted(compose(x, h) for h in big_h)) for x in _all_perms4()}
    check(sorted(p for c in cosets for p in c) == sorted(_all_perms4()), "the left cosets do not partition S_4")
    check(len(cosets) * len(big_h) == 24, "index times order is not 24")
    value = [list(p) for p in left]
    inv_g = tuple(sorted(range(1, 5), key=lambda i: g[i - 1]))
    cands = [
        ([list(p) for p in right], "coset-left-right-swapped"),
        ([list(p) for p in sorted(compose(inv_g, h) for h in big_h)], "coset-inverse-representative"),
        ([list(p) for p in sorted(compose(h, h2) for h in big_h[:1] for h2 in big_h)], "coset-is-the-subgroup-itself"),
        ([list(p) for p in left[1:]], "coset-element-missing"),
    ]
    text = set_answer_text(value)
    options = struct_options("set", value, text, [(v, t) for v, t in cands if v is not None], set_answer_text, 3)
    check(len(options) >= 2, "too few distractors")
    stem = (
        f"In S_4, permutations are composed right to left and written in one-line notation, by their images of 1, 2, 3, 4. "
        f"Let H be the subgroup generated by {gen_text} and let g = {_tuple_text(g)}. List the elements of the left coset "
        f"gH = {{g∘h : h in H}} in one-line notation, for example {{(2, 1, 3, 4), (1, 2, 3, 4)}}."
    )
    return dict(
        text=stem,
        answer_kind="set",
        answer=value,
        answer_text=text,
        working=[
            f"H = {set_answer_text([list(p) for p in big_h])}.",
            f"Apply h first and then g for each h in H: gH = {text}. The right coset Hg is a different set.",
        ],
        distractors=options,
    )


@generator(
    "r4a_cosets_and_index",
    level=19,
    presets={"easy": dict(tier="easy"), "medium": dict(tier="medium"), "hard": dict(tier="hard")},
)
@with_latex
def r4a_cosets_and_index(rng, tier="easy"):
    """Cosets of a subgroup; the tiers are described in the module docstring."""
    if tier == "easy":
        return _easy(rng)
    if tier == "medium":
        return _medium(rng)
    check(tier == "hard", f"unknown tier {tier!r}")
    return _hard(rng)


