@generator("exd_x_r4a_cosets_and_index", level=19, presets={"exam": dict(tier="exam")})
@with_latex
def exd_x_r4a_cosets_and_index(rng, tier="exam"):
    """Exam chain: order, index and a coset of H = ⟨h⟩ in Z_N."""
    check(tier == "exam", f"unknown tier {tier!r}")
    for _ in attempts(500, "a subgroup of Z_N of order 4 to 8 not given by its smallest generator"):
        n = rng.choice([24, 30, 36, 40, 42, 45, 48, 54, 56, 60])
        d = rng.choice([x for x in range(2, n // 2 + 1) if n % x == 0 and 4 <= n // x <= 8])
        h = rng.choice([k * d for k in range(2, n // d) if gcd(k, n // d) == 1])
        b = rng.randrange(n // 2, n)
        if b % d == 0 or b < n // 2:
            continue
        break
    big_h = _span_additive(n, h)
    order_h, index = len(big_h), n // len(big_h)
    check(order_h == n // gcd(n, h) and index == d, "order or index differs from the gcd formula")
    coset = sorted((b + x) % n for x in big_h)
    least = min(coset)
    check(least == b % d, "the least element differs from the residue modulo the gcd")
    check(len(set(coset)) == order_h, "the coset has the wrong size")
    other = lambda v: sorted(v)
    return dict(
        text=rng.choice(
            [
                f"In the group Z_{n} under addition modulo {n}, let H = ⟨{h}⟩ be the subgroup generated by {h}.",
                f"Let H = ⟨{h}⟩ be the subgroup of Z_{n} (addition modulo {n}) generated by {h}.",
                f"The integers modulo {n}, Z_{n}, form a group under addition, and H = ⟨{h}⟩ is the subgroup generated by {h}.",
            ]
        ),
        parts=[
            number_part(
                "Find the order of H.",
                order_h,
                2,
                [f"The order of {h} in Z_{n} is {n}/gcd({n}, {h}) = {n}/{gcd(n, h)} = {order_h}."],
                [
                    (gcd(n, h), "subgroup-order-read-as-gcd"),
                    (n, "coset-order-of-group-for-subgroup"),
                    (n // h if n % h == 0 else None, None),
                    (order_h + 1, None),
                ],
                sensible_range=(0, None),
            ),
            number_part(
                "Find the index [Z_%d : H]." % n,
                index,
                1,
                [f"By Lagrange, the index is {n}/{order_h} = {index}."],
                [
                    (order_h, "index-confused-with-subgroup-order"),
                    (n, "index-of-trivial-subgroup-confusion"),
                    (n - order_h, None),
                    (index + 1, None),
                ],
                follow_through=f"{n}/part_a",
                sensible_range=(0, None),
            ),
            number_part(
                f"Find the least non-negative integer in the coset {b} + H.",
                least,
                2,
                [f"{b} + H is every residue congruent to {b % d} modulo {d}; the least is {least}."],
                [
                    (b, "coset-representative-not-reduced"),
                    (d - least, "coset-least-element-negated"),
                    (b % index if index else None, "coset-modulus-index-confusion"),
                    (n - b, None),
                    (least + d, None),
                    (n - least, None),
                ],
                sensible_range=(0, None),
            ),
            set_part(
                f"List the elements of the coset {b} + H, as residues from 0 to {n - 1}. {_CONVENTION_NUMBERS}",
                coset,
                3,
                [
                    f"Adding {b} to each of the {order_h} elements of H = {set_answer_text(big_h)} modulo {n} gives {set_answer_text(coset)}."
                ],
                [
                    (sorted((b * x) % n for x in big_h), "coset-multiplied-not-added"),
                    (big_h, "coset-is-the-subgroup-itself"),
                    ([x for x in range(n) if x % index == b % index], "coset-modulus-index-confusion"),
                    (sorted((-b + x) % n for x in big_h), "coset-representative-sign-slip"),
                    (sorted((b + 1 + x) % n for x in big_h), "coset-representative-off-by-one"),
                ],
            ),
        ],
    )
