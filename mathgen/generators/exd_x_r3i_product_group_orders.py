"""Exam-tier source for `ucv1-isomorphism-invariant`: element orders in Z_m x Z_n decide whether it is cyclic.

The stem gives G = Z_m x Z_n (componentwise addition) and a student's claim that G is isomorphic to the cyclic group
Z_N with N = mn. The parts compute the invariants a marker would use to test the claim and end on a number that
carries the verdict:

(a) the order |G| = mn                                         number, 1 mark
(b) the order of a named element (p, q)                        number, 2 marks
(c) the largest order of any element of G, lcm(m, n)           number, 2 marks
(d) the index in G of the cyclic subgroup generated by an element of that largest order   number, 2 marks,
    part_a / part_c

The claim fails exactly when the index in (d) exceeds 1, that is when gcd(m, n) > 1. Every draw has gcd(m, n) > 1: in a
cyclic G the largest element order equals |G|, so (c) would repeat (a) and hand the learner a mark.

## Construction

m and n are drawn from 2..30 with |G| at most 500 and a common factor (so the claim is always false). The named element is not the identity and does not itself have
the largest order, so (b) and (c) are different computations. All four answers are whole numbers.
"""

from __future__ import annotations

import math
from fractions import Fraction

from ..core import attempts, check, generator, phrase
from ._exd_x_r3_distinct import distinct_answers
from .exd_x_r3i_support import number_part


def _lcm(a: int, b: int) -> int:
    return a * b // math.gcd(a, b)


@generator("exd_x_r3i_product_group_orders", level=18, presets={"exam": dict(tier="exam")})
@distinct_answers
def exd_x_r3i_product_group_orders(rng, tier: str = "exam") -> dict:
    """|G|, the order of an element, the largest element order and the cyclic subgroup's index in Z_m x Z_n."""
    check(tier == "exam", f"unknown tier {tier!r}")
    for _ in attempts(2000, "a product group with a mid-order element"):
        if rng.random() < 0.7:  # most draws share a factor, so the claim is usually false
            g = rng.choice([2, 2, 3, 4, 5, 6])
            m, n = g * rng.randint(1, 6), g * rng.randint(1, 6)
        else:
            m, n = rng.randint(2, 30), rng.randint(2, 30)
        if m < 2 or n < 2:
            continue
        p, q = rng.randint(0, m - 1), rng.randint(0, n - 1)
        if m * n > 500 or m * n < 12 or (p, q) == (0, 0):
            continue
        om, on = m // math.gcd(p, m), n // math.gcd(q, n)
        order = _lcm(om, on)
        top = _lcm(m, n)
        if order == top or order == 1 or top == m * n:
            continue  # a cyclic G would make (c) equal (a): two parts with one answer
        if len({om * on, max(om, on), om + on, top} - {order}) < 2:
            continue  # part (b) needs two distractors that differ from the key
        break
    size = m * n
    index = size // top
    # Independent routes: the order by repeated addition, the index as gcd(m, n).
    k, ap, aq = 1, p % m, q % n
    while (ap, aq) != (0, 0):
        ap, aq, k = (ap + p) % m, (aq + q) % n, k + 1
    check(k == order, "order disagrees with repeated addition")
    check(index == math.gcd(m, n) and size % top == 0, "index disagrees with gcd(m, n)")

    stem = phrase(
        rng,
        (
            "Let G = Z_{m} x Z_{n}, with addition done componentwise (the first coordinate modulo {m}, the second "
            "modulo {n}). A student claims that G is isomorphic to the cyclic group Z_{N}.",
            "The group G = Z_{m} x Z_{n} is formed under componentwise addition modulo {m} and modulo {n}. A student "
            "claims that G is isomorphic to Z_{N}, the cyclic group of order {N}.",
            "Two students discuss G = Z_{m} x Z_{n}, where elements are added coordinate by coordinate (mod {m} in "
            "the first, mod {n} in the second). One says G has the same structure as the cyclic group Z_{N}.",
        ),
        m=m,
        n=n,
        N=size,
    )
    part_a = number_part(
        "Find the order of G.",
        Fraction(size),
        0,
        1,
        [f"|G| = {m} × {n} = {size}."],
        [
            ("added-instead-of-multiplied", Fraction(m + n)),
            ("group-order-as-lcm", Fraction(top)),
            ("group-order-as-larger-factor", Fraction(max(m, n))),
        ],
        sensible_range=(0, None),
    )
    part_b = number_part(
        f"Find the order of the element ({p}, {q}) in G.",
        Fraction(order),
        0,
        2,
        [
            f"The order of {p} in Z_{m} is {om} and the order of {q} in Z_{n} is {on}; the element has order lcm({om}, {on}) = {order}."
        ],
        [
            ("element-order-not-lcm", Fraction(om * on)),
            ("element-order-not-lcm", Fraction(max(om, on))),
            ("element-order-not-lcm", Fraction(om + on)),
            ("element-order-is-group-exponent", Fraction(top)),
        ],
        sensible_range=(0, None),
    )
    part_c = number_part(
        "Find the largest order of any element of G.",
        Fraction(top),
        0,
        2,
        [f"The largest order is lcm({m}, {n}) = {top}."],
        [
            ("largest-order-is-group-order", Fraction(size)),
            ("element-order-not-lcm", Fraction(max(m, n))),
            ("element-order-not-lcm", Fraction(math.gcd(m, n))),
            ("largest-order-is-order-of-named-element", Fraction(order)),
        ],
        sensible_range=(0, None),
    )
    part_d = number_part(
        "Hence find the index in G of the cyclic subgroup generated by an element of the largest order found in (c).",
        Fraction(index),
        0,
        2,
        [f"The subgroup has {top} elements, so its index in G is {size} ÷ {top} = {index}."],
        [
            ("index-confused-with-subgroup-order", Fraction(top)),
            ("index-of-trivial-subgroup-confusion", Fraction(size)),
            ("index-as-smaller-modulus", Fraction(min(m, n))),
            ("index-zero-for-whole-group", Fraction(0)),
            ("off-by-one-count", Fraction(index + 1)),
        ],
        follow_through="part_a/part_c",
        sensible_range=(0, None),
    )
    return dict(text=stem, parts=[part_a, part_b, part_c, part_d])
