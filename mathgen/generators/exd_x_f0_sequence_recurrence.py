"""Exam-tier source for `generate-sequence-from-rule`: a sequence whose terms are not an explicit function of
the position.

  first_order  -- t(1) = a and t(n+1) = p * t(n) + q; reach t(k) by repeated application.
  second_order -- t(1) = a, t(2) = b and t(n+2) = p * t(n+1) + q * t(n); each term needs the previous two.
  partial_sums -- only the sum of the first n terms, S(n) = a n^2 + b n, is given; the k-th term is the
                  difference S(k) - S(k-1). The rule for a single term is never stated.

Terms are generated by a simple forward loop for the key and cross-checked by a second route (the
closed form for the first-order case, the two-point difference for the sums, a matrix power for the
second-order case).
"""

from __future__ import annotations

import random

from sympy import Matrix

from ..core import check, generator, join_terms, pick_distractors


def _signed(rng: random.Random, lo: int, hi: int) -> int:
    return rng.choice([-1, 1]) * rng.randint(lo, hi)


def _pack(text: str, value: int, label: str, working: list[str], wrong: list[int]) -> dict:
    answer_text = str(value)
    return dict(
        text=text,
        latex=f"plain:{text}",
        answer=value,
        answer_text=answer_text,
        answer_latex=answer_text,
        working=working,
        distractors=pick_distractors(answer_text, [str(w) for w in wrong]),
    )


def _step(prev: int, p: int, q: int) -> int:
    return p * prev + q


def _first_order(rng: random.Random) -> dict:
    for _ in range(200):
        a = rng.randint(-5, 6)
        p = rng.choice([2, 3, -2, -3])
        q = _signed(rng, 1, 7)
        k = rng.randint(4, 6)
        terms = [a]
        for _i in range(k - 1):
            terms.append(_step(terms[-1], p, q))
        value = terms[-1]
        too_early, too_late = terms[-2], _step(value, p, q)
        multiplied_only = a * p ** (k - 1)  # drops the constant at every step
        add_first = a  # applies "add q, then multiply by p"
        for _i in range(k - 1):
            add_first = p * (add_first + q)
        if len({value, too_early, too_late, multiplied_only, add_first}) == 5 and abs(value) < 2000:
            break
    else:
        check(False, "no usable first-order recurrence")
    # Second route: closed form t(k) = p^(k-1) (a + q/(p-1)) - q/(p-1), in exact rational arithmetic.
    from fractions import Fraction

    fixed = Fraction(q, 1 - p)
    check((a - fixed) * p ** (k - 1) + fixed == value, "closed form disagrees with the iterated terms")
    rule = join_terms([(p, "t(n)"), (q, "")])
    text = f"A sequence is defined by t(1) = {a} and t(n + 1) = {rule} for every n ≥ 1. Find t({k})."
    working = [f"t({i + 1}) = {t}" for i, t in enumerate(terms)]
    return _pack(text, value, f"t({k})", working, [multiplied_only, add_first, too_early, too_late])


def _second_order(rng: random.Random) -> dict:
    for _ in range(300):
        a, b = rng.randint(-3, 4), rng.randint(-3, 4)
        p = rng.choice([1, 2, -1])
        q = rng.choice([1, 2, 3, -1, -2])
        k = rng.randint(5, 7)
        terms = [a, b]
        for _i in range(k - 2):
            terms.append(p * terms[-1] + q * terms[-2])
        value = terms[-1]
        # swapped roles of the two coefficients
        swapped = [a, b]
        for _i in range(k - 2):
            swapped.append(q * swapped[-1] + p * swapped[-2])
        # uses only the previous term (forgets the one before)
        single = [a, b]
        for _i in range(k - 2):
            single.append(p * single[-1])
        too_early, too_late = terms[-2], p * value + q * terms[-2]
        if len({value, swapped[-1], single[-1], too_early, too_late}) == 5 and abs(value) < 2000 and a != b:
            break
    else:
        check(False, "no usable second-order recurrence")
    # Second route: the companion matrix applied to (t(2), t(1)).
    state = Matrix([[p, q], [1, 0]]) ** (k - 2) * Matrix([b, a])
    check(state[0] == value, "matrix power disagrees with the iterated terms")
    rule = join_terms([(p, "t(n + 1)"), (q, "t(n)")])
    text = f"A sequence has t(1) = {a}, t(2) = {b} and t(n + 2) = {rule} for every n ≥ 1. Find t({k})."
    working = [f"t({i + 1}) = {t}" for i, t in enumerate(terms)]
    return _pack(text, value, f"t({k})", working, [swapped[-1], single[-1], too_early, too_late])


def _partial_sums(rng: random.Random) -> dict:
    for _ in range(200):
        a = rng.randint(1, 5)
        b = rng.randint(-6, 6)
        k = rng.randint(4, 9)

        def s(n):
            return a * n * n + b * n

        value = s(k) - s(k - 1)
        wrong = [s(k), s(k + 1) - s(k), s(k) - s(k - 2), s(k - 1)]
        if len({value, *wrong}) == 5:
            break
    else:
        check(False, "no usable partial-sum question")
    check(value == 2 * a * k - a + b, "difference of sums disagrees with the closed form")
    text = (
        f"The sum of the first n terms of a sequence is S(n) = {join_terms([(a, 'n^2'), (b, 'n')])}. "
        f"Find the {_ordinal(k)} term of the sequence."
    )
    working = [f"t({k}) = S({k}) - S({k - 1}) = {s(k)} - {s(k - 1)} = {value}."]
    return _pack(text, value, f"t({k})", working, wrong)


def _ordinal(n: int) -> str:
    if 10 <= n % 100 <= 13:
        return f"{n}th"
    return f"{n}" + {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")


@generator(
    "exd_x_f0_sequence_recurrence",
    level=10,
    presets={
        "easy": dict(tier="exam"),
        "medium": dict(tier="exam"),
        "hard": dict(tier="exam"),
        "exam": dict(tier="exam"),
    },
)
def exd_x_f0_sequence_recurrence(rng: random.Random, tier: str = "exam") -> dict:
    check(tier == "exam", "this topic only builds the exam tier")
    return rng.choice([_first_order, _second_order, _partial_sums])(rng)
