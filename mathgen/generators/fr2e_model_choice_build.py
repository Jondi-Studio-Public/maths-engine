def _ctx(rng, bank):
    text, unit_x, unit_y, limit, bound = rng.choice(bank)
    return dict(text=text, ux=unit_x, uy=unit_y, limit=limit, bound=bound)


def _lin(rng, xs, up: bool | None = None) -> Model:
    up = rng.random() < 0.5 if up is None else up
    m = rng.choice((2, 3, 4, 5, 6, 7, 8))
    if up:
        c = rng.randint(3, 25)
        return Model("lin", Integer(m) * x + c, xs, _ctx(rng, _LINEAR_UP), True)
    c = rng.randint(m * max(xs) + 10, m * max(xs) + 60)
    return Model("lin", -Integer(m) * x + c, xs, _ctx(rng, _LINEAR_DOWN), False)


def _quad(rng, xs, up: bool | None = None) -> Model:
    up = rng.random() < 0.5 if up is None else up
    if up:
        a, b, c = rng.choice((1, 2, 3)), rng.randint(0, 4), rng.randint(1, 9)
        return Model("quad", a * x**2 + b * x + c, xs, _ctx(rng, _QUAD_UP), True)
    a = -rng.choice((1, 2))
    top = max(xs)
    b = rng.randint(-a * top + 2, -a * top + 8) * 1  # the apex sits beyond the table, so y keeps rising
    c = rng.randint(1, 6)
    model = Model("quad", a * x**2 + b * x + c, xs, _ctx(rng, _QUAD_DOWN), False)
    if min(model.ys) <= 0:
        raise Redraw("the thrown object must stay above ground in the table")
    return model


def _exp(rng, xs, up: bool | None = None) -> Model:
    up = rng.random() < 0.5 if up is None else up
    if up:
        r = rng.choice((2, 3))
        A = rng.choice((2, 3, 4, 5) if r == 3 else (2, 3, 5, 6, 8, 10))
        return Model("exp", A * Integer(r) ** x, xs, _ctx(rng, _EXP_UP), True)
    A = rng.choice((160, 320, 480, 640)) if len(xs) <= 6 else rng.choice((512, 1024))
    return Model("exp", A * Rational(1, 2) ** x, xs, _ctx(rng, _EXP_DOWN), False)


# -- the three tests, run on a table -------------------------------------------------------------------------------


def first_diffs(ys):
    return [b - a for a, b in zip(ys, ys[1:])]


def constant(values) -> bool:
    return len(set(values)) == 1


_MODEL_WORD = {"lin": "linear", "quad": "quadratic", "exp": "exponential"}


def classify(ys) -> str:
    """The one model whose test the table passes, by first differences, second differences and ratios."""
    d1 = first_diffs(ys)
    d2 = first_diffs(d1)
    passes = []
    if constant(d1):
        passes.append("lin")
    if constant(d2) and not constant(d1):
        passes.append("quad")
    if all(y != 0 for y in ys) and constant([Fraction(b, a) for a, b in zip(ys, ys[1:])]) and not constant(d1):
        passes.append("exp")
    check(len(passes) == 1, "exactly one test must pass for every table")
    return passes[0]


_MODEL_NAMES = {"lin": "linear", "quad": "quadratic", "exp": "exponential"}


def _times(q: Fraction) -> str:
    if q == Fraction(1, 2):
        return "half the one before"
    if q.denominator == 1:
        return f"{q.numerator} times the one before"
    return f"{q.numerator}/{q.denominator} of the one before"


def _up_down(d: int, step: int = 1) -> str:
    unit = "1" if step == 1 else str(step)
    return (
        f"y goes up by {d} each time x goes up by {unit}"
        if d > 0
        else f"y goes down by {-d} each time x goes up by {unit}"
    )


def claims(model: Model):
    """(key text, [(wrong text, misconception)]) for the four statements about a table with step 1 in x."""
    ys = model.ys
    d1 = first_diffs(ys)
    d2 = first_diffs(d1)
    lin_claim = lambda d: f"Linear: {_up_down(d)}"  # noqa: E731
    quad_claim = lambda s: f"Quadratic: the second differences are all {s}"  # noqa: E731
    exp_claim = lambda q: f"Exponential: each y-value is {_times(q)}"  # noqa: E731
    q_first = Fraction(ys[1], ys[0])
    q_all = Fraction(ys[-1], ys[0])
    texts = {
        "lin": (lin_claim(d1[0]), lin_claim(ys[-1] - ys[0]), E_FIRST_PAIR, E_TOTAL_AS_STEP),
        "quad": (
            quad_claim(d2[0]) if model.kind == "quad" else quad_claim(d1[0]),
            quad_claim(d1[0]),
            E_FIRST_AS_SECOND,
            E_FIRST_AS_SECOND,
        ),
        "exp": (exp_claim(q_first), exp_claim(q_all), E_FIRST_PAIR, E_OVERALL_RATIO),
    }
    key = {
        "lin": lin_claim(d1[0]),
        "quad": quad_claim(d2[0]),
        "exp": exp_claim(q_first),
    }[model.kind]
    wrong = []
    for kind in ("lin", "quad", "exp"):
        if kind == model.kind:
            continue
        wrong.append((texts[kind][0], texts[kind][2]))
    same_kind_wrong = texts[model.kind][1]
    wrong.append((same_kind_wrong, texts[model.kind][3]))
    return key, wrong


def holds(text: str, ys) -> bool:
    """Whether a statement from `claims` is true of the table `ys`, re-derived from its text alone."""
    kind, _, rest = text.partition(": ")
    d1 = first_diffs(ys)
    d2 = first_diffs(d1)
    if kind == "Linear":
        return constant(d1) and _up_down(d1[0]) == rest
    if kind == "Quadratic":
        return constant(d2) and rest == f"the second differences are all {d2[0]}"
    ratios = [Fraction(b, a) for a, b in zip(ys, ys[1:])]
    return constant(ratios) and rest == f"each y-value is {_times(ratios[0])}"


# -- parts ---------------------------------------------------------------------------------------------------------


def _choose_part(model: Model, marks: int, wrong_extra=()) -> dict:
    key, wrong = claims(model)
    check(model.kind == classify(model.ys), "the model drawn must be the one the tests find")
    wrong = [(t, tag) for t, tag in wrong if t != key]
    if any(holds(t, model.ys) for t, _ in wrong):
        raise Redraw("a wrong statement is also true of this table")
    check(holds(key, model.ys), "the key statement must be true of the table")
    d1 = first_diffs(model.ys)
    return mcq_part(
        "Which statement about the table is true?",
        key,
        wrong,
        marks,
        [
            f"First differences: {', '.join(str(v) for v in d1)}.",
            f"Second differences: {', '.join(str(v) for v in first_diffs(d1))}.",
            "Ratios of each y-value to the one before: "
            + ", ".join(str(Fraction(b, a)) for a, b in zip(model.ys, model.ys[1:]))
            + ".",
            key + ".",
        ],
    )


def _lin_rule_wrongs(model: Model):
    ys = model.ys
    d1 = first_diffs(ys)
    wrong = [
        (Integer(d1[0]) * x + ys[0], E_LINEAR_FOR_ANY),
        (Integer(d1[0]) * x, E_NO_INTERCEPT),
    ]
    return wrong


def rule_wrongs(model: Model):
    """Wrong rules from named errors, for any model."""
    ys = model.ys
    d1 = first_diffs(ys)
    d2 = first_diffs(d1)
    y0 = ys[0]
    out = []
    if model.kind != "lin":
        out.append((Integer(d1[0]) * x + y0, E_LINEAR_FOR_ANY))
    if model.kind == "quad":
        a = Rational(d2[0], 2)
        b = Rational(d1[0]) - a
        out.append((Integer(d2[0]) * x**2 + b * x + y0, E_NOT_HALVED))
        out.append((a * x**2 + b * x, E_NO_INTERCEPT))
        out.append((a * x**2 + Integer(d1[0]) * x + y0, "fr2e-model-first-difference-used-as-linear-coefficient"))
    elif model.kind == "exp":
        q = Rational(ys[1], ys[0])
        out.append((Integer(y0) * x ** sympy.Integer(q.p if q.q == 1 else 2), E_POWER_FOR_EXP))
        out.append((q * x, E_NO_INTERCEPT))
        out.append((Integer(y0) + (q if q.q == 1 else Rational(1, 2)) * x, "fr2e-model-ratio-added-not-multiplied"))
    else:
        out.append((Integer(d1[0]) * x, E_NO_INTERCEPT))
        out.append((Integer(d1[0]) + y0 * x, "fr2e-model-slope-and-start-swapped"))
        out.append((Integer(y0) * Integer(d1[0]) ** x, E_POWER_FOR_EXP))
        out.append((Integer(d1[0]) * x + Integer(ys[-1]), "fr2e-model-last-value-used-as-start"))
    return out


def _rule_part(model: Model, marks: int, working_pre=()) -> dict:
    ys, d1 = model.ys, first_diffs(model.ys)
    steps = list(working_pre)
    if model.kind == "lin":
        steps += [f"First differences are all {d1[0]}, so the slope is {d1[0]} and y = {d1[0]}x + {ys[0]}."]
    elif model.kind == "quad":
        d2 = first_diffs(d1)[0]
        steps += [
            f"Second differences are all {d2}, so a = {Fraction(d2, 2)}.",
            f"c = {ys[0]} and a + b + c = {ys[1]} give b = {ys[1] - ys[0] - Fraction(d2, 2)}.",
        ]
    else:
        steps += [f"Each y-value is {_times(Fraction(ys[1], ys[0]))}, so y = {ys[0]} × {Fraction(ys[1], ys[0])}^x."]
    part = expression_part(
        "Write a rule for y in terms of x that fits every value in the table.",
        model.rule,
        marks,
        steps,
        rule_wrongs(model),
        prefix="y = ",
    )
    # An independent check: the rule must reproduce the table.
    check(all(model.at(v) == y for v, y in zip(model.xs, ys)), "the rule must give every table value")
    return part


def _stem(model: Model) -> str:
    return f"{model.context['text']} {model.table_text()}."


# -- tiers ---------------------------------------------------------------------------------------------------------

_XS = [0, 1, 2, 3, 4]


def _easy(rng):
    model = rng.choice((_lin, _quad, _exp))(rng, _XS)
    return single(_stem(model), _choose_part(model, 1))


def _rule_choice_part(model: Model, marks: int) -> dict:
    """Which rule fits the whole table? The key and rules from named errors, each written `y = ...`."""
    from .exd_x_r2b_support import same_function

    key = "y = " + rule_text(model.rule)
    wrong = []
    for expr, tag in rule_wrongs(model):
        misses = any(sympy.Rational(expr.subs(x, v)) != y for v, y in zip(model.xs, model.ys))
        if misses and not same_function(expr, model.rule):
            wrong.append(("y = " + rule_text(expr), tag))
    check(all(model.at(v) == y for v, y in zip(model.xs, model.ys)), "the key rule must give every table value")
    ys, d1 = model.ys, first_diffs(model.ys)
    working = {
        "lin": [f"First differences are all {d1[0]}, so the slope is {d1[0]}.", f"The rule is {key}."],
        "quad": [
            f"Second differences are all {first_diffs(d1)[0]}, so the rule is a quadratic.",
            f"The rule is {key}.",
        ],
        "exp": [
            f"Each y-value is {_times(Fraction(ys[1], ys[0]))}, so the rule is exponential.",
            f"The rule is {key}.",
        ],
    }[model.kind]
    return mcq_part("Which rule fits every value in the table?", key, wrong, marks, working)


def _medium(rng):
    model = rng.choice((_lin, _quad, _exp))(rng, _XS)
    return single(_stem(model), _rule_choice_part(model, 1))


def _hard(rng):
    step = rng.choice((2, 3))
    xs = [step * i for i in range(5)]
    kind = rng.choice(("lin", "quad", "exp"))
    if kind == "lin":
        model = _lin(rng, xs)
    elif kind == "quad":
        model = _quad(rng, xs, up=True)
    else:
        model = _exp(rng, xs, up=True)
    if kind == "exp" and model.grow and step == 3 and max(model.ys) > 40000:
        raise Redraw("too large")
    N = rng.choice([v for v in range(xs[-1] + 1, xs[-1] + 5) if v % step])
    target = model.at(N)
    if target.denominator != 1 or not 0 < target < 100000:
        raise Redraw("the predicted value must be a modest whole number")
    ys = model.ys
    d1 = first_diffs(ys)
    last_slope = Fraction(d1[-1], step)
    y_last, x_last = ys[-1], xs[-1]
    wrong = [
        (y_last + last_slope * (N - x_last), E_LINEAR_EXTRAP),
        (model.at(N - 1), E_X_OFF),
        (model.at(N + 1), E_X_OFF),
    ]
    if model.kind == "lin":
        wrong.append((ys[0] + d1[0] * N, E_STEP_IGNORED))
    elif model.kind == "exp":
        ratio = Fraction(ys[1], ys[0])
        wrong.append((Fraction(ys[0]) * ratio**N, E_RATIO_PER_ROW))
    else:
        wrong.append((Fraction(ys[0]) + d1[0] * N, E_STEP_IGNORED))
    stem = _stem(model) + f" The pattern in the table continues, and x goes up by {step} from one row to the next."
    key_text = str(int(target))
    wrong_text = []
    for v, tag in wrong:
        v = Fraction(v)
        if v.denominator == 1 and 0 <= v < 30 * target and str(int(v)) != key_text:
            wrong_text.append((str(int(v)), tag))
    part = mcq_part(
        f"Which is the value of y when x = {N}?",
        key_text,
        wrong_text,
        1,
        [
            f"The model is {_MODEL_NAMES[classify(ys)]} (checked using differences per row of {step} in x).",
            f"Rule: y = {rule_text(model.rule)}.",
            f"At x = {N}, y = {target}.",
        ],
    )
    return single(stem, part)


# -- exam ----------------------------------------------------------------------------------------------------------


def _limit(model: Model, rng):
    """(below, bound, sentence, first): the physical limit and the first whole x that breaks it, found by two routes."""
    ctx = model.context
    below = ctx["bound"] is not None
    bound = ctx["bound"] if below else int(model.ys[-1] * rng.choice((6, 8, 10, 12)))
    text = ctx["limit"].format(b=bound)
    first = next(v for v in range(0, 400) if (model.at(v) < bound if below else model.at(v) > bound))
    # second route: the value just before is allowed and the value at `first` is not
    check(first > model.xs[-1], "the limit must be reached beyond the table")
    check(
        not (model.at(first - 1) < bound if below else model.at(first - 1) > bound), "the value before must be allowed"
    )
    return below, bound, text, first


def _exam(rng):
    kind = rng.choice(("lin", "quad", "exp"))
    model = {"lin": _lin, "quad": _quad, "exp": _exp}[kind](rng, _XS)
    below, bound, limit_text, first = _limit(model, rng)
    if first > 60:
        raise Redraw("limit too far away")
    N = rng.choice(range(first - 3, first - 1)) if first > 7 else rng.choice((6, 7))
    N = max(N, 6)
    if N >= first:
        raise Redraw("the predicted x should be inside the model's sensible range")
    ux, uy = model.context["ux"], model.context["uy"]
    stem = _stem(model)
    part_a = _choose_part(model, 2)
    part_b = _rule_part(model, 3)
    target = model.at(N)
    if target.denominator != 1:
        raise Redraw("whole predicted value")
    ys = model.ys
    d1 = first_diffs(ys)
    ft = f"Subs(part_b, (x,), ({N},))"
    part_c = exact_number_part(
        f"Use your rule to find y when x = {N}.",
        target,
        2,
        [f"y = {rule_text(model.rule)} at x = {N} gives {target}."],
        [
            (ys[-1] + Fraction(d1[-1]) * (N - 4), E_LINEAR_EXTRAP),
            (model.at(N - 1), E_X_OFF),
            (model.at(N + 1), E_X_OFF),
            (model.at(N) + (model.at(N) - model.at(N - 1)), "fr2e-model-extra-step-added"),
        ],
        suffix="",
        follow_through=ft,
        sensible_range=(0, None) if all(v >= 0 for v in ys) else None,
    )
    ask = f"{limit_text} Find the first whole number of {ux} at which the rule gives a value that breaks this limit."
    part_d = exact_number_part(
        ask,
        first,
        2,
        [
            f"Checking whole values: at x = {first - 1} the rule gives {model.at(first - 1)}, which is allowed.",
            f"At x = {first} it gives {model.at(first)}, which breaks the limit.",
        ],
        [
            (first - 1, E_BOUNDARY_LOW),
            (first + 1, E_BOUNDARY_HIGH),
            (bound, E_LIMIT_AS_X),
            (5, E_TABLE_END),
            (first + 2, E_BOUNDARY_HIGH),
        ],
        suffix="",
    )
    return dict(text=stem, parts=[part_a, part_b, part_c, part_d])


