x = Symbol("x")

E_FIRST_AS_SECOND = "fr2e-model-first-difference-read-as-second"
E_FIRST_PAIR = "fr2e-model-first-pair-only-checked"
E_TOTAL_AS_STEP = "fr2e-model-total-change-as-step"
E_OVERALL_RATIO = "fr2e-model-overall-ratio-as-ratio"
E_LINEAR_FOR_ANY = "fr2e-model-first-difference-used-for-any-model"
E_NOT_HALVED = "fr2e-model-second-difference-not-halved"
E_POWER_FOR_EXP = "fr2e-model-power-for-exponential"
E_NO_INTERCEPT = "fr2e-model-starting-value-left-out"
E_LINEAR_EXTRAP = "fr2e-model-linear-extrapolation-of-curve"
E_STEP_IGNORED = "fr2e-model-step-in-x-ignored"
E_RATIO_PER_ROW = "fr2e-model-ratio-per-row-used-per-unit"
E_X_OFF = "fr2e-model-x-off-by-one"
E_BOUNDARY_LOW = "fr2e-model-limit-answer-one-too-early"
E_BOUNDARY_HIGH = "fr2e-model-limit-answer-one-too-late"
E_LIMIT_AS_X = "fr2e-model-limit-reported-as-x"
E_TABLE_END = "fr2e-model-limit-read-from-table"


class Model:
    """One exact model and the table it makes."""

    def __init__(self, kind: str, rule, xs: list[int], context: dict, grow: bool = True):
        self.kind, self.rule, self.xs, self.context, self.grow = kind, rule, xs, context, grow
        self._values: dict[int, Fraction] = {}
        self.ys = [self.at(v) for v in xs]
        check(all(y.denominator == 1 for y in self.ys), "table values must be whole numbers")
        self.ys = [int(y) for y in self.ys]

    def at(self, value) -> Fraction:
        """The rule's exact value at a whole x, remembered because the limit search asks for the same values again."""
        if value not in self._values:
            r = sympy.Rational(self.rule.xreplace({x: Integer(value)}))
            self._values[value] = Fraction(int(r.p), int(r.q))
        return self._values[value]

    def table_text(self) -> str:
        return "x: " + ", ".join(str(v) for v in self.xs) + "; y: " + ", ".join(str(v) for v in self.ys)


