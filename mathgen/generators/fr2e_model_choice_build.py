"""Generates `f10-choose-model-from-data` questions and its exam chain. `answer: mcq` (the exam chain also has
typed expression and number parts).

Scope: a table of values for a quantity is given as text. It was generated by exactly one of three models, a linear
rule y = mx + c, a quadratic rule y = ax^2 + bx + c, or an exponential rule y = A r^x with whole-number A and a ratio
r of 2, 3 or 1/2. The learner chooses the model from the table by the test that separates them (first differences
constant, second differences constant, ratios constant), writes its rule, predicts, and says where it stops being a
sensible model. Fitting by regression, other families and noisy data are out of scope: every table fits its model
exactly.

Ladder (reasoning escalation, not size):
  easy:   choose the model. Four statements, each a claim about the table that is true or false; exactly one is true.
          Three of them are tempting because the first pair of rows would support them.
  medium: choose the rule. The learner must choose the model before the parameters can be found; the wrong rules
          come from named errors (a first difference used as a slope, a second difference not halved).
  hard:   the x-values go up in steps of 2 or 3, so every difference or ratio is per row, not per 1 in x; choose the
          value at an x-value that is not in the table.
  exam:   a four-part chain on one table: the model (multiple choice), its rule (3 marks), the predicted value at a
          stated x (follows through from the rule) and the first whole x at which the model's value stops being
          possible because of a stated physical limit.

Every table is built from the model, then re-derived: the three tests are run on the table and exactly one holds.
"""

