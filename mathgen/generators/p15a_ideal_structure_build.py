"""Generates `ucv1-ideal-membership` and `ucv1-structure-classification` questions on ring ideals and algebraic
structures, both `answer: mcq`.

`ucv1-ideal-membership` and `ucv1-structure-classification`. Both `answer: mcq`.

`ucv1-ideal-membership`: the raw contract ("decide whether A supplied polynomial belongs to the principal
ideal generated by another supplied monic polynomial") is binary as written. Per the composition's own quoted
reading the words support a wider question: FOUR supplied polynomials are shown, exactly one of which lies in
the principal ideal (g) (its remainder on division by g is exactly zero); "which one belongs". Membership is
decided by an exact polynomial remainder (`sympy.div`/`sympy.rem`), never by factoring or inspection.

`ucv1-structure-classification`: given a finite group's order and its
element-order profile, select the one named isomorphism class (from
`p15a_group_data`'s catalogue, itself computed fresh from
`sympy.combinatorics`) that is consistent with the supplied data. The
supplied table determines the answer uniquely -- every candidate name in the
catalogue at a given order has a DISTINCT profile (verified once, at import
time, below), so there is never more than one honestly-consistent option.
"""

from __future__ import annotations

from sympy import GF, Poly, Symbol, div

from mathgen.core import check, generator, latex_answer
from mathgen.generators.p15a_group_data import DISPLAY_NAME, GROUP_CATALOG, ORDER_TO_NAMES

_x = Symbol("x")

