def _poly_str(coeffs: list[int]) -> str:
    """coeffs highest degree first, e.g. [1,0,-2,3] -> 'x^3 - 2x + 3'."""
    deg = len(coeffs) - 1
    terms = []
    for i, c in enumerate(coeffs):
        power = deg - i
        if c == 0:
            continue
        sign = "+" if c > 0 else "-"
        mag = abs(c)
        if power == 0:
            piece = f"{mag}"
        elif power == 1:
            piece = "x" if mag == 1 else f"{mag}x"
        else:
            piece = f"x^{power}" if mag == 1 else f"{mag}x^{power}"
        terms.append((sign, piece))
    if not terms:
        return "0"
    out = terms[0][1] if terms[0][0] == "+" else f"-{terms[0][1]}"
    for sign, piece in terms[1:]:
        out += f" {sign} {piece}"
    return out


def _expr_from_coeffs(coeffs: list[int]):
    deg = len(coeffs) - 1
    e = 0
    for i, c in enumerate(coeffs):
        e += c * _x ** (deg - i)
    return e


def _random_poly_coeffs(rng, degree: int, lo=-6, hi=6, lead=1) -> list[int]:
    coeffs = [lead] + [rng.randint(lo, hi) for _ in range(degree)]
    return coeffs


def _remainder_zz(p_coeffs, g_coeffs):
    p = Poly(_expr_from_coeffs(p_coeffs), _x, domain="ZZ")
    g = Poly(_expr_from_coeffs(g_coeffs), _x, domain="ZZ")
    _, r = div(p, g)
    return r


def _remainder_gf(p_coeffs, g_coeffs, prime: int):
    p = Poly(_expr_from_coeffs(p_coeffs), _x, domain=GF(prime))
    g = Poly(_expr_from_coeffs(g_coeffs), _x, domain=GF(prime))
    _, r = div(p, g)
    return r


def _build_zz_candidates(rng, g_coeffs, deg_g: int, target_idx: int, extra_degree: int):
    """4 candidate polynomials over ZZ, degree deg_g + extra_degree, exactly
    one (target_idx) with remainder 0 mod g."""
    cands = []
    for i in range(4):
        m_coeffs = _random_poly_coeffs(rng, extra_degree, -4, 4, lead=1)
        g_expr = _expr_from_coeffs(g_coeffs)
        m_expr = _expr_from_coeffs(m_coeffs)
        base = Poly(m_expr * g_expr, _x, domain="ZZ")
        if i == target_idx:
            p_expr = base.as_expr()
        else:
            for _ in range(50):
                shift_coeffs = [rng.randint(1, 5) * rng.choice([-1, 1]) for _ in range(deg_g)]
                shift_expr = _expr_from_coeffs([0] + shift_coeffs) if deg_g > 0 else 0
                # shift is a nonzero polynomial of degree < deg_g
                shift_poly = Poly(shift_expr, _x, domain="ZZ") if shift_expr != 0 else None
                if shift_poly is not None and shift_poly.degree() < deg_g and not shift_poly.is_zero:
                    p_expr = base.as_expr() + shift_expr
                    break
            else:
                raise AssertionError("could not build a nonzero-remainder candidate")
        p_poly = Poly(p_expr, _x, domain="ZZ")
        cands.append(p_poly.all_coeffs())
    return cands


def _build_hard_zz_candidates(rng, deg_g: int, target_idx: int, tries=300):
    """Hard tier's 4 candidates, each written as `(q(x))(g(x)) + (r(x))` with `r(x)` of the SAME degree (`deg_g`)
    in every option -- never a bare product with no `+` term. The target's `r(x)` is itself a nonzero multiple
    of `g(x)` (degree >= deg_g, reducible to a zero remainder only after actually dividing); every decoy's
    `r(x)` is a same-shaped polynomial that is NOT a multiple of `g`, so it leaves a nonzero remainder.

    Returns `(g_coeffs, cand_coeffs, q_coeffs_list, r_coeffs_list)`.
    """
    for _ in range(tries):
        g_coeffs = _random_poly_coeffs(rng, deg_g, -3, 3)
        g_expr = _expr_from_coeffs(g_coeffs)
        q_list, r_list, cand_coeffs = [], [], []
        ok = True
        for i in range(4):
            q_coeffs = _random_poly_coeffs(rng, 1, -4, 4, lead=1)
            q_expr = _expr_from_coeffs(q_coeffs)
            if i == target_idx:
                c = rng.choice([-3, -2, -1, 1, 2, 3])
                r_coeffs = [c * v for v in g_coeffs]
            else:
                lead = rng.choice([-3, -2, -1, 1, 2, 3])
                r_coeffs = _random_poly_coeffs(rng, deg_g, -4, 4, lead=lead)
            r_expr = _expr_from_coeffs(r_coeffs)
            p_poly = Poly(q_expr * g_expr + r_expr, _x, domain="ZZ")
            want_zero = i == target_idx
            rem = _remainder_zz(p_poly.all_coeffs(), g_coeffs)
            if rem.is_zero != want_zero:
                ok = False
                break
            q_list.append(q_coeffs)
            r_list.append(r_coeffs)
            cand_coeffs.append(p_poly.all_coeffs())
        if ok and len(set(tuple(c) for c in cand_coeffs)) == 4:
            return g_coeffs, cand_coeffs, q_list, r_list
    raise AssertionError("could not build 4 pairwise-distinct, uniform-shape hard-tier candidates")


def _distinct_zz_build(rng, deg_g, lo, hi, target_idx, extra_degree, tries=60):
    """Retry ZZ candidate construction until all 4 candidates are pairwise
    distinct (a rare random coincidence otherwise); each retry draws a fresh
    g and a fresh candidate set, consuming rng further -- still fully
    deterministic given the seed."""
    for _ in range(tries):
        g_coeffs = _random_poly_coeffs(rng, deg_g, lo, hi)
        cand_coeffs = _build_zz_candidates(rng, g_coeffs, deg_g, target_idx, extra_degree=extra_degree)
        if len(set(tuple(c) for c in cand_coeffs)) == 4:
            return g_coeffs, cand_coeffs
    raise AssertionError("could not build 4 pairwise-distinct ZZ candidates")


@generator(
    "p15a_ideal_membership",
    level=18,
    presets={
        "easy": dict(tier="easy"),
        "medium": dict(tier="medium"),
        "hard": dict(tier="hard"),
        "exam": dict(tier="exam"),
    },
)
def p15a_ideal_membership(rng, tier="easy"):
    target_idx = rng.randint(0, 3)

    if tier == "easy":
        deg_g = 2
        g_coeffs, cand_coeffs = _distinct_zz_build(rng, deg_g, -3, 3, target_idx, extra_degree=1)
        remainders = [_remainder_zz(c, g_coeffs) for c in cand_coeffs]
        cand_texts = [_poly_str(c) for c in cand_coeffs]
        g_text = _poly_str(g_coeffs)
        text = (
            f"Let g(x) = {g_text} and let (g(x)) be the principal ideal it generates in "
            f"Z[x]. Exactly one of the following four polynomials belongs to (g(x)) -- "
            f"that is, has remainder 0 on division by g(x). Which one? "
            f"A: {cand_texts[0]}   B: {cand_texts[1]}   C: {cand_texts[2]}   D: {cand_texts[3]}"
        )
    elif tier == "medium":
        deg_g = 3
        g_coeffs, cand_coeffs = _distinct_zz_build(rng, deg_g, -4, 4, target_idx, extra_degree=1)
        remainders = [_remainder_zz(c, g_coeffs) for c in cand_coeffs]
        cand_texts = [_poly_str(c) for c in cand_coeffs]
        g_text = _poly_str(g_coeffs)
        text = (
            f"Let g(x) = {g_text} and let (g(x)) be the principal ideal it generates in "
            f"Z[x]. Exactly one of the following four polynomials belongs to (g(x)) -- "
            f"that is, has remainder 0 on division by g(x). Which one? "
            f"A: {cand_texts[0]}   B: {cand_texts[1]}   C: {cand_texts[2]}   D: {cand_texts[3]}"
        )
    elif tier == "hard":
        deg_g = 2
        g_coeffs, cand_coeffs, q_coeffs_list, r_coeffs_list = _build_hard_zz_candidates(rng, deg_g, target_idx)
        remainders = [_remainder_zz(c, g_coeffs) for c in cand_coeffs]
        g_text = _poly_str(g_coeffs)
        # Present each candidate UNEXPANDED, as q(x) * g(x) + r(x): a genuine extra step (expand
        # before dividing) over easy/medium, which give the candidate already expanded. Every
        # candidate -- including the key -- is written with the SAME shape (one "+ (" group, r(x)
        # the same degree as g): the key's r(x) is itself a nonzero multiple of g, invisible until
        # actually divided out. See `_build_hard_zz_candidates`'s docstring.
        factored_texts = [
            f"({_poly_str(q_coeffs_list[i])})({g_text}) + ({_poly_str(r_coeffs_list[i])})" for i in range(4)
        ]
        text = (
            f"Let g(x) = {g_text} and let (g(x)) be the principal ideal it generates in "
            f"Z[x]. Each candidate below is written as a product plus a remainder-shaped "
            f"term; expand it first. Exactly one of the following four polynomials belongs "
            f"to (g(x)) -- that is, has remainder 0 on division by g(x). Which one? "
            f"A: {factored_texts[0]}   B: {factored_texts[1]}   C: {factored_texts[2]}   "
            f"D: {factored_texts[3]}"
        )
        cand_texts = [_poly_str(c) for c in cand_coeffs]
    else:  # exam
        prime = rng.choice([5, 7])
        deg_g = 2

        def _build_gf_set():
            g = _random_poly_coeffs(rng, deg_g, 1, prime - 1)
            cands = []
            for i in range(4):
                for _ in range(200):
                    extra_deg = 1
                    m_coeffs = [1] + [rng.randint(0, prime - 1) for _ in range(extra_deg)]
                    base_poly = Poly(_expr_from_coeffs(m_coeffs) * _expr_from_coeffs(g), _x, domain=GF(prime))
                    if i == target_idx:
                        p_poly = base_poly
                    else:
                        shift_deg = rng.randint(0, deg_g - 1)
                        shift_coeffs = [rng.randint(1, prime - 1)] + [
                            rng.randint(0, prime - 1) for _ in range(shift_deg)
                        ]
                        p_poly = base_poly + Poly(_expr_from_coeffs(shift_coeffs), _x, domain=GF(prime))
                        if p_poly.is_zero:
                            continue
                    cands.append([int(v) % prime for v in p_poly.all_coeffs()])
                    break
                else:
                    raise AssertionError("could not build exam-tier candidate")
            return g, cands

        for _ in range(60):
            g_coeffs, cand_coeffs = _build_gf_set()
            if len(set(tuple(c) for c in cand_coeffs)) == 4:
                break
        else:
            raise AssertionError("could not build 4 pairwise-distinct GF candidates")
        remainders = [_remainder_gf(c, g_coeffs, prime) for c in cand_coeffs]
        cand_texts = [_poly_str(c) for c in cand_coeffs]
        g_text = _poly_str(g_coeffs)
        text = (
            f"Working in the polynomial ring (Z/{prime}Z)[x] (all coefficients reduced "
            f"modulo {prime}), let g(x) = {g_text} and let (g(x)) be the principal ideal "
            f"it generates. Exactly one of the following four polynomials, with "
            f"coefficients already reduced mod {prime}, belongs to (g(x)) -- that is, has "
            f"remainder 0 on division by g(x) in this ring. Which one? "
            f"A: {cand_texts[0]}   B: {cand_texts[1]}   C: {cand_texts[2]}   D: {cand_texts[3]}"
        )

    # Independent check: recompute every remainder fresh from the coefficient
    # lists (never reusing whichever intermediate the construction branch
    # already held), and confirm exactly one is zero, at the target index.
    if tier == "exam":
        fresh_remainders = [_remainder_gf(c, g_coeffs, prime) for c in cand_coeffs]
    else:
        fresh_remainders = [_remainder_zz(c, g_coeffs) for c in cand_coeffs]
    zero_flags = [r.is_zero for r in fresh_remainders]
    check(sum(zero_flags) == 1, "ideal-membership: expected exactly one zero remainder")
    check(zero_flags[target_idx], "ideal-membership: zero remainder is not at the target index")

    check(len(set(tuple(c) for c in cand_coeffs)) == 4, "ideal-membership candidate polynomials must all be distinct")
    check(len(set(cand_texts)) == 4, "ideal-membership candidate polynomials must all display differently")

    labels = ["A", "B", "C", "D"]
    answer_text = labels[target_idx]
    distractors = [lbl for lbl in labels if lbl != answer_text]

    def _rem_str(r):
        if r.is_zero:
            return "0"
        coeffs = [int(v) for v in r.all_coeffs()]
        if tier == "exam":
            coeffs = [v % prime for v in coeffs]
        return _poly_str(coeffs)

    working = [
        f"g(x) = {g_text}.",
        f"Remainders: " + ", ".join(f"{labels[i]}: {_rem_str(fresh_remainders[i])}" for i in range(4)),
        f"Only option {answer_text} has remainder 0, so it is the one that belongs to (g(x)).",
    ]

    return dict(
        text=text,
        answer=answer_text,
        answer_text=answer_text,
        answer_latex=latex_answer(answer_text, plain=True),
        working=working,
        distractors=distractors,
    )


