def _profile_text(profile: dict) -> str:
    return ", ".join(
        f"{k} element of order {v}" if k == 1 else f"{k} elements of order {v}"
        for v, k in sorted(profile.items(), key=lambda kv: kv[1])
    )


def _profile_raw_list(rng, profile: dict) -> list[int]:
    raw = []
    for order, count in profile.items():
        raw += [order] * count
    rng.shuffle(raw)
    return raw


def _build_options(rng, n: int):
    same_order = list(ORDER_TO_NAMES[n])
    target = rng.choice(same_order)
    distractors = [nm for nm in same_order if nm != target]
    rng.shuffle(distractors)
    distractors = distractors[:3]
    if len(distractors) < 3:
        other_orders = [m for m in ORDER_TO_NAMES if m != n]
        pool = [nm for m in other_orders for nm in ORDER_TO_NAMES[m]]
        rng.shuffle(pool)
        for nm in pool:
            if len(distractors) >= 3:
                break
            if nm not in distractors and nm != target:
                distractors.append(nm)
    return target, distractors[:3]


@generator(
    "p15a_structure_classification",
    level=18,
    presets={
        "easy": dict(tier="easy"),
        "medium": dict(tier="medium"),
        "hard": dict(tier="hard"),
        "exam": dict(tier="exam"),
    },
)
def p15a_structure_classification(rng, tier="easy"):
    if tier == "easy":
        n = rng.choice([4, 6])
    elif tier == "medium":
        n = rng.choice([8, 9])
    else:
        n = 12

    target, distractor_names = _build_options(rng, n)
    order_t, profile_t = GROUP_CATALOG[target]
    check(order_t == n, "structure-classification order mismatch")

    labels = ["A", "B", "C", "D"]
    options = [target] + distractor_names
    rng.shuffle(options)
    answer_idx = options.index(target)

    if tier == "exam":
        raw = _profile_raw_list(rng, profile_t)
        raw_text = ", ".join(str(v) for v in raw)
        opts_text = "   ".join(f"{labels[i]}: {DISPLAY_NAME[options[i]]}" for i in range(4))
        text = (
            f"A finite group G has order {n}. The order of each of its {n} elements, "
            f"listed in no particular order, is: {raw_text}. Tally the element orders, "
            f"then decide which of the following named structures is consistent with the "
            f"data. {opts_text}"
        )
    else:
        opts_text = "   ".join(f"{labels[i]}: {DISPLAY_NAME[options[i]]}" for i in range(4))
        text = (
            f"A finite group G has order {n}, with {_profile_text(profile_t)}. Which of "
            f"the following named structures is consistent with this data? {opts_text}"
        )

    # Independent check: for every offered option, recompute its profile
    # fresh from the catalogue and confirm exactly one (the target) matches.
    matches = []
    for name in options:
        order_c, profile_c = GROUP_CATALOG[name]
        if order_c == n and profile_c == profile_t:
            matches.append(name)
    check(matches == [target], f"structure-classification: expected exactly one match, got {matches}")

    option_texts = [DISPLAY_NAME[nm] for nm in options]
    check(len(set(options)) == 4, "structure-classification options must all be distinct names")
    check(len(set(option_texts)) == 4, "structure-classification options must all display differently")

    answer_text = labels[answer_idx]
    distractors = [lbl for lbl in labels if lbl != answer_text]
    working = [
        f"|G| = {n}, profile {dict(sorted(profile_t.items()))}.",
        f"Only option {answer_text} ({DISPLAY_NAME[target]}) has a matching profile.",
    ]

    return dict(
        text=text,
        answer=answer_text,
        answer_text=answer_text,
        answer_latex=latex_answer(answer_text, plain=True),
        working=working,
        distractors=distractors,
    )
