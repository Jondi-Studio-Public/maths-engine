"""Exam tier for ideal membership by polynomial remainder: a three-part chain with two unknown coefficients.

g(x) = x^2 + s x + t generates an ideal of Z[x], and f(x) = x^4 + a x^3 + h x^2 + k x + c belongs to it. The practice
tiers choose which of four polynomials is a member. Here membership is given and the learner uses it to find the
unknown coefficients, by forcing the remainder on division by g to be zero:

(a) the coefficient h (from the constant term of the remainder, which involves h and the known c);
(b) the coefficient k (from the x term of the remainder, which involves h);
(c) the value f(n) at a stated point, using h and k.

Parts (b) and (c) follow through from the learner's earlier answers.

Built backwards from the quotient q(x) = x^2 + q1 x + q0, so f = q g and every coefficient is a whole number.
"""

from __future__ import annotations

from fractions import Fraction

import sympy

from ..core import attempts, check, generator, join_terms
from ..core import paren_negative as pn
from ._exd_distinct_parts import distinct_part_answers
from ._exd_x_r3h_kit import number_part

X = sympy.Symbol("x")


@generator("exd_x_r3h_ideal_unknown_coefficients", level=18, presets={"exam": dict(tier="exam")})
@distinct_part_answers
def exd_x_r3h_ideal_unknown_coefficients(rng, tier="exam"):
    if tier != "exam":
        raise ValueError(f"unknown tier {tier!r}")
    for _ in attempts(1000, "a quotient with nonzero unknown coefficients"):
        s = rng.randint(-4, 4)
        t = rng.choice((-5, -4, -3, -2, -1, 1, 2, 3, 4, 5))
        q1 = rng.randint(-4, 4)
        q0 = rng.choice((-5, -4, -3, -2, -1, 1, 2, 3, 4, 5))
        a = q1 + s
        c = t * q0
        h = q0 + s * q1 + t
        k = s * q0 + t * q1
        if s == 0 or q1 == 0 or h == 0 or k == 0 or a == 0:
            continue
        n = rng.choice((-3, -2, -1, 2, 3))
        g = X**2 + s * X + t
        q = X**2 + q1 * X + q0
        f = sympy.expand(g * q)
        value = int(f.subs(X, n))
        # Part (c) needs two distractors that differ from the key and from each other.
        if len({int(q.subs(X, n)), value - k * n, int(f.subs(X, -n)), int(g.subs(X, n))} - {value}) >= 2:
            break
    check(sympy.Poly(f, X).all_coeffs() == [1, a, h, k, c], "coefficients of the product")
    check(sympy.rem(f, g, X) == 0, "f lies in the ideal generated by g")

    # Reducing x^2 with the wrong sign (x^2 = s x + t instead of -s x - t) gives wrong coefficients.
    wrong_h = -(s * s + t + a * s + Fraction(c, t))
    wrong_k = -((s**3 + 2 * s * t) + a * (s * s + t) + h * s)

    shown = join_terms([(1, "x^4"), (a, "x^3")])
    stem = (
        f"Let I be the ideal of Z[x] generated by g(x) = {join_terms([(1, 'x^2'), (s, 'x'), (t, '')])}. "
        f"The polynomial f(x) = {shown} + h x^2 + k x {'+' if c > 0 else '-'} {abs(c)}, where h and k are integers, "
        "belongs to I."
    )
    ff = Fraction
    return dict(
        text=stem,
        parts=[
            dict(
                **number_part(
                    "Find the value of h.",
                    ff(h),
                    0,
                    3,
                    [
                        f"Since f is in I, f = g(x)(x^2 + q1 x + q0). Comparing constant terms, {t} q0 = {c}, so q0 = {q0}.",
                        f"Comparing x^3 terms gives q1 = {a} - ({s}) = {q1}; the x^2 term gives h = q0 + ({s})q1 + {pn(t)} = {h}.",
                    ],
                    [
                        (wrong_h, "sign-slip-in-formula"),
                        (q0 + s * q1 - t, "sign-error-moving-term"),
                        (q0, "gave-constant-quotient-term-for-coefficient"),
                        (q0 + s * q1, "omitted-entry-in-total"),
                    ],
                )
            ),
            dict(
                **number_part(
                    "Hence find the value of k.",
                    ff(k),
                    0,
                    3,
                    [f"The x term gives k = ({s})q0 + ({t})q1 = {join_terms([(s * q0, ''), (t * q1, '')])} = {k}."],
                    [
                        (wrong_k, "sign-slip-in-formula"),
                        (s * q0 - t * q1, "sign-error-moving-term"),
                        (s * q1 + t * q0, "swapped-quotient-coefficients-in-product"),
                        (-k, "sign-error-moving-term"),
                    ],
                    follow_through=f"({s})*(part_a - ({s})*({q1}) - ({t})) + ({t})*({q1})",
                )
            ),
            dict(
                **number_part(
                    f"Hence find f({n}).",
                    ff(value),
                    0,
                    2,
                    [f"f({n}) = ({n})^4 + ({a})({n})^3 + ({h})({n})^2 + ({k})({n}) + ({c}) = {value}."],
                    [
                        (int(q.subs(X, n)), "gave-factor-value-for-product-value"),
                        (value - k * n, "omitted-entry-in-total"),
                        (int(f.subs(X, -n)), "substitution-sign-error"),
                        (int(g.subs(X, n)), "gave-factor-value-for-product-value"),
                    ],
                    follow_through=f"({n})**4 + ({a})*({n})**3 + part_a*({n})**2 + part_b*({n}) + ({c})",
                )
            ),
        ],
    )
