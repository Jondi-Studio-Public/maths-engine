"""Exam tier for "test a finite subset for subgroup closure".

The practice tiers decide whether a listed subset is a subgroup. Here the subgroup is the one an element
generates inside the group of units modulo n, and the learner uses its order to describe how it sits in the group,
as an abstract-algebra exam would set it:

(a) the order of the group G of units modulo n;
(b) the order of the subgroup H generated by g (the least k > 0 with g^k = 1 modulo n);
(c) the index of H in G (Lagrange's theorem), from (a) and (b);
(d) the number of elements of G outside H, from (a) and (b).

Every key is re-derived by brute force in the tests: the units are listed, and the powers of g are multiplied out
modulo n until they return to 1.
"""

from __future__ import annotations

import math
import random

from ..core import attempts, check, generator
from ._exd_distinct_parts import distinct_part_answers
from ._exd_x_r3g_kit import clashes, number_part

_MODULI = tuple(range(30, 451))  # primes, prime powers and products alike
_STEMS = (
    "Let G be the group of units modulo {n} under multiplication: the residues from 1 to {m} that have no common "
    "factor with {n}. Let H be the subgroup of G generated by {g}.",
    "Consider the multiplicative group G = (Z/{n}Z)× and its cyclic subgroup H = ⟨{g}⟩.",
    "The residues modulo {n} that are coprime to {n} form a group G under multiplication modulo {n}. "
    "The element {g} of G generates a subgroup H.",
)


def _units(n: int) -> list[int]:
    return [u for u in range(1, n) if math.gcd(u, n) == 1]


def _order(g: int, n: int) -> int:
    value, k = g % n, 1
    while value != 1:
        value, k = value * g % n, k + 1
        check(k <= n, "element has no order")
    return k


def _distinct_primes(n: int) -> list[int]:
    return [p for p in range(2, n + 1) if n % p == 0 and all(p % q for q in range(2, int(p**0.5) + 1))]


@generator("exd_x_r3g_unit_group_index", level=12, presets={"exam": dict(tier="exam")})
@distinct_part_answers
def exd_x_r3g_unit_group_index(rng: random.Random, tier: str = "exam") -> dict:
    """Order of the unit group modulo n, order of a generated subgroup, its index and the elements outside it."""
    if tier != "exam":
        raise ValueError(f"unknown tier {tier!r}")
    for _ in attempts(1000, "a unit and modulus with a proper, non-trivial generated subgroup"):
        n = rng.choice(_MODULI)
        units = _units(n)
        g = rng.choice([u for u in units if 1 < u < n - 1])
        order_g, size = _order(g, n), len(units)
        if order_g < 3 or size // order_g < 2:
            continue
        stem = rng.choice(_STEMS).format(n=n, m=n - 1, g=g)
        if clashes((size, order_g, size // order_g, size - order_g), stem):
            continue
        break

    index, outside = size // order_g, size - order_g
    check(size == index * order_g, "Lagrange's theorem fails")
    powers = [pow(g, k, n) for k in range(1, order_g + 1)]
    check(len(set(powers)) == order_g and powers[-1] == 1, "the powers of g do not form a cycle of that length")
    additive = n // math.gcd(g, n)
    prime_part = math.prod(p - 1 for p in _distinct_primes(n))
    parts = [
        number_part(
            "Find the order of G.",
            size,
            0,
            1,
            [f"The units modulo {n} are the residues coprime to {n}: there are {size} of them."],
            [
                (n - 1, "group-units-counted-as-all-nonzero-residues"),
                (size - 1, "group-units-exclude-the-identity"),
                (n, "group-units-counted-as-all-residues"),
                (prime_part, "group-totient-ignores-prime-powers"),
            ],
            sensible_range=(0, None),
        ),
        number_part(
            f"Find the order of H.",
            order_g,
            0,
            3,
            [
                f"Powers of {g} modulo {n}: "
                + ", ".join(map(str, powers[: min(order_g, 6)]))
                + (", ..." if order_g > 6 else "")
                + ".",
                f"The first power equal to 1 is g^{order_g}, so |H| = {order_g}.",
            ],
            [
                (size, "group-element-order-taken-as-group-order"),
                (additive, "group-order-computed-additively"),
                (order_g + 1, "off-by-one-count"),
                (order_g - 1, "off-by-one-count"),
            ],
            sensible_range=(0, None),
        ),
        number_part(
            "Find the index of H in G, that is, the number of distinct cosets of H in G.",
            index,
            0,
            2,
            [f"Lagrange: |G| = [G : H] x |H|, so [G : H] = {size} / {order_g} = {index}."],
            [
                (size * order_g, "multiplied-instead-of-divided"),
                (order_g, "index-confused-with-subgroup-order"),
                (outside, "group-index-reports-elements-outside"),
                (index + 1, "off-by-one-count"),
            ],
            follow_through="part_a/part_b",
            sensible_range=(0, None),
        ),
        number_part(
            "How many elements of G do not belong to H?",
            outside,
            0,
            1,
            [f"{size} - {order_g} = {outside}."],
            [
                (order_g, "group-outside-counts-inside"),
                (outside + 1, "off-by-one-count"),
                (size, "group-outside-counts-everything"),
                (index, "group-outside-reports-index"),
            ],
            follow_through="part_a - part_b",
            sensible_range=(0, None),
        ),
    ]
    return dict(text=stem, parts=parts)
