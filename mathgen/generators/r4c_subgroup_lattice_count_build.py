"""Generates `r4c_subgroup_lattice_count` questions (easy, medium, hard) and the exam chain `exd_x_r4c_subgroup_lattice_count`.

``uc2-subgroup-lattice-count`` (``abstract-algebra``, answer ``number``): count subgroups from the shape of the subgroup
lattice rather than by listing them.

* easy: in Z_n, how many subgroups contain ⟨k⟩ for a generator k that is not a divisor of n. A subgroup ⟨d⟩ (d | n)
  contains ⟨k⟩ exactly when d divides gcd(n, k), so the count is the number of divisors of gcd(n, k).
* medium: in the dihedral group D_n of order 2n, how many subgroups have order k. Rotation subgroups and the dihedral
  subgroups ⟨r^d, s r^j⟩ both have to be counted.
* hard: how many subgroups does Z_m × Z_n have in total. The count is the sum of gcd(a, b) over divisors a of m and b of
  n, which no product of divisor counts gives.
* exam: the subgroups of D_n: (a) inside the rotation subgroup, (b) not inside it, (c) in total, (d) normal.

The tests count every answer by brute force (closing generated sets under the group operation).
"""

from __future__ import annotations

from math import gcd, lcm

from ..core import attempts, check, generator
from ._r4c_kit import divisors, factorise, number_part, number_question


def _tau(n):
    return len(divisors(n))


def _sigma(n):
    return sum(divisors(n))


def _dihedral_count(n, k):
    """Subgroups of order k in D_n (order 2n): the rotation subgroup if k | n, and n/m dihedral ones if k = 2m, m | n."""
    out = 1 if n % k == 0 else 0
    if k % 2 == 0 and n % (k // 2) == 0:
        out += n // (k // 2)
    return out


def _product_count(m, n):
    """Subgroups of Z_m × Z_n: the sum of gcd(a, b) over a | m and b | n."""
    return sum(gcd(a, b) for a in divisors(m) for b in divisors(n))


def _cyclic_count(m, n):
    """Cyclic subgroups of Z_m × Z_n: elements of each order d, divided by phi(d)."""
    from ._r4c_kit import totient

    orders = {}
    for x in range(m):
        for y in range(n):
            o = lcm(m // gcd(m, x), n // gcd(n, y))
            orders[o] = orders.get(o, 0) + 1
    return sum(c // totient(o) for o, c in orders.items())


def _easy(rng):
    for _ in attempts(500, "a generator whose gcd with n has several divisors but is a proper divisor"):
        n = rng.choice([60, 72, 84, 90, 96, 108, 120, 126, 144, 150, 168, 180, 210, 240, 252, 360])
        by_tau = {}
        for d in divisors(n):
            if 4 <= _tau(d) <= 12 and d not in (1, n):
                by_tau.setdefault(_tau(d), []).append(d)
        if not by_tau:
            continue
        g = rng.choice(by_tau[rng.choice(sorted(by_tau))])
        coprime = [u for u in range(2, n // g + 1) if gcd(u, n) == 1]
        if not coprime:
            continue
        u = rng.choice(coprime)
        k = g * u
        if k >= n or k == g:
            continue
        break
    check(gcd(n, k) == g, "the gcd differs from the planned divisor")
    key = _tau(g)
    check(
        key == sum(1 for d in range(1, n + 1) if n % d == 0 and g % d == 0),
        "the divisor count differs from the direct count",
    )
    stem = rng.choice(
        [
            f"In the cyclic group Z_{n} under addition, how many subgroups contain the subgroup H = ⟨{k}⟩? "
            f"(H itself counts, and so does Z_{n}.)",
            f"Let H = ⟨{k}⟩ be the subgroup of (Z_{n}, +) generated by {k}. Count the subgroups of Z_{n} that contain H, "
            f"including H and Z_{n} themselves.",
            f"Z_{n} is the group of integers modulo {n} under addition. How many subgroups K of Z_{n} satisfy ⟨{k}⟩ ⊆ K? "
            f"Both K = ⟨{k}⟩ and K = Z_{n} count.",
        ]
    )
    return number_question(
        stem,
        key,
        [
            f"⟨{k}⟩ = ⟨gcd({k}, {n})⟩ = ⟨{g}⟩.",
            f"A subgroup ⟨d⟩ with d | {n} contains ⟨{g}⟩ exactly when d divides {g}, so the count is the number of divisors of {g}: {key}.",
        ],
        [
            (_tau(n // g), "lattice-contains-contained-swapped"),
            (_tau(n), "lattice-counts-all-subgroups"),
            (_tau(k), "lattice-uses-generator-not-gcd"),
            (key - 1, "lattice-excludes-the-subgroup-itself"),
            (key + 1, None),
        ],
    )


def _medium(rng):
    for _ in attempts(500, "a dihedral group and an order with a clear count"):
        n = rng.choice(
            [
                6,
                8,
                9,
                10,
                12,
                14,
                15,
                16,
                18,
                20,
                21,
                22,
                24,
                25,
                26,
                27,
                28,
                30,
                32,
                36,
                40,
                42,
                45,
                48,
                50,
                54,
                56,
                60,
            ]
        )
        m = rng.choice([d for d in divisors(n) if d >= 2])
        k = 2 * m
        key = _dihedral_count(n, k)
        if key >= 3 and not (n % k == 0 and m == n):
            break
    check(key == (1 if n % k == 0 else 0) + n // m, "the count differs from rotation plus dihedral subgroups")
    stem = rng.choice(
        [
            f"Let D_{n} be the dihedral group of order {2 * n}, the symmetries of a regular {n}-gon. "
            f"How many subgroups of D_{n} have order {k}?",
            f"The symmetries of a regular {n}-gon form the dihedral group D_{n}, of order {2 * n}. Count its subgroups of order {k}.",
            f"How many different subgroups of order {k} does the dihedral group D_{n} (of order {2 * n}) have? "
            "Subgroups are counted as sets of elements, not by their generators.",
        ]
    )
    return number_question(
        stem,
        key,
        [
            f"Dihedral subgroups of order {k} = 2·{m}: one for each of the {n // m} cosets of ⟨r^({n}/{m})⟩ in the rotations, so {n // m}.",
            f"A rotation subgroup of order {k} exists only if {k} divides {n}: {'yes, add 1' if n % k == 0 else 'no here'}. Total {key}.",
        ],
        [
            (n // m, "dihedral-count-forgets-rotation-subgroup"),
            (1 if n % k == 0 else 2, "dihedral-count-forgets-reflection-type"),
            (n, "dihedral-count-elements-not-subgroups"),
            (key + 1, None),
            (key - 1, None),
            (2 * n // k if n % k else 2 * n // k + 2, None),
        ],
    )


def _hard(rng):
    for _ in attempts(500, "Z_m x Z_n with a shared prime factor and between 12 and 220 elements"):
        m = rng.choice([2, 3, 4, 6, 8, 9, 10, 12, 16, 18, 20, 24, 27])
        n = rng.choice([2, 3, 4, 6, 8, 9, 10, 12, 16, 18, 20, 24, 27])
        if gcd(m, n) < 2 or m * n > 220 or m * n < 12:
            continue
        break
    key = _product_count(m, n)
    # second route inside the generator: the count multiplies over the primes of m and n
    primes = {q for q, _ in factorise(m)} | {q for q, _ in factorise(n)}
    check(
        key
        == _prod(_product_count(q ** dict(factorise(m)).get(q, 0), q ** dict(factorise(n)).get(q, 0)) for q in primes),
        "the count does not multiply over the primes",
    )
    stem = rng.choice(
        [
            f"How many subgroups does Z_{m} × Z_{n} have, counting the trivial subgroup and the whole group?",
            f"Count every subgroup of the direct product Z_{m} × Z_{n} (with componentwise addition), including the trivial subgroup and the whole group.",
            f"The group G = Z_{m} × Z_{n} is formed with componentwise addition. How many subgroups does G have in total?",
        ]
    )
    return number_question(
        stem,
        key,
        [
            f"Subgroups of Z_{m} × Z_{n} number the sum of gcd(a, b) over divisors a of {m} and b of {n}.",
            f"That sum is {key}.",
        ],
        [
            (_tau(m) * _tau(n), "subgroup-count-assumes-product-subgroups"),
            (_cyclic_count(m, n), "subgroup-count-cyclic-only"),
            (_tau(m * n), "subgroup-count-divisors-of-order"),
            (key - 1, None),
            (key + 1, None),
        ],
    )


def _prod(values):
    out = 1
    for v in values:
        out *= v
    return out


@generator(
    "r4c_subgroup_lattice_count",
    level=19,
    presets={"easy": dict(tier="easy"), "medium": dict(tier="medium"), "hard": dict(tier="hard")},
)
def r4c_subgroup_lattice_count(rng, tier="easy"):
    """Count subgroups from the lattice; the tiers are described in the module docstring."""
    if tier == "easy":
        return _easy(rng)
    if tier == "medium":
        return _medium(rng)
    check(tier == "hard", f"unknown tier {tier!r}")
    return _hard(rng)


