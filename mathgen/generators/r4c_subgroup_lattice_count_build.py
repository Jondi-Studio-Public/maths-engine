@generator("exd_x_r4c_subgroup_lattice_count", level=19, presets={"exam": dict(tier="exam")})
def exd_x_r4c_subgroup_lattice_count(rng, tier="exam"):
    """Exam chain: the subgroups of D_n inside and outside the rotation subgroup, in total, and the normal ones."""
    check(tier == "exam", f"unknown tier {tier!r}")
    n = rng.choice([6, 8, 9, 10, 12, 14, 15, 16, 18, 20, 24, 30])
    inside, outside = _tau(n), _sigma(n)
    total = inside + outside
    normal = inside + 1 + (2 if n % 2 == 0 else 0)
    # the dihedral subgroups <r^d, s r^j> with d | n and 0 <= j < d are normal exactly when d divides 2
    check(outside == sum(d for d in divisors(n)), "the dihedral subgroups do not number sigma(n)")
    check(
        normal == inside + sum(d for d in divisors(n) if 2 % d == 0), "the normal subgroups differ from the d | 2 count"
    )
    return dict(
        text=rng.choice(
            [
                f"Let D_{n} be the dihedral group of order {2 * n}, generated by a rotation r of order {n} and a reflection s, "
                "and let R = ⟨r⟩ be the subgroup of rotations.",
                f"The dihedral group D_{n} has order {2 * n}. It is generated by a rotation r of order {n} and a reflection s, "
                "and R = ⟨r⟩ denotes its subgroup of rotations.",
                f"Consider the symmetries of a regular {n}-gon, the group D_{n} of order {2 * n} with rotation r and reflection s. "
                "Write R = ⟨r⟩ for the rotation subgroup.",
            ]
        ),
        parts=[
            number_part(
                f"How many subgroups of D_{n} are contained in R?",
                inside,
                1,
                [f"R is cyclic of order {n}, so its subgroups correspond to the divisors of {n}: {inside}."],
                [
                    (_sigma(n), "dihedral-count-sigma-for-tau"),
                    (inside - 1, None),
                    (inside + 1, None),
                    (n, "dihedral-count-elements-not-subgroups"),
                ],
                sensible_range=(0, None),
            ),
            number_part(
                f"How many subgroups of D_{n} are not contained in R? Each of these contains at least one reflection.",
                outside,
                3,
                [
                    f"Such a subgroup is ⟨r^d, s r^j⟩ with d | {n} and 0 ≤ j < d.",
                    f"There are d choices of j for each d, so the number is the sum of the divisors of {n}: {outside}.",
                ],
                [
                    (inside, "dihedral-count-tau-for-sigma"),
                    (n, "dihedral-count-elements-not-subgroups"),
                    (outside - 1, None),
                    (_tau(n) * 2, None),
                ],
                sensible_range=(0, None),
            ),
            number_part(
                f"How many subgroups does D_{n} have in total?",
                total,
                1,
                [f"{inside} inside R plus {outside} outside R gives {total}."],
                [
                    (inside, "dihedral-count-forgets-reflection-type"),
                    (outside, "dihedral-count-forgets-rotation-subgroup"),
                    (total + 1, None),
                    (total - 1, None),
                ],
                follow_through="part_a + part_b",
                sensible_range=(0, None),
            ),
            number_part(
                f"How many of the subgroups of D_{n} are normal in D_{n}?",
                normal,
                3,
                [
                    f"Every subgroup of R is normal: {inside}.",
                    "A subgroup ⟨r^d, s r^j⟩ is normal only if r s r^(-1) = s r^(-2) lies in it, so r^2 is in ⟨r^d⟩: d divides 2.",
                    f"d = 1 gives D_{n} itself{', and d = 2 gives two subgroups of index 2' if n % 2 == 0 else '; d = 2 is not a divisor of an odd n'}. Total {normal}.",
                ],
                [
                    (inside, "normal-count-only-rotations"),
                    (total, "normal-count-every-subgroup"),
                    (inside + 1 + (0 if n % 2 == 0 else 2), "normal-count-parity-swapped"),
                    (normal + 1, None),
                ],
                sensible_range=(0, None),
            ),
        ],
    )
