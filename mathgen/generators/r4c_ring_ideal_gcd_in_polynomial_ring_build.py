"""Generates `r4c_ring_ideal_gcd_in_polynomial_ring` questions (easy, medium, hard) and the exam chain
`exd_x_r4c_ring_ideal_gcd_in_polynomial_ring`.

``uc2-ring-ideal-gcd-in-polynomial-ring`` (``abstract-algebra``, answer ``expression``): a polynomial ring over a field is
a principal ideal domain, so an ideal ⟨f, g⟩ is ⟨d⟩ for the monic gcd d, and ⟨f⟩ ∩ ⟨g⟩ is ⟨ℓ⟩ for the monic lcm ℓ. The
answer is always a monic polynomial, which makes the generator unique; the stem says so.

* easy: ⟨f, g⟩ in Q[x] for expanded integer polynomials sharing a linear or quadratic factor.
* medium: ⟨f, g⟩ in Z_p[x], p in {5, 7, 11}, with coefficients written in {0, ..., p-1}.
* hard: ⟨f⟩ ∩ ⟨g⟩ in Z_p[x].
* exam: in Z_p[x]: (a) the remainder of f on division by g, (b) the monic gcd, (c) the dimension of Z_p[x] / ⟨f, g⟩ over
  Z_p, (d) the number of elements of that ring (follows from (c)).

The answer is built from the planned common factor and re-derived by Euclid's algorithm over the field; the tests redo it
with SymPy.
"""

from __future__ import annotations

from fractions import Fraction

from ..core import attempts, check, generator
from ._r4c_kit import expr_part, expr_question, number_part, pdivmod, pgcd, pmul, poly_text, trim


# -- polynomials over Q (coefficient tuples of ints, lowest degree first) -----------------------------------------------


def _qmul(a, b):
    out = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            out[i + j] += x * y
    return tuple(out)


def _qgcd_monic(a, b):
    """The monic gcd over Q by Euclid's algorithm, as a tuple of Fractions."""

    def rem(x, y):
        x = [Fraction(c) for c in x]
        while len(x) >= len(y):
            f = x[-1] / y[-1]
            for i, c in enumerate(y):
                x[len(x) - len(y) + i] -= f * c
            x.pop()
            while x and x[-1] == 0:
                x.pop()
        return tuple(x)

    a, b = tuple(Fraction(c) for c in a), tuple(Fraction(c) for c in b)
    while b:
        a, b = b, rem(a, b)
    return tuple(c / a[-1] for c in a)


def _small_factor(rng, degree, p=None):
    """A monic polynomial of the degree: over Q (x - r), (x - r1)(x - r2) or a quadratic without rational roots; over Z_p random."""
    if p is not None:
        return tuple(rng.randrange(p) for _ in range(degree)) + (1,)
    if degree == 1:
        return (-rng.randint(-5, 5), 1)
    if rng.random() < 0.25:
        return rng.choice([(1, 0, 1), (2, 0, 1), (1, 1, 1), (2, 2, 1), (5, 2, 1), (5, 4, 1), (2, -2, 1)])
    return _times(_small_factor(rng, 1, p), _small_factor(rng, 1, p), p)


def _norm(c, p):
    return tuple(x % p for x in c) if p else tuple(c)


def _times(a, b, p):
    return pmul(a, b, p) if p else _qmul(a, b)


def _coprime(a, b, p):
    if p:
        return len(pgcd(a, b, p)) == 1
    return len(_qgcd_monic(a, b)) == 1


def _build(rng, p, deg_h, deg_u, deg_v, scalars):
    """f = c1 h u, g = c2 h v with u, v coprime; the gcd is h. Returns (h, u, v, f, g)."""
    for _ in attempts(500, "a pair with the planned common factor and nothing else in common"):
        h = _small_factor(rng, deg_h, p)
        u = _small_factor(rng, deg_u, p)
        v = _small_factor(rng, deg_v, p)
        if not _coprime(u, v, p) or u == v or not _coprime(h, u, p) or not _coprime(h, v, p):
            continue
        c1, c2 = scalars(rng)
        f = tuple(c1 * x for x in _times(h, u, p))
        g = tuple(c2 * x for x in _times(h, v, p))
        if p:
            f, g = _norm(f, p), _norm(g, p)
        if p and (len(trim(f)) != deg_h + deg_u + 1 or len(trim(g)) != deg_h + deg_v + 1):
            continue
        return h, u, v, f, g
    raise AssertionError  # pragma: no cover


def _stem_poly(c):
    return poly_text(c)


def _as_ints(frac_poly):
    check(all(c.denominator == 1 for c in frac_poly), "the Euclidean gcd is not integral")
    return tuple(int(c) for c in frac_poly)


def _easy(rng):
    deg_h = rng.choice([1, 1, 2])
    h, u, v, f, g = _build(
        rng,
        None,
        deg_h,
        rng.choice([1, 2]) if deg_h == 1 else 1,
        rng.choice([1, 2]) if deg_h == 1 else 1,
        lambda r: (r.choice([1, 2, 3]), r.choice([1, 2, 3])),
    )
    key = _as_ints(_qgcd_monic(f, g))
    check(key == h, "Euclid's algorithm differs from the planned common factor")
    lcm = _times(_times(h, u, None), v, None)
    lead = max(f[-1], g[-1]) if f[-1] != g[-1] else f[-1]
    stem = rng.choice(
        [
            f"Let I = ⟨f, g⟩ be the ideal of Q[x] generated by f = {_stem_poly(f)} and g = {_stem_poly(g)}. "
            "Every ideal of Q[x] is generated by a single polynomial; find the monic polynomial d with I = ⟨d⟩.",
            f"In Q[x], the ideal I is generated by f = {_stem_poly(f)} and g = {_stem_poly(g)}. "
            "I is principal, I = ⟨d⟩ for exactly one monic d. Find d.",
            f"Find the monic generator of the ideal ⟨f, g⟩ of Q[x], where f = {_stem_poly(f)} and g = {_stem_poly(g)}.",
        ]
    )
    cands = [
        (tuple(lead * c for c in h) if lead > 1 else None, "ideal-generator-not-monic"),
        (lcm, "ideal-generator-is-lcm"),
        (_times(h, u, None), "ideal-generator-is-one-of-the-polynomials"),
        (_times(h, v, None), "ideal-generator-is-one-of-the-polynomials"),
        (_first_factor(h) if deg_h == 2 else None, "ideal-generator-misses-a-common-factor"),
        ((-h[0], 1) if deg_h == 1 and h[0] != 0 else None, "ideal-generator-root-sign-slip"),
    ]
    return expr_question(
        stem,
        key,
        [
            "Divide f by g, then g by the remainder, and continue until the remainder is zero (Euclid's algorithm in Q[x]).",
            f"The last non-zero remainder, made monic, is {poly_text(key)}.",
        ],
        cands,
    )


def _first_factor(h):
    """A linear factor (x - r) of a quadratic with integer roots, else None."""
    b, c = h[1], h[0]
    for r in range(-9, 10):
        if r * r + b * r + c == 0:
            return (-r, 1)
    return None


def _medium(rng):
    p = rng.choice([5, 7, 11])
    deg_h = rng.choice([1, 2])
    h, u, v, f, g = _build(
        rng,
        p,
        deg_h,
        rng.choice([1, 2]) if deg_h == 1 else 2,
        rng.choice([1, 2]) if deg_h == 1 else 1,
        lambda r: (r.randrange(1, p), r.randrange(1, p)),
    )
    key = pgcd(f, g, p)
    check(key == h, "Euclid's algorithm differs from the planned common factor")
    first = pdivmod(f, g, p)[1] if len(f) >= len(g) else pdivmod(g, f, p)[1]
    lcm = pmul(pmul(h, u, p), v, p)
    scaled = tuple((2 * c) % p for c in h) if p > 2 else None
    stem = rng.choice(
        [
            f"Let I = ⟨f, g⟩ be the ideal of Z_{p}[x] generated by f = {poly_text(f)} and g = {poly_text(g)}. "
            f"Every ideal of Z_{p}[x] is generated by one polynomial; find the monic polynomial d with I = ⟨d⟩, written with "
            f"coefficients from 0 to {p - 1}.",
            f"In Z_{p}[x], the ideal I is generated by f = {poly_text(f)} and g = {poly_text(g)}. "
            f"Find the unique monic d with I = ⟨d⟩, with coefficients from 0 to {p - 1}.",
            f"Find the monic generator of the ideal ⟨f, g⟩ of Z_{p}[x], where f = {poly_text(f)} and g = {poly_text(g)}. "
            f"Write its coefficients from 0 to {p - 1}.",
        ]
    )
    return expr_question(
        stem,
        key,
        [
            f"Run Euclid's algorithm with all arithmetic modulo {p}.",
            f"The last non-zero remainder, made monic, is {poly_text(key)}.",
        ],
        [
            (scaled, "ideal-generator-not-monic"),
            (first if first and first != key else None, "ideal-generator-stopped-at-first-remainder"),
            (lcm, "ideal-generator-is-lcm"),
            (((p - h[0]) % p, 1) if deg_h == 1 and (p - h[0]) % p != h[0] else None, "ideal-generator-root-sign-slip"),
            (
                _monic_mod(first, p) if first and _monic_mod(first, p) != key else None,
                "ideal-generator-stopped-at-first-remainder",
            ),
        ],
    )


def _monic_mod(a, p):
    from ._r4c_kit import monic

    return monic(a, p) if a else None


def _hard(rng):
    p = rng.choice([5, 7])
    deg_h = rng.choice([1, 2])
    h, u, v, f, g = _build(
        rng, p, deg_h, 2 if deg_h == 1 else 1, 2 if deg_h == 1 else 1, lambda r: (r.randrange(1, p), r.randrange(1, p))
    )
    d = pgcd(f, g, p)
    check(d == h, "Euclid's algorithm differs from the planned common factor")
    key = pmul(pmul(h, u, p), v, p)
    prod, rem = pdivmod(pmul(f, g, p), d, p)
    check(not rem and pgcd(f, g, p) == d, "gcd does not divide the product")
    check(_monic_mod(prod, p) == key, "the lcm differs from fg / gcd")
    stem = rng.choice(
        [
            f"In Z_{p}[x] let I = ⟨f⟩ and J = ⟨g⟩, where f = {poly_text(f)} and g = {poly_text(g)}. "
            f"The intersection I ∩ J is generated by a single monic polynomial ℓ. Find ℓ, written with coefficients from "
            f"0 to {p - 1}.",
            f"Find the monic polynomial ℓ that generates the intersection of the principal ideals ⟨f⟩ and ⟨g⟩ of Z_{p}[x], "
            f"where f = {poly_text(f)} and g = {poly_text(g)}. Use coefficients from 0 to {p - 1}.",
            f"In Z_{p}[x], with f = {poly_text(f)} and g = {poly_text(g)}, a polynomial lies in both ⟨f⟩ and ⟨g⟩ exactly when "
            f"it is a multiple of one monic polynomial ℓ. Find ℓ, with coefficients from 0 to {p - 1}.",
        ]
    )
    return expr_question(
        stem,
        key,
        [
            "A polynomial lies in both ideals exactly when it is a multiple of f and of g, that is, a multiple of lcm(f, g).",
            f"lcm(f, g) = f·g / gcd(f, g), and gcd(f, g) = {poly_text(d)}. Made monic, ℓ = {poly_text(key)}.",
        ],
        [
            (_monic_mod(pmul(f, g, p), p), "intersection-generated-by-the-product"),
            (d, "intersection-confused-with-sum"),
            (
                tuple((c * f[-1]) % p for c in key) if f[-1] != 1 else tuple((2 * c) % p for c in key),
                "ideal-generator-not-monic",
            ),
            (pmul(u, v, p), "lcm-drops-the-common-factor"),
        ],
    )


@generator(
    "r4c_ring_ideal_gcd_in_polynomial_ring",
    level=19,
    presets={"easy": dict(tier="easy"), "medium": dict(tier="medium"), "hard": dict(tier="hard")},
)
def r4c_ring_ideal_gcd_in_polynomial_ring(rng, tier="easy"):
    """Ideals of a polynomial ring from gcds and lcms; the tiers are described in the module docstring."""
    if tier == "easy":
        return _easy(rng)
    if tier == "medium":
        return _medium(rng)
    check(tier == "hard", f"unknown tier {tier!r}")
    return _hard(rng)


# -- exam -------------------------------------------------------------------------------------------------------


@generator("exd_x_r4c_ring_ideal_gcd_in_polynomial_ring", level=19, presets={"exam": dict(tier="exam")})
def exd_x_r4c_ring_ideal_gcd_in_polynomial_ring(rng, tier="exam"):
    """Exam chain: Euclid step, gcd, dimension and size of the quotient ring."""
    check(tier == "exam", f"unknown tier {tier!r}")
    p = rng.choice([5, 7])
    for _ in attempts(200, "a pair with a non-zero first remainder"):
        deg_h = rng.choice([1, 2])
        h, u, v, f, g = _build(rng, p, deg_h, 4 - deg_h, 4 - deg_h, lambda r: (r.randrange(1, p), r.randrange(1, p)))
        q, r = pdivmod(f, g, p)
        if r and r != h and len(r) < len(g):
            break
    d = pgcd(f, g, p)
    check(d == h, "Euclid's algorithm differs from the planned common factor")
    dim = len(d) - 1
    check(len(pgcd(f, g, p)) - 1 == dim, "dimension differs from the degree of the gcd")
    neg_r = trim(((-c) % p) for c in r)
    return dict(
        text=rng.choice(
            [
                f"In the ring Z_{p}[x], let f = {poly_text(f)} and g = {poly_text(g)}, and let I = ⟨f, g⟩. "
                f"All polynomials below are written with coefficients from 0 to {p - 1}.",
                f"Let I be the ideal of Z_{p}[x] generated by f = {poly_text(f)} and g = {poly_text(g)}. "
                f"Write every polynomial with coefficients from 0 to {p - 1}.",
                f"Work in Z_{p}[x] with f = {poly_text(f)} and g = {poly_text(g)}, and write I = ⟨f, g⟩. "
                f"Polynomial answers use coefficients from 0 to {p - 1}.",
            ]
        ),
        parts=[
            expr_part(
                "Find the remainder when f is divided by g.",
                r,
                p,
                2,
                [
                    f"Divide f by g with arithmetic modulo {p}: the quotient is {poly_text(q)} and the remainder is {poly_text(r)}."
                ],
                [
                    (q, "remainder-confused-with-quotient"),
                    (neg_r, "division-sign-slip"),
                    (_monic_mod(r, p) if _monic_mod(r, p) != r else None, "remainder-made-monic"),
                    (trim(((a - b) % p) for a, b in zip(f, g + (0,) * (len(f) - len(g)))), "division-step-incomplete"),
                ],
            ),
            expr_part(
                "Find the monic polynomial d with I = ⟨d⟩.",
                d,
                p,
                3,
                [
                    "Continue Euclid's algorithm: divide g by the remainder, and so on, until the remainder is zero.",
                    f"The last non-zero remainder, made monic, is {poly_text(d)}.",
                ],
                [
                    (r, "ideal-generator-stopped-at-first-remainder"),
                    (_monic_mod(r, p), "ideal-generator-stopped-at-first-remainder"),
                    (tuple((2 * c) % p for c in d), "ideal-generator-not-monic"),
                    (pmul(pmul(h, u, p), v, p), "ideal-generator-is-lcm"),
                ],
            ),
            number_part(
                f"What is the dimension of the quotient ring Z_{p}[x] / I as a vector space over Z_{p}?",
                dim,
                1,
                [f"Z_{p}[x] / ⟨d⟩ has the basis 1, x, ..., x^({dim} - 1), so its dimension is deg d = {dim}."],
                [
                    (max(len(f), len(g)) - 1, "quotient-dimension-is-degree-of-f"),
                    (dim + 1, "quotient-dimension-counts-the-constant-term-twice"),
                    (len(f) + len(g) - 2 - dim, None),
                    (dim * 2, None),
                ],
                sensible_range=(0, 4),
            ),
            number_part(
                f"How many elements does Z_{p}[x] / I have?",
                p**dim,
                1,
                [
                    f"Each element is a polynomial of degree below {dim}, fixed by {dim} coefficient{'' if dim == 1 else 's'} with {p} possible values each: {p}^{dim} = {p**dim} elements."
                ],
                [
                    (dim * p, "ring-size-is-dimension-times-p"),
                    (p ** (dim + 1), None),
                    (dim, "ring-size-is-dimension"),
                    (p**dim - 1, None),
                    (p ** max(len(f), len(g)) // 1, None),
                ],
                follow_through=f"{p}**part_c",
                sensible_range=(0, None),
            ),
        ],
    )
