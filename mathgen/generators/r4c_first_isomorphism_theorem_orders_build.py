@generator("exd_x_r4c_first_isomorphism_theorem_orders", level=19, presets={"exam": dict(tier="exam")})
def exd_x_r4c_first_isomorphism_theorem_orders(rng, tier="exam"):
    """Exam chain: image order, kernel order, order of a coset in G / ker φ, size of a fibre."""
    check(tier == "exam", f"unknown tier {tier!r}")
    m, n, k, a, b, g = _hom_params(rng, [12, 18, 20, 24, 30, 36, 40, 60], max_size=700)
    image = k // g
    kernel = m * n // image
    t = rng.choice([v for v in range(g, k, g) if v != 0])
    quotient_element = k // gcd(a, k)
    return dict(
        text=rng.choice(
            [
                f"The map φ: Z_{m} × Z_{n} → Z_{k} given by φ(x, y) = {a}x + {b}y (mod {k}) is a homomorphism.",
                f"Let φ(x, y) = {a}x + {b}y (mod {k}), a homomorphism from G = Z_{m} × Z_{n} to Z_{k}.",
                f"Consider the homomorphism φ: Z_{m} × Z_{n} → Z_{k} defined by φ(x, y) = {a}x + {b}y mod {k}.",
            ]
        ),
        parts=[
            number_part(
                "How many elements does the image of φ have?",
                image,
                2,
                [
                    f"The image is generated by {a} and {b} in Z_{k}, so it is ⟨gcd({a}, {b}, {k})⟩ = ⟨{g}⟩ with {image} elements."
                ],
                [
                    (k, "kernel-order-assumes-image-is-the-codomain"),
                    (g, "image-order-is-gcd-not-index"),
                    (k // gcd(a, k), "kernel-order-ignores-one-generator"),
                    (image + 1, None),
                ],
                sensible_range=(0, k),
            ),
            number_part(
                "Find the order of the kernel of φ.",
                kernel,
                1,
                [f"|ker φ| = |G| / |im φ| = {m * n} / {image} = {kernel}."],
                [
                    (image, "kernel-order-is-image-order"),
                    (m * n, "kernel-order-is-group-order"),
                    (m * n // k, "kernel-order-assumes-image-is-the-codomain"),
                    (kernel + 1, None),
                ],
                follow_through=f"{m * n} / part_a",
                sensible_range=(0, m * n),
            ),
            number_part(
                "Find the order of the element (1, 0) + ker φ in the quotient group (Z_%d × Z_%d) / ker φ." % (m, n),
                quotient_element,
                3,
                [
                    "By the first isomorphism theorem the quotient is isomorphic to the image, with (1, 0) + ker φ corresponding to φ(1, 0).",
                    f"φ(1, 0) = {a} in Z_{k}, which has order {k} / gcd({k}, {a}) = {quotient_element}.",
                ],
                [
                    (m, "coset-order-taken-from-the-domain"),
                    (image, "quotient-element-order-is-group-order"),
                    (gcd(a, k), "image-order-is-gcd-not-index"),
                    (quotient_element + 1, None),
                    (quotient_element * 2, None),
                    (quotient_element + 2, None),
                ],
                sensible_range=(0, k),
            ),
            number_part(
                f"How many elements (x, y) of Z_{m} × Z_{n} satisfy φ(x, y) = {t}?",
                kernel,
                2,
                [
                    f"{t} is a multiple of {g}, so it lies in the image, and the solutions form one coset of the kernel: {kernel} elements."
                ],
                [
                    (1, "fibre-size-assumes-injective"),
                    (image, "kernel-order-is-image-order"),
                    (kernel // 2 if kernel % 2 == 0 else None, None),
                    (kernel + 1, None),
                ],
                follow_through="part_b",
                sensible_range=(0, m * n),
            ),
        ],
    )
