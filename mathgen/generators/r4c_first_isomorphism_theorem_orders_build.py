"""Generates `r4c_first_isomorphism_theorem_orders` questions (easy, medium, hard) and the exam chain
`exd_x_r4c_first_isomorphism_theorem_orders`.

``uc2-first-isomorphism-theorem-orders`` (``abstract-algebra``, answer ``number``): the first isomorphism theorem says
G / ker φ is isomorphic to the image of φ, so |G| = |ker φ| · |im φ|. The questions ask for one of the three orders when
the others have to be found.

* easy: φ: Z_m → Z_n, φ(x) = ax; the order of the kernel. The image is the subgroup ⟨a⟩ of Z_n.
* medium: φ: Z_m × Z_n → Z_k, φ(x, y) = ax + by; the order of the kernel. The image is ⟨gcd(a, b, k)⟩.
* hard: φ: U(Z_N) → U(Z_N), φ(x) = x^e; how many elements of the unit group are e-th powers (the order of the image).
  The unit group is often not cyclic, so the count is not φ(N) / gcd(e, φ(N)).
* exam: φ: Z_m × Z_n → Z_k, φ(x, y) = ax + by: (a) |im φ|, (b) |ker φ| (follows from (a)), (c) the order of the element
  (1, 0) + ker φ of the quotient, (d) how many elements map to a given element of the image (follows from (b)).

The tests recount kernels and images by running through every element.
"""

from __future__ import annotations

from math import gcd

from ..core import attempts, check, generator
from ._r4c_kit import number_part, number_question, totient


def _hom_params(rng, ks, max_size=900):
    """(m, n, k, a, b) with k | ma and k | nb, so that (x, y) -> ax + by is a homomorphism Z_m x Z_n -> Z_k."""
    for _ in attempts(1000, "a homomorphism Z_m x Z_n -> Z_k that is not onto"):
        k = rng.choice(ks)
        a, b = rng.randrange(1, k), rng.randrange(1, k)
        g = gcd(gcd(a, b), k)
        if g == 1 or g == k:
            continue
        m = k // gcd(k, a) * rng.randint(1, 3)
        n = k // gcd(k, b) * rng.randint(1, 3)
        if m < 3 or n < 3 or m * n > max_size or m == n:
            continue
        return m, n, k, a, b, g
    raise AssertionError  # pragma: no cover


def _easy(rng):
    for _ in attempts(1000, "a map Z_m -> Z_n with a kernel larger than 1 and an image larger than 1"):
        n = rng.choice([12, 15, 18, 20, 24, 28, 30, 36, 40, 42, 45, 48, 60])
        a = rng.randrange(2, n)
        image = n // gcd(n, a)
        t = rng.randint(2, 12)
        m = image * t
        if 2 <= image < n and m <= 240 and gcd(m, n) != m:
            break
    key = m // image
    check(m * a % n == 0, "the map is not well defined")
    check(key == sum(1 for x in range(m) if x * a % n == 0), "the kernel order differs from the direct count")
    stem = rng.choice(
        [
            f"The map φ: Z_{m} → Z_{n} given by φ(x) = {a}x (mod {n}) is a homomorphism. Find the order of its kernel.",
            f"Let φ: Z_{m} → Z_{n} be the homomorphism φ(x) = {a}x mod {n}. How many elements x of Z_{m} does φ send to 0?",
            f"Z_{m} is mapped into Z_{n} by x ↦ {a}x (mod {n}), which respects addition. Find |ker φ|.",
        ]
    )
    return number_question(
        stem,
        key,
        [
            f"The image is the subgroup of Z_{n} generated by {a}, which has order {n} / gcd({n}, {a}) = {image}.",
            f"By the first isomorphism theorem, |ker φ| = |Z_{m}| / |im φ| = {m} / {image} = {key}.",
        ],
        [
            (image, "kernel-order-is-image-order"),
            (gcd(a, m), "kernel-order-is-gcd-with-the-generator"),
            (m // n if m % n == 0 else None, "kernel-order-assumes-image-is-the-codomain"),
            (gcd(n, a), "kernel-order-is-gcd-with-the-codomain"),
            (key + 1, None),
            (key * 2, None),
        ],
    )


def _medium(rng):
    m, n, k, a, b, g = _hom_params(rng, [12, 18, 20, 24, 30, 36, 40, 45, 60])
    image = k // g
    key = m * n // image
    stem = rng.choice(
        [
            f"The map φ: Z_{m} × Z_{n} → Z_{k} given by φ(x, y) = {a}x + {b}y (mod {k}) is a homomorphism. "
            "Find the order of its kernel.",
            f"φ(x, y) = {a}x + {b}y (mod {k}) defines a homomorphism from Z_{m} × Z_{n} to Z_{k}. "
            "How many pairs (x, y) does it send to 0?",
            f"Let φ: Z_{m} × Z_{n} → Z_{k} be the homomorphism φ(x, y) = {a}x + {b}y mod {k}. Find |ker φ|.",
        ]
    )
    return number_question(
        stem,
        key,
        [
            f"The image is generated by {a} and {b} in Z_{k}, so it is the subgroup ⟨gcd({a}, {b}, {k})⟩ = ⟨{g}⟩ of order {image}.",
            f"|ker φ| = {m * n} / {image} = {key}.",
        ],
        [
            (m * n // k, "kernel-order-assumes-image-is-the-codomain"),
            (image, "kernel-order-is-image-order"),
            (m * n // (k // gcd(a, k)), "kernel-order-ignores-one-generator"),
            (m * n // (k // gcd(b, k)), "kernel-order-ignores-one-generator"),
            (key + 1, None),
            (key * 2, None),
        ],
    )


def _hard(rng):
    for _ in attempts(1000, "a unit group that is not cyclic and a power map that is not onto"):
        n = rng.choice(
            [
                15,
                16,
                20,
                21,
                24,
                28,
                30,
                32,
                35,
                36,
                40,
                42,
                45,
                48,
                52,
                55,
                56,
                60,
                63,
                72,
                75,
                77,
                80,
                84,
                88,
                90,
                96,
                99,
                100,
                104,
                105,
                108,
                112,
                120,
                126,
                132,
                140,
                144,
            ]
        )
        e = rng.choice([2, 3, 4, 5, 6, 8])
        units = [x for x in range(1, n) if gcd(x, n) == 1]
        key = len({pow(x, e, n) for x in units})
        phi = len(units)
        cyclic_guess = phi // gcd(e, phi)
        if 1 < key < phi and key != cyclic_guess:
            break
    kernel = phi // key
    stem = rng.choice(
        [
            f"Let U be the group of units of Z_{n} under multiplication modulo {n}, and let φ: U → U be the homomorphism "
            f"φ(x) = x^{e}. How many elements does the image of φ have?",
            f"Raising to the power {e} is a homomorphism φ(x) = x^{e} of the unit group U of Z_{n} (multiplication mod {n}). "
            "How many distinct values does φ take?",
            f"Let U be the group of units of Z_{n} and consider φ: U → U, φ(x) = x^{e}. Find the order of the image of φ.",
        ]
    )
    return number_question(
        stem,
        key,
        [
            f"|U| = {phi}. The kernel of φ is the set of units with x^{e} = 1, which has {kernel} elements.",
            f"By the first isomorphism theorem, |im φ| = {phi} / {kernel} = {key}.",
        ],
        [
            (cyclic_guess, "image-order-assumes-cyclic-unit-group"),
            (phi // e if phi % e == 0 else None, "image-order-assumes-kernel-has-e-elements"),
            (kernel, "image-order-is-kernel-order"),
            (phi, "image-order-assumes-onto"),
            (key + 1, None),
            (key * 2 if key * 2 < phi else None, None),
        ],
    )


@generator(
    "r4c_first_isomorphism_theorem_orders",
    level=19,
    presets={"easy": dict(tier="easy"), "medium": dict(tier="medium"), "hard": dict(tier="hard")},
)
def r4c_first_isomorphism_theorem_orders(rng, tier="easy"):
    """Kernel and image orders by the first isomorphism theorem; the tiers are described in the module docstring."""
    if tier == "easy":
        return _easy(rng)
    if tier == "medium":
        return _medium(rng)
    check(tier == "hard", f"unknown tier {tier!r}")
    return _hard(rng)


