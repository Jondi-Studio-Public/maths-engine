"""Generates `exd_x_r3j_biquadratic_field_degree` questions: field degrees for a polynomial in x^2.

Skill: `ucv1-field-extension-degree` (exam tier). The practice tiers read a degree off one cubic or one pair of
square roots, with only three possible answers. The exam sets the biquadratic p(x) = q(x^2), q(y) = y^2 - s y + t,
whose two roots in y are positive integers u1 > u2, and asks, in order:

(a) the discriminant of q                                                number, 1 mark
(b) the larger root of q                                                number, 1 mark,  (s + sqrt(part_a)) / 2
(c) [Q(alpha) : Q] for alpha the largest real root of p                 number, 2 marks (alpha = sqrt(u1))
(d) [K : Q] for K the field generated by all the real roots of p        number, 2 marks (K = Q(sqrt(u1), sqrt(u2)))

## Construction: draw the case, then the roots

The case fixes (c) and (d): u1 a square and u2 not ((c) 1, (d) 2); or both non-squares with u1 u2 not a square
((c) 2, (d) 4). The other square-class patterns give (c) = (d) ((1, 1), (2, 2)), so one answer would serve two parts and
they are not drawn. The two cases are drawn at 2:3, then the roots are drawn until they fit the case.
The degrees are read from the square classes of u1, u2 and u1 u2 and are checked in the tests against SymPy's
minimal polynomial of sqrt(u1) + sqrt(u2).
"""

from __future__ import annotations

from math import isqrt

from ..core import attempts, check, generator
from ._exd_x_r3_distinct import distinct_answers
from ._exd_x_r3j_kit import number_part

# (case, weight): see the module docstring
_CASES = [("big-square", 2), ("independent", 3)]
_STEMS = [
    "Let p(x) = {poly}, and write p(x) = q(x^2) where q(y) = {quad}. Let α be the largest real root of p, "
    "and let K be the field generated over the rationals Q by all the real roots of p.",
    "The polynomial p(x) = {poly} equals q(x^2), where q(y) = {quad}. Let α be the largest real root of p(x), "
    "and let K be the smallest field containing Q and every real root of p(x).",
    "Consider p(x) = {poly} = q(x^2), where q(y) = {quad}. Denote by α the largest real root of p, and by K the "
    "field obtained by adjoining all the real roots of p to Q.",
]


def _is_square(n: int) -> bool:
    return isqrt(n) ** 2 == n


def _fits(case: str, u1: int, u2: int) -> bool:
    s1, s2 = _is_square(u1), _is_square(u2)
    if case == "both-square":
        return s1 and s2
    if case == "big-square":
        return s1 and not s2
    if case == "small-square":
        return s2 and not s1
    both_non = not s1 and not s2
    if case == "dependent":
        return both_non and _is_square(u1 * u2)
    return both_non and not _is_square(u1 * u2)


def _quartic_text(s: int, t: int) -> str:
    return f"x^4 − {s}x^2 + {t}"


def _quadratic_text(s: int, t: int) -> str:
    return f"y^2 − {s}y + {t}"


@generator("exd_x_r3j_biquadratic_field_degree", level=17, presets={"exam": {}})
@distinct_answers
def exd_x_r3j_biquadratic_field_degree(rng):
    case = rng.choices([c for c, _ in _CASES], weights=[w for _, w in _CASES])[0]
    for _ in attempts(5000, "two positive roots matching the case"):
        u1, u2 = rng.randint(2, 60), rng.randint(1, 59)
        if u1 > u2 and _fits(case, u1, u2) and u1 + u2 <= 99:
            break
    s, t = u1 + u2, u1 * u2
    disc = s * s - 4 * t
    root = isqrt(disc)
    check(root * root == disc and (s + root) // 2 == u1, "discriminant route disagrees with the roots")

    deg_alpha = 1 if _is_square(u1) else 2
    if _is_square(u1) and _is_square(u2):
        deg_field = 1
    elif _is_square(u1) or _is_square(u2):
        deg_field = 2
    else:
        deg_field = 2 if _is_square(t) else 4

    stem = rng.choice(_STEMS).format(poly=_quartic_text(s, t), quad=_quadratic_text(s, t))
    both_nonsquare = not _is_square(u1) and not _is_square(u2)

    alpha_slips = [(4, "degree-of-polynomial-for-degree-of-extension")]
    if deg_alpha == 1:
        alpha_slips.append((2, "missed-perfect-square"))
    else:
        alpha_slips.append((1, "assumed-roots-rational"))
    if deg_field != deg_alpha:
        alpha_slips.append((deg_field, "field-degree-whole-and-one-root-confused"))
    if deg_field == 1:
        field_slips = [(2, "missed-perfect-square"), (4, "degree-of-polynomial-for-degree-of-extension")]
    elif deg_field == 4:
        field_slips = [(2, "assumed-roots-generate-the-same-field"), (1, "assumed-roots-rational")]
    elif both_nonsquare:
        field_slips = [(4, "multiplied-degrees-ignoring-dependence"), (1, "assumed-roots-rational")]
    else:
        field_slips = [(4, "degree-of-polynomial-for-degree-of-extension"), (1, "assumed-roots-rational")]
    if deg_alpha != deg_field:
        field_slips.append((deg_alpha, "field-degree-whole-and-one-root-confused"))

    parts = [
        number_part(
            "Find the discriminant of q.",
            disc,
            0,
            1,
            [f"Δ = ({s})² − 4({t}) = {disc}."],
            [
                (s * s - t, "dropped-factor-of-four"),
                (s * s + 4 * t, "sign-slip-in-formula"),
                (root, "gave-root-of-discriminant"),
                (4 * t, "gave-part-of-discriminant"),
            ],
            sensible_range=(0, None),
        ),
        number_part(
            "Find the larger root of q.",
            u1,
            0,
            1,
            [f"y = ({s} + √{disc}) / 2 = ({s} + {root}) / 2 = {u1}."],
            [
                (u2, "gave-other-root"),
                (s + root, "dropped-factor-of-two"),
                ((s + disc) // 2, "forgot-square-root"),
                (-u2, "sign-slip-in-formula"),
            ],
            follow_through=f"({s} + sqrt(part_a))/2",
            sensible_range=(0, None),
        ),
        number_part(
            "Find [Q(α) : Q].",
            deg_alpha,
            0,
            2,
            [
                f"α = √{u1}, and {u1} is {'a perfect square, so α is rational and the degree is 1' if deg_alpha == 1 else 'not a perfect square, so x² − ' + str(u1) + ' is the minimal polynomial and the degree is 2'}.",
            ],
            alpha_slips,
        ),
        number_part(
            "Find [K : Q].",
            deg_field,
            0,
            2,
            [
                f"K = Q(√{u1}, √{u2}); "
                + (
                    "both are rational, so K = Q."
                    if deg_field == 1
                    else "one is irrational, so the degree is 2."
                    if _is_square(u1) or _is_square(u2)
                    else f"{t} is a perfect square, so both generate the same quadratic field and the degree is 2."
                    if deg_field == 2
                    else f"{t} is not a perfect square, so the fields are independent and the degree is 4."
                )
            ],
            field_slips,
        ),
    ]
    return dict(text=stem, parts=parts)
