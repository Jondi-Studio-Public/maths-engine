"""Generates `w7c_coding` questions (easy, medium, hard) and the exam chain `exd_x_w7c_coding`.

``uc2-error-correcting-codes`` (``logic-computability-and-information``): Hamming distance, the size and rate of a linear
code, the minimum distance of a small code, the errors a code detects and corrects (d − 1 and ⌊(d − 1)/2⌋), syndrome
decoding of the [7,4] Hamming code and of a small systematic linear code, and the sphere-packing bound. Every answer is a
whole number or a fraction in lowest terms.

* easy: the Hamming distance of two binary words, or of two words over {0, 1, 2} or {0, 1, 2, 3} (where the sum of the
  digit differences is the trap); the number q^k of codewords of a linear code over GF(q) with dimension k; the rate k/n,
  possibly from the number of codewords.
* medium: the minimum distance of a list of binary words (the code is not linear, so the lightest word is not the
  answer); the most errors a listed code can always detect or correct; the same from a stated minimum distance; the
  error position read from the syndrome of a word received for the [7,4] Hamming code.
* hard: decode a received word of the [7,4] Hamming code to its message; the minimum distance of a code from its
  generator matrix (a sum of rows can be lighter than every row) or from its parity-check matrix (the smallest set of
  dependent columns); the sphere-packing bound on the number of codewords or on the length; the minimum distance needed
  to correct t errors and detect s ≥ t; and syndrome decoding for a systematic code whose columns are not in binary
  order.
* exam (``exd_x_w7c_coding``): a systematic generator matrix [I | A]. (a) the number of codewords, (b) the rate,
  (c) the minimum distance, (d) the errors always corrected (follows through from (c)), (e) the message sent when a
  word with one error is received.

Every distance is computed by two independent routes (the lightest non-zero codeword, and the closest pair of
codewords; for a parity-check matrix, the smallest dependent set of columns and the lightest word of the kernel), every
detect/correct count by testing balls against all 2^n words, and every decoded message by searching all codewords for the
unique closest one and re-encoding the message.
"""

