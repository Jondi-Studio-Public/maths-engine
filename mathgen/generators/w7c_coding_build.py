@redrawn
def _easy_distance(rng):
    n = rng.randint(7, 12)
    d = rng.randint(2, n - 3)
    a = rng.getrandbits(n)
    mask = sum(1 << p for p in rng.sample(range(n), d))
    b = a ^ mask
    check(distance(a, b) == d == distance_by_position(word(a, n), word(b, n)), "two ways of counting disagree")
    wrong = [
        ("cod-distance-counts-agreements", n - d),
        ("cod-distance-decimal-difference", abs(a - b)),
        ("cod-distance-first-difference", next(i for i in range(1, n + 1) if word(a, n)[i - 1] != word(b, n)[i - 1])),
        ("cod-distance-weight-of-first-word", weight(a)),
        ("cod-distance-miscounted-by-one", d + 1),
        ("cod-distance-miscounted-by-one", d - 1),
    ]
    working = [
        f"Compare the words position by position: they differ in {d} of the {n} positions.",
        f"The Hamming distance is {d}.",
    ]
    return dict(
        text=phrase(rng, _DISTANCE_STEMS, a=word(a, n), b=word(b, n)), working=working, **value_fields(d, wrong)
    )


_SYMBOL_STEMS = (
    "The words are over the alphabet {alphabet}. Find the Hamming distance between {a} and {b}.",
    "Two words over {alphabet} are {a} and {b}. How many positions differ?",
)


@redrawn
def _easy_distance_symbols(rng):
    q = rng.choice([3, 4])
    n = rng.randint(6, 9)
    d = rng.randint(2, n - 3)
    a = [rng.randrange(q) for _ in range(n)]
    changed = rng.sample(range(n), d)
    a[changed[0]] = rng.choice([0, q - 1])  # from an end symbol, so a change of two or more is possible
    b = list(a)
    for p in changed:
        b[p] = rng.choice([s for s in range(q) if s != a[p]])
    b[changed[0]] = rng.choice([s for s in range(q) if abs(s - a[changed[0]]) >= 2])
    total = sum(abs(x - y) for x, y in zip(a, b))
    check(total != d, "the digit differences sum to the distance")
    check(sum(1 for x, y in zip(a, b) if x != y) == d, "counts disagree")
    alphabet = "{" + ", ".join(map(str, range(q))) + "}"
    wrong = [
        ("cod-distance-sum-of-digit-differences", total),
        ("cod-distance-counts-agreements", n - d),
        ("cod-distance-miscounted-by-one", d + 1),
        ("cod-distance-miscounted-by-one", d - 1),
        ("cod-distance-first-difference", changed and min(changed) + 1),
    ]
    working = [
        "The Hamming distance counts the positions where the symbols differ, however far apart the symbols are.",
        f"The words differ in {d} positions.",
    ]
    text = phrase(rng, _SYMBOL_STEMS, a="".join(map(str, a)), b="".join(map(str, b)), alphabet=alphabet)
    return dict(text=text, working=working, **value_fields(d, wrong))


