"""Generates `scatterplot-describe-association` questions (easy, medium, hard) and the exam chain `sr2a_scatter_assoc_chain`.

Describing the association shown by a drawn scatterplot (ACMGM052, with the strength bands of r behind ACMGM056),
`statistics-probability`, answer ``ordered_list`` of plain words. The scatterplot is a ``cartesian`` figure of 12 points;
the prompt never lists them and never states r (except in the exam chain, where r is given and used).

Words and bands: direction is positive or negative; form is linear or non-linear; strength is strong, moderate or
weak. Strength is the size of the correlation between the data and the pattern the points follow: |r| for a linear
pattern, and the correlation with the fitted curve for a non-linear one. Strong is 0.75 or more, moderate 0.5 to
under 0.75, weak under 0.5. Every drawn set is accepted only when that measure is well clear of 0.5 and 0.75, so
the band does not depend on rounding.

* easy: a linear scatterplot; give the direction, then the strength;
* medium: the pattern may be a curve (accelerating or levelling off, rising or falling); give the direction, then the
  form, then the strength. A curve is accepted only when a quadratic fits clearly better than a line;
* hard: one point P is labelled. Give the direction, the strength with every point included, and whether the
  association becomes stronger or weaker if P is removed. P is either far from an otherwise tight line (removing it
  strengthens the association) or far out along x on the line followed by a loose cluster (removing it weakens it);
* exam (``sr2a_scatter_assoc_chain``): a linear scatterplot with r stated. (a) direction, form and strength, using the
  stated r; (b) the percentage of the variation in y explained by x, 100 r squared to the nearest whole number;
  (c) the percentage left unexplained; (d) the conclusion the data justify.

The registered figure reader recomputes r (and, for a curve, the fit of a quadratic) from the plotted points.
"""

from __future__ import annotations

import math
import re
from fractions import Fraction

from .. import figures
from ..core import attempts, check, generator, phrase
from ._sr2a_kit import (
    clear_of_band_edges,
    corr,
    curvature_gain,
    listed,
    mcq_part,
    number_part,
    list_part,
    strength_band,
)

_POSITIVE = (
    dict(
        x="Study time per week (hours)",
        y="Test score (marks)",
        lead="The scatterplot shows the test score of each of 12 students against the time they spent studying each week.",
    ),
    dict(
        x="Sunshine each day (hours)",
        y="Solar power generated (kWh)",
        lead="The scatterplot shows the solar power generated by a household on each of 12 days against the hours of sunshine that day.",
    ),
    dict(
        x="Practice per week (hours)",
        y="Exam mark (marks)",
        lead="The scatterplot shows the exam mark of each of 12 pianists against the hours they practise each week.",
    ),
)
_NEGATIVE = (
    dict(
        x="Age of car (years)",
        y="Value of car ($ thousand)",
        lead="The scatterplot shows the value of each of 12 used cars of one model against its age.",
    ),
    dict(
        x="Distance from the city centre (km)",
        y="Rent per week ($ tens)",
        lead="The scatterplot shows the weekly rent of each of 12 flats against its distance from the city centre.",
    ),
    dict(
        x="Height of campsite above sea level (hundreds of metres)",
        y="Night temperature (degrees Celsius)",
        lead="The scatterplot shows the night temperature at each of 12 campsites against the height of the campsite.",
    ),
)

_WORDS_NOTE = (
    "Strength: strong means the points lie close to the pattern they follow, moderate means a clear pattern with "
    "noticeable scatter, and weak means only a faint pattern."
)


class Data:
    """One drawn set of points with the facts the answers depend on."""

    def __init__(self, ctx, xs, ys, *, form="linear", direction="positive", label_index=None):
        self.ctx, self.xs, self.ys, self.form, self.direction = ctx, list(xs), list(ys), form, direction
        self.label_index = label_index

    def r(self):
        return corr(self.xs, self.ys)

    def measure(self) -> float:
        """The correlation of the data with the pattern it follows: r, or the fit of a quadratic."""
        if self.form == "linear":
            return corr(self.xs, self.ys)
        return _quad_corr(self.xs, self.ys)

    def figure(self):
        points = [{"at": [x, y]} for x, y in zip(self.xs, self.ys)]
        if self.label_index is not None:
            points[self.label_index]["label"] = "P"
        return figures.cartesian(
            x_range=(0, 14),
            y_range=(0, 24),
            grid=1,
            x_grid=1,
            y_grid=2,
            equal_scale=False,
            points=points,
            x_label=self.ctx["x"],
            y_label=self.ctx["y"],
            alt="a scatterplot of twelve points",
        )


def _quad_corr(xs, ys) -> float:
    import numpy as np

    x, y = np.array(xs, dtype=float), np.array(ys, dtype=float)
    fit = np.polyval(np.polyfit(x, y, 2), x)
    return float(np.corrcoef(y, fit)[0, 1])


def _clip(v):
    return min(23, max(1, int(round(v))))


_BAND_NOISE = {"strong": (0.5, 1.2), "moderate": (2.6, 3.6), "weak": (5.5, 8.0)}
_BAND_RANGE = {"strong": (0.9, 0.985), "moderate": (0.58, 0.70), "weak": (0.15, 0.40)}


def _linear(rng, direction, band, ctx):
    """Twelve points about a straight line, with |r| in the chosen band."""
    for _ in attempts(3000, f"a {band} linear scatterplot"):
        xs = sorted(rng.sample(range(1, 14), 12))
        slope = rng.uniform(1.2, 1.7)
        base = rng.uniform(2, 5)
        sigma = rng.uniform(*_BAND_NOISE[band])
        ys = [_clip(base + slope * (x - 1) + rng.gauss(0, sigma)) for x in xs]
        if direction == "negative":
            ys = [24 - y for y in ys]
        if len(set(ys)) < 6:
            continue
        r = corr(xs, ys)
        lo, hi = _BAND_RANGE[band]
        if not lo <= abs(r) <= hi or (r > 0) != (direction == "positive"):
            continue
        if curvature_gain(xs, ys) > 0.03 or not clear_of_band_edges(r):
            continue
        return Data(ctx, xs, ys, form="linear", direction=direction)
    raise AssertionError  # pragma: no cover


def _curve(rng, direction, band, ctx):
    """Twelve points about a clearly curved monotone pattern; strength is the fit of a quadratic."""
    for _ in attempts(3000, f"a {band} curved scatterplot"):
        xs = sorted(rng.sample(range(1, 14), 12))
        k = rng.uniform(2.2, 3.0)
        convex = rng.random() < 0.5
        if convex:
            f = lambda x: 1 + 21 * (math.exp(k * x / 13) - 1) / (math.exp(k) - 1)  # noqa: E731
        else:
            f = lambda x: 1 + 21 * (1 - math.exp(-k * x / 13)) / (1 - math.exp(-k))  # noqa: E731
        sigma = rng.uniform(*_BAND_NOISE[band])
        ys = [_clip(f(x) + rng.gauss(0, sigma)) for x in xs]
        if direction == "negative":
            ys = [24 - y for y in ys]
        if len(set(ys)) < 6:
            continue
        data = Data(ctx, xs, ys, form="non-linear", direction=direction)
        m = data.measure()
        lo, hi = {"strong": (0.9, 0.99), "moderate": (0.6, 0.72)}[band]
        if not lo <= m <= hi or not clear_of_band_edges(m):
            continue
        if curvature_gain(xs, ys) < 0.06 or (corr(xs, ys) > 0) != (direction == "positive"):
            continue
        return data
    raise AssertionError  # pragma: no cover


def _truth(data):
    direction = "positive" if corr(data.xs, data.ys) > 0 else "negative"
    return direction, data.form, strength_band(data.measure())


def _shift(word, bands=("weak", "moderate", "strong")):
    i = bands.index(word)
    return [bands[j] for j in (i - 1, i + 1) if 0 <= j < 3]


def _other(word, pair):
    return pair[1] if word == pair[0] else pair[0]


# -- easy -------------------------------------------------------------------------------------------------------

_EASY_ASK = (
    "Describe the association between the two variables. Give the direction (positive or negative), then the strength "
    "(strong, moderate or weak), separated by a comma, for example 'positive, weak'. {note}",
    "State the direction of the association (positive or negative) and then its strength (strong, moderate or weak), "
    "separated by a comma, for example 'negative, moderate'. {note}",
)


def _easy(rng):
    for _ in attempts(100, "an easy scatterplot description"):
        direction = rng.choice(["positive", "negative"])
        band = rng.choice(["strong", "moderate", "weak"])
        ctx = rng.choice(_POSITIVE if direction == "positive" else _NEGATIVE)
        data = _linear(rng, direction, band, ctx)
        d, _f, s = _truth(data)
        wrong = [
            ([_other(d, ("positive", "negative")), s], "sr2a-sc-direction-reversed"),
            *[([d, w], "sr2a-sc-strength-one-band-off") for w in _shift(s)],
            ([s, d], "sr2a-sc-fields-swapped"),
            ([_other(d, ("positive", "negative")), _shift(s)[0]], "sr2a-sc-direction-reversed"),
        ]
        text = f"{ctx['lead']} " + phrase(rng, _EASY_ASK, note=_WORDS_NOTE)
        working = [
            f"As {ctx['x'].split(' (')[0].lower()} increases, {ctx['y'].split(' (')[0].lower()} {'increases' if d == 'positive' else 'decreases'}, so the direction is {d}.",
            f"The points {'lie close to' if s == 'strong' else 'follow with noticeable scatter' if s == 'moderate' else 'only faintly follow'} a straight line, so the strength is {s}.",
        ]
        q = listed(text, [d, s], working, wrong, figure=data.figure())
        if q:
            return q
    raise AssertionError  # pragma: no cover


# -- medium -----------------------------------------------------------------------------------------------------

_MEDIUM_ASK = (
    "Describe the association. Give the direction (positive or negative), then the form (linear or non-linear), then "
    "the strength (strong, moderate or weak), separated by commas, for example 'positive, linear, strong'. Use the "
    "spelling 'non-linear'. For a curve, judge strength by how closely the points follow the curve. {note}",
    "State the direction (positive or negative), the form (linear or non-linear) and the strength (strong, moderate "
    "or weak), in that order, separated by commas, for example 'negative, non-linear, moderate'. A curve's strength "
    "is how closely the points follow the curve. {note}",
)


def _medium(rng):
    for _ in attempts(100, "a medium scatterplot description"):
        direction = rng.choice(["positive", "negative"])
        ctx = rng.choice(_POSITIVE if direction == "positive" else _NEGATIVE)
        if rng.random() < 0.5:
            data = _curve(rng, direction, rng.choice(["strong", "strong", "moderate"]), ctx)
        else:
            data = _linear(rng, direction, rng.choice(["strong", "moderate", "weak"]), ctx)
        d, f, s = _truth(data)
        flip = {"linear": "non-linear", "non-linear": "linear"}
        wrong = [
            ([d, flip[f], s], "sr2a-sc-form-misjudged"),
            ([_other(d, ("positive", "negative")), f, s], "sr2a-sc-direction-reversed"),
            *[([d, f, w], "sr2a-sc-strength-one-band-off") for w in _shift(s)],
            ([d, s, f], "sr2a-sc-fields-swapped"),
            ([d, flip[f], _shift(s)[0]], "sr2a-sc-form-misjudged"),
        ]
        text = f"{ctx['lead']} " + phrase(rng, _MEDIUM_ASK, note=_WORDS_NOTE)
        working = [
            f"As the {ctx['x'].split(' (')[0].lower()} increases, the {ctx['y'].split(' (')[0].lower()} tends to {'rise' if d == 'positive' else 'fall'}: {d}.",
            f"The points follow {'a straight line' if f == 'linear' else 'a curve, not a straight line'}: {f}.",
            f"They follow it {'very closely' if s == 'strong' else 'fairly closely' if s == 'moderate' else 'only loosely'}: {s}.",
        ]
        q = listed(text, [d, f, s], working, wrong, figure=data.figure())
        if q:
            return q
    raise AssertionError  # pragma: no cover


# -- hard -------------------------------------------------------------------------------------------------------

_HARD_ASK = (
    "One point is labelled P. Describe the association for all the points shown: give the direction (positive or "
    "negative), then the strength (strong, moderate or weak), then say whether the association would become stronger "
    "or weaker if P were removed. Separate the three words with commas, for example 'negative, moderate, weaker'. {note}",
    "Look at the point labelled P. Give the direction (positive or negative) and the strength (strong, moderate or "
    "weak) of the association with every point included, then whether removing P would make the association "
    "stronger or weaker, as three words separated by commas, for example 'positive, weak, stronger'. {note}",
)


def _vertical_outlier(rng, direction, ctx):
    """A tight line plus one point far off it: removing P strengthens the association."""
    for _ in attempts(60000, "a tight line with one outlier"):
        xs = sorted(rng.sample(range(1, 14), 12))
        slope = rng.uniform(1.2, 1.7)
        base = rng.uniform(2, 5)
        ys = [_clip(base + slope * (x - 1) + rng.gauss(0, 0.8)) for x in xs]
        if direction == "negative":
            ys = [24 - y for y in ys]
        i = rng.randrange(3, 9)
        shift = rng.choice([-1, 1]) * rng.randint(9, 14)
        ys[i] = _clip(ys[i] + shift)
        if abs(ys[i] - (ys[i] - shift)) < 7:
            continue
        data = Data(ctx, xs, ys, form="linear", direction=direction, label_index=i)
        r_with = corr(xs, ys)
        rest_x = [x for k, x in enumerate(xs) if k != i]
        rest_y = [y for k, y in enumerate(ys) if k != i]
        r_without = corr(rest_x, rest_y)
        if (r_with > 0) != (direction == "positive") or (r_without > 0) != (direction == "positive"):
            continue
        if (
            abs(r_with) <= 0.67
            and clear_of_band_edges(r_with)
            and abs(r_without) - abs(r_with) >= 0.2
            and curvature_gain(rest_x, rest_y) <= 0.03
        ):
            return data
    raise AssertionError  # pragma: no cover


def _leverage(rng, direction, ctx):
    """A loose cluster plus one distant point on its trend: removing P weakens the association."""
    for _ in attempts(8000, "a loose cluster with a distant point on the trend"):
        xs = sorted(rng.sample(range(1, 8), 6))
        xs = [*xs, *sorted(rng.sample(range(1, 8), 5)), 13]
        xs = sorted(xs[:-1]) + [13]
        slope = rng.uniform(1.2, 1.7)
        base = rng.uniform(2, 5)
        ys = [_clip(base + slope * (x - 1) + rng.gauss(0, 3.0)) for x in xs]
        ys[-1] = _clip(base + slope * 12 + rng.gauss(0, 0.6))
        if direction == "negative":
            ys = [24 - y for y in ys]
        data = Data(ctx, xs, ys, form="linear", direction=direction, label_index=len(xs) - 1)
        r_with = corr(xs, ys)
        r_without = corr(xs[:-1], ys[:-1])
        if (r_with > 0) != (direction == "positive") or (r_without > 0) != (direction == "positive"):
            continue
        if (
            abs(r_with) >= 0.8
            and clear_of_band_edges(r_with)
            and abs(r_with) - abs(r_without) >= 0.25
            and abs(r_without) >= 0.1
        ):
            return data
    raise AssertionError  # pragma: no cover


def _hard(rng):
    for _ in attempts(60, "a hard scatterplot description"):
        direction = rng.choice(["positive", "negative"])
        ctx = rng.choice(_POSITIVE if direction == "positive" else _NEGATIVE)
        vertical = rng.random() < 0.5
        data = _vertical_outlier(rng, direction, ctx) if vertical else _leverage(rng, direction, ctx)
        i = data.label_index
        xs, ys = data.xs, data.ys
        r_with = corr(xs, ys)
        rest = ([x for k, x in enumerate(xs) if k != i], [y for k, y in enumerate(ys) if k != i])
        r_without = corr(*rest)
        d = "positive" if r_with > 0 else "negative"
        s = strength_band(r_with)
        effect = "stronger" if abs(r_without) > abs(r_with) else "weaker"
        s_without = strength_band(r_without)
        wrong = [
            ([d, s, _other(effect, ("stronger", "weaker"))], "sr2a-sc-outlier-effect-reversed"),
            ([d, s_without, effect], "sr2a-sc-strength-without-outlier"),
            ([_other(d, ("positive", "negative")), s, effect], "sr2a-sc-direction-reversed"),
            *[([d, w, effect], "sr2a-sc-strength-one-band-off") for w in _shift(s)],
            ([d, s_without, _other(effect, ("stronger", "weaker"))], "sr2a-sc-strength-without-outlier"),
        ]
        text = f"{ctx['lead']} " + phrase(rng, _HARD_ASK, note=_WORDS_NOTE)
        if vertical:
            working = [
                f"With every point the pattern is {d} and {s}.",
                "P lies a long way from the line the other points follow, so it spoils the pattern: without it the points lie closer to a line, and the association is stronger.",
            ]
        else:
            working = [
                f"With every point the pattern is {d} and {s}.",
                "P is far from the others and lies on the trend. It is what makes the pattern look strong: the other points are loosely scattered, so without P the association is weaker.",
            ]
        q = listed(text, [d, s, effect], working, wrong, figure=data.figure())
        if q:
            return q
    raise AssertionError  # pragma: no cover


@generator(
    "sr2a_scatter_assoc",
    level=12,
    presets={"easy": dict(tier="easy"), "medium": dict(tier="medium"), "hard": dict(tier="hard")},
)
def sr2a_scatter_assoc(rng, tier="easy"):
    """Describe the association in a drawn scatterplot; the tiers are described in the module docstring."""
    if tier == "easy":
        return _easy(rng)
    if tier == "medium":
        return _medium(rng)
    check(tier == "hard", f"unknown tier {tier!r}")
    return _hard(rng)


# -- exam -------------------------------------------------------------------------------------------------------

_CAUSE_KEY = "There is a {s} {d} linear association, but the data alone do not show that one variable causes the other."
_BANDS_NOTE = "Treat |r| of 0.75 or more as strong, from 0.5 up to 0.75 as moderate, and less than 0.5 as weak."


def _round_pct(r_text: str) -> tuple[int, Fraction]:
    value = Fraction(r_text) ** 2 * 100
    whole = int(value + Fraction(1, 2))
    return whole, value


@generator("sr2a_scatter_assoc_chain", level=12, presets={"exam": dict(tier="exam")})
def sr2a_scatter_assoc_chain(rng, tier="exam"):
    """Exam chain: describe the pattern using the stated r, the variation explained, the rest, and a justified conclusion."""
    check(tier == "exam", f"unknown tier {tier!r}")
    for _ in attempts(200, "a scatterplot chain with enough distractors"):
        direction = rng.choice(["positive", "negative"])
        ctx = rng.choice(_POSITIVE if direction == "positive" else _NEGATIVE)
        band = rng.choice(["strong", "strong", "moderate"])
        data = _linear(rng, direction, band, ctx)
        r_text = f"{data.r():.2f}"
        d, f, s = _truth(data)
        check(strength_band(float(r_text)) == s, "the stated r changes the strength band")
        whole, value = _round_pct(r_text)
        if abs(value - whole) > Fraction(2, 5):
            continue
        r_abs = abs(float(r_text))
        left = 100 - whole
        stem = f"{ctx['lead']} The correlation coefficient for these data is r = {r_text}. {_BANDS_NOTE} {_WORDS_NOTE}"
        yname = ctx["y"].split(" (")[0].lower()
        xname = ctx["x"].split(" (")[0].lower()
        part_a = list_part(
            "Describe the association. Give the direction (positive or negative), then the form (linear or non-linear), "
            "then the strength (strong, moderate or weak), separated by commas, for example 'positive, linear, strong'.",
            [d, f, s],
            2,
            [
                f"The sign of r is {'positive' if d == 'positive' else 'negative'}, the points follow a straight line, and |r| = {abs(float(r_text)):.2f} is {s}."
            ],
            [
                ([_other(d, ("positive", "negative")), f, s], "sr2a-sc-direction-reversed"),
                *[([d, f, w], "sr2a-sc-strength-one-band-off") for w in _shift(s)],
                ([d, "non-linear", s], "sr2a-sc-form-misjudged"),
                ([d, f, "weak" if d == "negative" else s], "sr2a-sc-negative-as-weak"),
            ],
        )
        part_b = number_part(
            f"What percentage of the variation in {yname} is explained by the variation in {xname}? Give the nearest whole number.",
            whole,
            2,
            [f"r squared = {r_text} x {r_text} = {float(r_text) ** 2:.4f}, so about {whole}% is explained."],
            [
                (round(100 * r_abs), "sr2a-sc-r-not-squared"),
                (100 - whole, "sr2a-sc-explained-for-unexplained"),
                (whole + 1, "sr2a-sc-rounding-slip"),
                (whole - 1, "sr2a-sc-rounding-slip"),
                (round(r_abs**2 * 10), "sr2a-sc-percentage-slip"),
            ],
            lo=1,
            sensible=(0, 100),
        )
        part_c = number_part(
            f"What percentage of the variation in {yname} is not explained by {xname}?",
            left,
            1,
            [f"100 - {whole} = {left}."],
            [
                (whole, "sr2a-sc-explained-for-unexplained"),
                (round(100 - 100 * r_abs), "sr2a-sc-r-not-squared"),
                (left + 1, "sr2a-sc-rounding-slip"),
                (left - 1, "sr2a-sc-rounding-slip"),
            ],
            follow="100 - part_b",
            lo=1,
            sensible=(0, 100),
        )
        key = _CAUSE_KEY.format(s=s, d=d)
        part_d = mcq_part(
            "Which conclusion do the data justify?",
            key,
            1,
            ["A correlation describes how two variables vary together; it does not show that one causes the other."],
            [
                (
                    f"Changing {xname} {'will increase' if d == 'positive' else 'will decrease'} {yname}, because the association is {s}.",
                    "sr2a-sc-correlation-is-causation",
                ),
                (
                    f"The association is weak because r is {'negative' if d == 'negative' else 'less than 1'}.",
                    "sr2a-sc-negative-as-weak",
                ),
                (f"About {whole}% of the points lie exactly on the line.", "sr2a-sc-r-squared-as-points-on-line"),
            ],
        )
        if None in (part_a, part_b, part_c, part_d):
            continue
        return dict(text=stem, parts=[part_a, part_b, part_c, part_d], figure=data.figure())
    raise AssertionError  # pragma: no cover


# -- the figure readers -----------------------------------------------------------------------------------------


def _xy(question):
    pts = question.figure["points"]
    return [p["at"][0] for p in pts], [p["at"][1] for p in pts], [p.get("label") for p in pts]


def _read_describe(question) -> str:
    xs, ys, labels = _xy(question)
    r = corr(xs, ys)
    direction = "positive" if r > 0 else "negative"
    text = question.text
    if "labelled P" in text:
        i = labels.index("P")
        r_without = corr([x for k, x in enumerate(xs) if k != i], [y for k, y in enumerate(ys) if k != i])
        effect = "stronger" if abs(r_without) > abs(r) else "weaker"
        return f"{direction}, {strength_band(r)}, {effect}"
    if "form" in text:
        if curvature_gain(xs, ys) >= 0.045:
            return f"{direction}, non-linear, {strength_band(_quad_corr(xs, ys))}"
        return f"{direction}, linear, {strength_band(r)}"
    return f"{direction}, {strength_band(r)}"


def _read_chain(question) -> str:
    xs, ys, _labels = _xy(question)
    r_text = re.search(r"r = (-?\d\.\d\d)", question.text).group(1)
    r = corr(xs, ys)
    whole, _ = _round_pct(r_text)
    direction = "positive" if r > 0 else "negative"
    form = "non-linear" if curvature_gain(xs, ys) >= 0.045 else "linear"
    s = strength_band(float(r_text))
    key = _CAUSE_KEY.format(s=s, d=direction)
    return f"(a) {direction}, {form}, {s}; (b) {whole}; (c) {100 - whole}; (d) {key}"


figures.register_reader("sr2a_scatter_assoc", _read_describe)
figures.register_reader("sr2a_scatter_assoc_chain", _read_chain)
