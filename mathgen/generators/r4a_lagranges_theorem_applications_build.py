"""Generates `r4a_lagranges_theorem_applications` questions (easy, medium, hard) and the exam chain
`exd_x_r4a_lagranges_theorem_applications`.

``uc2-lagranges-theorem-applications`` (``abstract-algebra``, answer ``number``): what Lagrange's theorem forces, with no
group given in full.

* easy: the order of a group from a chain of indices ([G:H], [H:K] and |K|), or the number of left cosets of the cyclic
  subgroup generated by an element of known order.
* medium: how many of 1, ..., n cannot be the order of a subgroup of a group of order n; or how many distinct products hk
  there are when |H| and |K| are coprime (so H ∩ K is trivial by Lagrange, and the product set has |H||K| elements).
* hard: the largest possible order of H ∩ K for two different subgroups of the same order m; or how many orders H ∩ K
  can have when |G|, |H| and |K| are given (a divisor of gcd(|H|, |K|), and at least |H||K|/|G| because |HK| ≤ |G|).
* exam: |G| and |H| are given, with K between them: (a) [G:H], (b) [G:K] from [K:H] (follows through from (a)), (c) |K|
  (follows through from (b)), (d) the largest possible order of a proper subgroup of G that strictly contains K.

Every key is found by the argument above and then re-derived by brute force over the divisors of the orders involved.
"""

from __future__ import annotations

from math import gcd

from ..core import attempts, check, generator, phrase
from ._r4a_alg_kit import number_part, number_question, with_latex


def divisors(n):
    return [d for d in range(1, n + 1) if n % d == 0]


def smallest_prime(n):
    return next(p for p in range(2, n + 1) if n % p == 0)


def largest_prime(n):
    return max(p for p in range(2, n + 1) if n % p == 0 and all(p % q for q in range(2, p)))


# -- easy ----------------------------------------------------------------------------------------------------------

_EASY_TOWER = (
    "G is a finite group with subgroups K ≤ H ≤ G. The index of H in G is {a}, the index of K in H is {b}, and K has "
    "order {c}. Find the order of G.",
    "Let K ≤ H ≤ G be finite groups with [G:H] = {a}, [H:K] = {b} and |K| = {c}. What is |G|?",
)
_EASY_ELEMENT = (
    "G is a group of order {n}, and a is an element of G of order {d}. How many left cosets does the cyclic subgroup "
    "⟨a⟩ have in G?",
    "An element a of a group G of order {n} has order {d}. Find the number of distinct left cosets of ⟨a⟩ in G.",
)


def _easy(rng):
    if rng.random() < 0.55:
        a, b, c = rng.randint(2, 7), rng.randint(2, 6), rng.randint(2, 9)
        total = a * b * c
        check(total == a * b * c and (total // c) % a == 0, "the chain of indices does not multiply to the order")
        slips = [
            (a + b + c, "index-tower-added"),
            (a * b, "index-tower-subgroup-order-forgotten"),
            (a * c, "index-tower-middle-index-forgotten"),
            (b * c, "index-tower-top-index-forgotten"),
        ]
        return number_question(
            phrase(rng, _EASY_TOWER, a=a, b=b, c=c),
            total,
            [f"|H| = [H:K]·|K| = {b}·{c} = {b * c}.", f"|G| = [G:H]·|H| = {a}·{b * c} = {total}."],
            slips,
            lo=1,
        )
    d = rng.choice([4, 6, 8, 9, 10, 12, 14, 15, 18])
    cosets = rng.randint(3, 9)
    n = d * cosets
    check(len({(k * cosets) % n for k in range(n)}) == d, "the cyclic model of the subgroup has the wrong order")
    slips = [
        (d, "index-confused-with-subgroup-order"),
        (n - d, None),
        (cosets + 1, None),
        (n, "index-of-trivial-subgroup-confusion"),
    ]
    return number_question(
        phrase(rng, _EASY_ELEMENT, n=n, d=d),
        cosets,
        [f"⟨a⟩ has order {d}, the order of a.", f"By Lagrange the number of left cosets is {n}/{d} = {cosets}."],
        slips,
        lo=1,
    )


# -- medium --------------------------------------------------------------------------------------------------------

_MED_RULED_OUT = (
    "G is a finite group of order {n}. Of the integers 1, 2, ..., {n}, how many can Lagrange's theorem rule out as "
    "the order of a subgroup of G?",
    "How many of the integers 1, 2, ..., {n} are impossible, by Lagrange's theorem, as the order of a subgroup of a group "
    "of order {n}?",
)
_MED_PRODUCT = (
    "H and K are subgroups of a finite group G of order {n}, with |H| = {a} and |K| = {b}. How many different elements "
    "can be written as a product hk with h in H and k in K?",
    "Let G be a group of order {n} with subgroups H and K, where |H| = {a} and |K| = {b}. Find the number of distinct "
    "products hk (h in H, k in K).",
)


def _medium(rng):
    if rng.random() < 0.5:
        n = rng.choice([12, 18, 20, 24, 28, 30, 36, 40, 42, 45, 48, 50, 56, 60])
        allowed = len(divisors(n))
        key = n - allowed
        check(key == sum(1 for m in range(1, n + 1) if n % m != 0), "ruled-out count differs from the direct count")
        slips = [
            (allowed, "ruled-out-count-uses-allowed"),
            (key - 2, "ruled-out-count-drops-ends"),
            (n - allowed + 1, None),
            (n - allowed - 1, None),
        ]
        return number_question(
            phrase(rng, _MED_RULED_OUT, n=n),
            key,
            [
                f"{n} has {allowed} divisors, so {allowed} of the integers 1, ..., {n} are allowed.",
                f"The other {n} - {allowed} = {key} are ruled out.",
            ],
            slips,
            lo=0,
        )
    for _ in attempts(500, "coprime subgroup orders whose product fits in the group"):
        a, b = rng.choice([3, 4, 5, 7, 8, 9, 11]), rng.choice([2, 3, 4, 5, 6, 7, 9, 10])
        if gcd(a, b) != 1:
            continue
        n = a * b * rng.randint(1, 3)
        break
    key = a * b
    check(key <= n and gcd(a, b) == 1, "product set does not fit or orders are not coprime")
    slips = [
        (a + b - 1, "product-set-size-by-inclusion-exclusion"),
        (a + b, "product-set-size-by-inclusion-exclusion"),
        (max(a, b), "product-set-size-largest-factor"),
        (n, "product-set-size-whole-group"),
    ]
    return number_question(
        phrase(rng, _MED_PRODUCT, n=n, a=a, b=b),
        key,
        [
            f"H ∩ K is a subgroup of both H and K, so its order divides gcd({a}, {b}) = 1: H ∩ K is trivial.",
            f"The map (h, k) → hk is then one-to-one, so there are {a}·{b} = {key} products.",
        ],
        slips,
        lo=1,
    )


# -- hard ----------------------------------------------------------------------------------------------------------

_HARD_INTERSECT = (
    "G is a finite group with two different subgroups H and K, each of order {m}. What is the largest possible order of "
    "H ∩ K?",
    "Two distinct subgroups H and K of a finite group both have order {m}. Find the greatest order that H ∩ K can have.",
)
_HARD_COUNT = (
    "G is a group of order {n} with subgroups H and K of orders {a} and {b}. By Lagrange's theorem, and because the set HK "
    "of products has at most {n} elements, how many different orders can H ∩ K have?",
    "Let |G| = {n}, |H| = {a} and |K| = {b}. Using only Lagrange's theorem and the fact that |HK| = |H||K|/|H ∩ K| cannot "
    "exceed |G|, how many values are possible for |H ∩ K|?",
)


def _hard(rng):
    if rng.random() < 0.4:
        m = rng.choice([12, 18, 20, 24, 28, 30, 36, 40, 45, 50, 56, 60, 63, 72, 75, 84, 90])
        key = m // smallest_prime(m)
        direct = max(d for d in divisors(m) if d < m)
        check(key == direct, "the largest proper divisor differs from m over its smallest prime")
        slips = [
            (m // 2, "intersection-order-halved-regardless"),
            (m // largest_prime(m), "intersection-order-uses-largest-prime"),
            (m - 1, "intersection-order-one-less"),
            (m, "intersection-order-whole-subgroup"),
        ]
        return number_question(
            phrase(rng, _HARD_INTERSECT, m=m),
            key,
            [
                f"H ∩ K is a proper subgroup of H, so |H ∩ K| is a proper divisor of {m}.",
                f"The largest proper divisor of {m} is {m}/{smallest_prime(m)} = {key}, which is possible.",
            ],
            slips,
            lo=1,
        )
    for _ in attempts(2000, "orders with two to five possible intersection orders"):
        n = rng.choice([60, 72, 90, 96, 120, 144, 180, 240])
        a, b = rng.choice(divisors(n)), rng.choice(divisors(n))
        g = gcd(a, b)
        possible = [d for d in divisors(g) if d * n >= a * b]
        ignoring_bound = len(divisors(g))
        ignoring_lagrange = sum(1 for d in range(1, g + 1) if d * n >= a * b)
        if (
            2 <= len(possible) <= 5
            and ignoring_bound != len(possible)
            and ignoring_lagrange != len(possible)
            and a != b
            and a * b > n
        ):
            break
    key = len(possible)
    check(
        all((a * b) // d <= n and (a * b) % d == 0 for d in possible), "a possible intersection order gives |HK| > |G|"
    )
    slips = [
        (ignoring_bound, "intersection-count-ignores-product-bound"),
        (ignoring_lagrange, "intersection-count-ignores-divisibility"),
        (key - 1, "intersection-count-drops-the-extreme"),
        (key + 1, None),
    ]
    return number_question(
        phrase(rng, _HARD_COUNT, n=n, a=a, b=b),
        key,
        [
            f"|H ∩ K| divides gcd({a}, {b}) = {g}, so it is one of {', '.join(map(str, divisors(g)))}.",
            f"|HK| = {a * b}/|H ∩ K| ≤ {n} needs |H ∩ K| ≥ {a * b}/{n}, which leaves {', '.join(map(str, possible))}: {key} values.",
        ],
        slips,
        lo=1,
    )


@generator(
    "r4a_lagranges_theorem_applications",
    level=19,
    presets={"easy": dict(tier="easy"), "medium": dict(tier="medium"), "hard": dict(tier="hard")},
)
@with_latex
def r4a_lagranges_theorem_applications(rng, tier="easy"):
    """What Lagrange's theorem forces; the tiers are described in the module docstring."""
    if tier == "easy":
        return _easy(rng)
    if tier == "medium":
        return _medium(rng)
    check(tier == "hard", f"unknown tier {tier!r}")
    return _hard(rng)


# -- exam -------------------------------------------------------------------------------------------------------


@generator("exd_x_r4a_lagranges_theorem_applications", level=19, presets={"exam": dict(tier="exam")})
@with_latex
def exd_x_r4a_lagranges_theorem_applications(rng, tier="exam"):
    """Exam chain: index, index of an intermediate subgroup, its order and the largest subgroup above it."""
    check(tier == "exam", f"unknown tier {tier!r}")
    for _ in attempts(1000, "orders with a composite index of K and room above it"):
        index_k = rng.choice([6, 8, 9, 10, 12, 14, 15, 16, 18, 20])
        t = rng.randint(2, 5)
        h = rng.randint(2, 6)
        order_k = h * t
        n = index_k * order_k
        index_h = n // h
        if n <= 400 and smallest_prime(index_k) != largest_prime(index_k):
            break
    check(index_h == index_k * t, "[G:H] differs from [G:K][K:H]")
    key_d = n // smallest_prime(index_k)
    direct = max(d for d in divisors(n) if d < n and d % order_k == 0 and d > order_k)
    check(key_d == direct, "largest subgroup order above K differs from the direct search over divisors")
    return dict(
        text=(
            f"G is a finite group of order {n}. H and K are subgroups of G with H ≤ K, where |H| = {h} and the index "
            f"of H in K is {t}."
        ),
        parts=[
            number_part(
                "Find the index of H in G.",
                index_h,
                2,
                [f"[G:H] = |G|/|H| = {n}/{h} = {index_h}."],
                [
                    (h, "index-confused-with-subgroup-order"),
                    (n - h, None),
                    (index_h + t, None),
                    (n, "index-of-trivial-subgroup-confusion"),
                ],
                sensible_range=(0, None),
            ),
            number_part(
                "Find the index of K in G.",
                index_k,
                2,
                [f"[G:H] = [G:K][K:H], so [G:K] = {index_h}/{t} = {index_k}."],
                [
                    (index_h - t, "index-tower-subtracted"),
                    (index_h * t, "index-tower-multiplied-wrong-way"),
                    (t, None),
                    (index_h, None),
                ],
                follow_through=f"part_a/{t}",
                sensible_range=(0, None),
            ),
            number_part(
                "Find the order of K.",
                order_k,
                1,
                [f"|K| = |G|/[G:K] = {n}/{index_k} = {order_k}."],
                [(index_k, "index-confused-with-subgroup-order"), (n // t, None), (h, None), (order_k + h, None)],
                follow_through=f"{n}/part_b",
                sensible_range=(0, None),
            ),
            number_part(
                "Find the largest possible order of a subgroup L of G with K strictly inside L and L not equal to G.",
                key_d,
                3,
                [
                    f"|L| is a multiple of |K| = {order_k} and a proper divisor of {n}, with [G:L] dividing [G:K] = {index_k}.",
                    f"[G:L] is a proper divisor of {index_k} greater than 1, as small as possible: {smallest_prime(index_k)}, so |L| = {n}/{smallest_prime(index_k)} = {key_d}.",
                ],
                [
                    (n // largest_prime(index_k), "largest-subgroup-uses-largest-prime"),
                    (n // 2 if n % 2 == 0 else None, "largest-subgroup-halves-regardless"),
                    (n - order_k, None),
                    (n, None),
                ],
                sensible_range=(0, None),
            ),
        ],
    )
