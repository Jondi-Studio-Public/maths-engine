"""Generates `ucv1-sigma-algebra-closure` and `ucv1-product-measure-rectangle` questions on finite measure
theory.

Both skills are finite, mechanically checkable measure-theory slices (the
skills' stated exclusions rule out Lebesgue measure, Caratheodory extension
and infinite constructions).

``ucv1-sigma-algebra-closure`` (mcq): decide whether a supplied finite family of subsets of a small universe
is closed under complement and finite union. The answer space is exactly the four combinations named, ``fails
complement``, ``fails union``, ``fails both`` -- and every draw offers all four as options (three distractors,
always). Construction never trusts a single free random draw to land on a rare class: each class is built from
an explicit recipe (a genuine finite algebra generated by a partition; drop one block to break complement
only; pair two unrelated sets with their complements to break union only; combine both breaks), and the SAME
closure predicate -- computed by brute force over the concrete drawn sets, never by trusting the recipe -- is
the independent check that confirms the recipe actually produced the claimed class. That predicate is the one
the oracle (parsing only the rendered question) re-implements a second time from scratch.

``ucv1-product-measure-rectangle`` (fraction): two finite measure spaces X, Y
each carry a stated weight (a positive fraction, not required to sum to 1 --
the skill's stated exclusion of an "independence interpretation" is exactly
because these are not probability measures) on their elements. For supplied
subsets A of X and B of Y, the product measure of the rectangle A x B is
mu(A) * nu(B). Every tier is exact ``Fraction`` arithmetic; the independent
check recomputes each factor a second way (total measure minus the
complement's weight) rather than re-summing the same terms.
"""

from __future__ import annotations

from fractions import Fraction
from itertools import combinations

from ..core import check, check_pairwise_distinct, generator, pick_distractors, rational_text

# Shared small helpers.


def _fraction_payload(value: Fraction) -> tuple[dict, str]:
    value = Fraction(value)
    return {"p": value.numerator, "q": value.denominator}, rational_text(value)


# ---------------------------------------------------------------------------
# ucv1-sigma-algebra-closure

_CLOSED_BOTH = "closed under both"
_FAILS_COMPLEMENT = "fails complement"
_FAILS_UNION = "fails union"
_FAILS_BOTH = "fails both"
_ALL_CLASSES = [_CLOSED_BOTH, _FAILS_COMPLEMENT, _FAILS_UNION, _FAILS_BOTH]


def _closure_class(universe: frozenset, family: list[frozenset]) -> str:
    """Brute-force, from the concrete sets alone: never trusts how the
    family was constructed."""
    fam_set = set(family)
    comp_ok = all((universe - a) in fam_set for a in family)
    union_ok = True
    for a, b in combinations(family, 2):
        if (a | b) not in fam_set:
            union_ok = False
            break
    if union_ok:
        for a in family:
            if (a | a) not in fam_set:
                union_ok = False
                break
    if comp_ok and union_ok:
        return _CLOSED_BOTH
    if comp_ok:
        return _FAILS_UNION
    if union_ok:
        return _FAILS_COMPLEMENT
    return _FAILS_BOTH


def _set_text(s: frozenset) -> str:
    if not s:
        return "the empty set"
    return "{" + ", ".join(str(x) for x in sorted(s)) + "}"


def _build_family(rng, n: int, target: str, near_miss: bool):
    """Construct a family of subsets of {1, ..., n} realising `target`,
    verified afterward by `_closure_class` (the independent, brute-force
    route -- these recipes never call it while deciding what to build)."""
    universe = frozenset(range(1, n + 1))
    # A 2-block partition, chosen so neither block is empty.
    split = rng.randint(1, n - 1)
    elements = list(range(1, n + 1))
    rng.shuffle(elements)
    b1 = frozenset(elements[:split])
    b2 = universe - b1

    if target == _CLOSED_BOTH:
        family = [frozenset(), b1, b2, universe]
        rng.shuffle(family)
        return family

    if target == _FAILS_COMPLEMENT:
        # Drop b1 from the algebra: b2's complement (b1) is now missing.
        # Add a near-miss extra set (b2 minus one element on the harder
        # tiers, an unrelated random proper subset on the easier ones) --
        # neither its complement lands in the family either, and it is a
        # SUBSET of an existing family member so every union with an
        # existing member is already that member (union stays closed).
        if near_miss and len(b2) >= 2:
            drop = rng.choice(sorted(b2))
            extra = b2 - {drop}
        else:
            k = rng.randint(1, max(1, len(b2) - 1)) if len(b2) > 1 else 1
            extra = frozenset(rng.sample(sorted(b2), k)) if len(b2) > 1 else frozenset()
        family = [frozenset(), b2, universe, extra]
        family = [s for i, s in enumerate(family) if s not in family[:i]]
        rng.shuffle(family)
        return family

    if target == _FAILS_UNION:
        for _attempt in range(200):
            if near_miss:
                a = frozenset(rng.sample(elements, rng.randint(1, n - 1)))
                b = a ^ frozenset([rng.choice(elements)])  # one-element near miss of a
                b = frozenset(x for x in b if x in universe)
                if not b or b == universe:
                    continue
            else:
                a = frozenset(rng.sample(elements, rng.randint(1, n - 1)))
                b = frozenset(rng.sample(elements, rng.randint(1, n - 1)))
            if a == b or a == universe - b:
                continue
            family = [a, universe - a, b, universe - b]
            family = [s for i, s in enumerate(family) if s not in family[:i]]
            if len(family) < 3:
                continue
            if _closure_class(universe, family) == _FAILS_UNION:
                return family
        raise RuntimeError("p15c_sigma_algebra_closure: could not realise fails-union")

    # _FAILS_BOTH: drop-one-block (breaks complement) plus an unrelated
    # extra set that also breaks union.
    for _attempt in range(200):
        if near_miss and len(b2) >= 2:
            drop = rng.choice(sorted(b2))
            extra1 = b2 - {drop}
        else:
            extra1 = frozenset(rng.sample(sorted(b2), rng.randint(1, len(b2)))) if b2 else frozenset()
        extra2 = frozenset(rng.sample(elements, rng.randint(1, n - 1)))
        family = [frozenset(), b2, universe, extra1, extra2]
        family = [s for i, s in enumerate(family) if s not in family[:i]]
        if len(family) < 4:
            continue
        if _closure_class(universe, family) == _FAILS_BOTH:
            return family
    raise RuntimeError("p15c_sigma_algebra_closure: could not realise fails-both")


def _find_complementary_pair(universe, family):
    """The first (i, j) with family[j] == universe - family[i], if any --
    the ONLY pair an indirect "complement of ..." clause may honestly
    describe. Returns None when no such pair exists in the drawn family.
    Prefers a NON-trivial pair (neither side the empty set or the whole
    universe), so the indirection is a genuine computation rather than
    "the complement of the empty set is the universe" every time."""
    trivial = (frozenset(), universe)
    fallback = None
    for i, a in enumerate(family):
        comp = universe - a
        for j, b in enumerate(family):
            if j != i and b == comp:
                if a not in trivial and b not in trivial:
                    return i, j
                fallback = fallback or (i, j)
    return fallback


def _label_family(family: list[frozenset], indirect_pair):
    """Returns (labels, clauses). `indirect_pair`, when not None, is
    (i, j) with family[j] == universe - family[i] (verified by the caller):
    clause j is rendered as "the complement of A_i within the universe"
    instead of listing its elements -- the learner must compute it before
    checking anything. Always None when no such pair exists in the family,
    so the clause is only ever indirect when it is honestly true."""
    labels = [f"A{i + 1}" for i in range(len(family))]
    clauses = []
    indirect_j = indirect_pair[1] if indirect_pair else None
    indirect_i = indirect_pair[0] if indirect_pair else None
    for i, (label, s) in enumerate(zip(labels, family)):
        if i == indirect_j:
            clauses.append(f"{label} = the complement of {labels[indirect_i]} within the universe")
        else:
            clauses.append(f"{label} = {_set_text(s)}")
    return labels, clauses


def _build(rng, n: int, near_miss: bool, indirect_last: bool):
    target = rng.choice(_ALL_CLASSES)
    family = _build_family(rng, n, target, near_miss)
    universe = frozenset(range(1, n + 1))
    indirect_pair = _find_complementary_pair(universe, family) if indirect_last else None
    if indirect_pair is not None:
        i, j = indirect_pair
        check(
            family[j] == universe - family[i], "p15c_sigma_algebra_closure: indirect clause does not name the drawn set"
        )

    derived = _closure_class(universe, family)
    check(derived == target, f"p15c_sigma_algebra_closure: recipe for {target!r} produced {derived!r}")

    labels, clauses = _label_family(family, indirect_pair)
    family_text = "; ".join(clauses)
    text = (
        f"The universe is U = {{1, ..., {n}}}. A family of subsets is given: {family_text}. "
        "Decide whether this family is closed under complement (within U) and finite union: "
        "choose closed under both, fails complement, fails union, or fails both."
    )
    distractors = [c for c in _ALL_CLASSES if c != target]
    working = [
        f"Family (as concrete subsets of U): {', '.join(_set_text(s) for s in family)}.",
        f"Complement check (each set's complement within U also in the family): "
        f"{'holds' if derived in (_CLOSED_BOTH, _FAILS_UNION) else 'fails'}.",
        f"Finite-union check (every pairwise union stays in the family): "
        f"{'holds' if derived in (_CLOSED_BOTH, _FAILS_COMPLEMENT) else 'fails'}.",
        f"Classification: {target}.",
    ]
    return dict(
        text=text,
        latex=f"plain:{text}",
        answer=target,
        answer_text=target,
        answer_latex=f"plain:{target}",
        working=working,
        distractors=pick_distractors(target, distractors, n=3),
    )


@generator(
    "p15c_sigma_algebra_closure",
    level=17,
    presets={
        "easy": dict(n=3, near_miss=False, indirect_last=False),
        # medium: same universe size as easy -- the escalation is NOT size. One set is defined
        # INDIRECTLY, as "the complement of A_i", so the learner must compute that complement before
        # they can check whether ITS union with another listed set stays inside the family. Easy
        # never does this: every set is given directly.
        "medium": dict(n=3, near_miss=False, indirect_last=True),
        "hard": dict(n=4, near_miss=True, indirect_last=False),
        "exam": dict(n=4, near_miss=True, indirect_last=True),
    },
)
def p15c_sigma_algebra_closure(rng, n=3, near_miss=False, indirect_last=False):
    return _build(rng, n, near_miss, indirect_last)


# ---------------------------------------------------------------------------
# ucv1-product-measure-rectangle

_WEIGHT_DENOMS = [2, 3, 4, 5, 6]


def _draw_weights(rng, n: int) -> list[Fraction]:
    return [Fraction(rng.randint(1, 5), rng.choice(_WEIGHT_DENOMS)) for _ in range(n)]


def _weight_text(labels, weights, prefix) -> str:
    parts = [f"{prefix}({lbl}) = {rational_text(w)}" for lbl, w in zip(labels, weights)]
    return ", ".join(parts)


def _measure_via_complement(total: Fraction, weights: list[Fraction], idx: set[int]) -> Fraction:
    """Independent route: total measure minus the weight of everything NOT
    in idx -- a different identity from directly summing the included
    weights, so a slip in one route does not silently confirm the other."""
    excluded = sum((weights[i] for i in range(len(weights)) if i not in idx), Fraction(0))
    return total - excluded


def _direct_measure(weights: list[Fraction], idx: set[int]) -> Fraction:
    return sum((weights[i] for i in idx), Fraction(0))


def _labels(n: int, prefix: str) -> list[str]:
    return [f"{prefix}{i + 1}" for i in range(n)]


def _build_product(rng, nx: int, ny: int, kind: str):
    for _attempt in range(200):
        result = _try_build_product(rng, nx, ny, kind)
        if result is not None:
            return result
    raise RuntimeError("p15c_product_measure_rectangle: could not draw distinct candidates")


def _try_build_product(rng, nx: int, ny: int, kind: str):
    x_labels = _labels(nx, "x")
    y_labels = _labels(ny, "y")
    x_weights = _draw_weights(rng, nx)
    y_weights = _draw_weights(rng, ny)
    x_total = sum(x_weights, Fraction(0))
    y_total = sum(y_weights, Fraction(0))

    if kind == "singleton":
        a_idx = {rng.randrange(nx)}
        b_idx = {rng.randrange(ny)}
        a_text = f"A = {{{x_labels[list(a_idx)[0]]}}}"
        b_text = f"B = {{{y_labels[list(b_idx)[0]]}}}"
    elif kind == "sum":
        a_idx = set(rng.sample(range(nx), min(2, nx)))
        b_idx = set(rng.sample(range(ny), min(2, ny)))
        a_text = "A = {" + ", ".join(x_labels[i] for i in sorted(a_idx)) + "}"
        b_text = "B = {" + ", ".join(y_labels[i] for i in sorted(b_idx)) + "}"
    elif kind == "complement":
        excl_x = rng.randrange(nx)
        a_idx = set(range(nx)) - {excl_x}
        b_idx = set(rng.sample(range(ny), min(2, ny)))
        a_text = f"A = X minus {{{x_labels[excl_x]}}} (every element of X except {x_labels[excl_x]})"
        b_text = "B = {" + ", ".join(y_labels[i] for i in sorted(b_idx)) + "}"
    else:  # "dedup_and_complement" (exam)
        c1 = rng.sample(range(nx), min(2, nx))
        overlap = c1[0]
        remaining = [i for i in range(nx) if i not in c1]
        c2 = [overlap] + ([rng.choice(remaining)] if remaining else [])
        a_idx = set(c1) | set(c2)
        a_text = "A = {" + ", ".join(x_labels[i] for i in c1) + "} ∪ {" + ", ".join(x_labels[i] for i in c2) + "}"
        excl_y = rng.randrange(ny)
        b_idx = set(range(ny)) - {excl_y}
        b_text = f"B = Y minus {{{y_labels[excl_y]}}} (every element of Y except {y_labels[excl_y]})"

    mu_a = _direct_measure(x_weights, a_idx)
    nu_b = _direct_measure(y_weights, b_idx)
    mu_a_check = _measure_via_complement(x_total, x_weights, a_idx)
    nu_b_check = _measure_via_complement(y_total, y_weights, b_idx)
    check(mu_a == mu_a_check, "p15c_product_measure_rectangle: mu(A) mismatch")
    check(nu_b == nu_b_check, "p15c_product_measure_rectangle: nu(B) mismatch")

    product = mu_a * nu_b
    check(product == mu_a_check * nu_b_check, "p15c_product_measure_rectangle: product mismatch")

    trap_values = [mu_a + nu_b, mu_a, nu_b, x_total * y_total]
    if len(set([product, *trap_values])) != 5:
        return None  # a candidate collided with the answer or another candidate -- redraw

    answer, answer_text = _fraction_payload(product)
    candidates = [
        rational_text(mu_a + nu_b),  # sum instead of product
        rational_text(mu_a),  # forgot to multiply by nu(B)
        rational_text(nu_b),  # forgot to multiply by mu(A)
        rational_text(x_total * y_total),  # used the whole spaces
    ]
    check_pairwise_distinct(product, *trap_values, msg="p15c_product_measure_rectangle: a candidate collides")

    final_distractors = pick_distractors(answer_text, candidates)
    answer_is_int = "/" not in answer_text
    if not any(("/" not in d) == answer_is_int for d in final_distractors):
        return None  # the answer would be the only option of its integer/fraction shape

    text = (
        f"X = {{{', '.join(x_labels)}}} is a finite measure space with "
        f"{_weight_text(x_labels, x_weights, 'mu')}. "
        f"Y = {{{', '.join(y_labels)}}} is a finite measure space with "
        f"{_weight_text(y_labels, y_weights, 'nu')}. "
        f"{a_text}. {b_text}. "
        "Compute the product measure (mu x nu)(A x B) = mu(A) x nu(B), as a fraction."
    )
    working = [
        f"mu(A) = {rational_text(mu_a)}, nu(B) = {rational_text(nu_b)}.",
        f"(mu x nu)(A x B) = mu(A) x nu(B) = {answer_text}.",
    ]
    return dict(
        text=text,
        latex=f"plain:{text}",
        answer=answer,
        answer_text=answer_text,
        answer_latex=answer_text,
        working=working,
        distractors=final_distractors,
    )


@generator(
    "p15c_product_measure_rectangle",
    level=17,
    presets={
        "easy": dict(nx=2, ny=2, kind="singleton"),
        "medium": dict(nx=3, ny=3, kind="sum"),
        "hard": dict(nx=3, ny=3, kind="complement"),
        "exam": dict(nx=4, ny=4, kind="dedup_and_complement"),
    },
)
def p15c_product_measure_rectangle(rng, nx=2, ny=2, kind="singleton"):
    return _build_product(rng, nx, ny, kind)
