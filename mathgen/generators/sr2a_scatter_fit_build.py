_SLOPES = (0.5, 1, 1.5, 2)


def _clip(v):
    return min(23, max(1, int(round(v))))


def _fmt(v: float) -> str:
    return str(int(v)) if v == int(v) else f"{v:.1f}"


def _fmt_paren(v: float) -> str:
    """`_fmt` with a negative value bracketed, so it can follow an operator."""
    return paren_negative(int(v) if v == int(v) else round(v, 1))


def _dp(v: float) -> int:
    return 0 if v == int(v) else 1


class Fit:
    """One scatterplot with its drawn line ``y = c + m x``."""

    def __init__(self, ctx, c, m, xs, ys, p_index=None):
        self.ctx, self.c, self.m, self.xs, self.ys, self.p = ctx, c, m, list(xs), list(ys), p_index

    @property
    def y2(self):
        return self.c + 10 * self.m

    def at(self, x):
        return self.c + self.m * x

    def figure(self):
        pts = [{"at": [x, y]} for x, y in zip(self.xs, self.ys)]
        if self.p is not None:
            pts[self.p]["label"] = "P"
        return figures.cartesian(
            x_range=(0, 12),
            y_range=(0, 24),
            grid=1,
            x_grid=1,
            y_grid=2,
            equal_scale=False,
            points=pts,
            lines=[{"through": [[0, self.c], [10, self.y2]]}],
            x_label=self.ctx["x"],
            y_label=self.ctx["y"],
            alt="a scatterplot of ten points with a line of best fit",
        )


def _ols(xs, ys):
    n = len(xs)
    mx, my = sum(xs) / n, sum(ys) / n
    m = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs)
    return my - m * mx, m


def _draw(rng, direction=None):
    """A drawn scatterplot and line; the least-squares line of the points is within 0.2 of the drawn one."""
    for _ in attempts(3000, "a scatterplot close to its drawn line"):
        positive = rng.random() < 0.5 if direction is None else direction == "positive"
        ctx = rng.choice(_POSITIVE if positive else _NEGATIVE)
        m = rng.choice(_SLOPES) * (1 if positive else -1)
        lo, hi = (1, 22 - 10 * m) if positive else (1 - 10 * m, 22)
        c = rng.randint(max(1, int(lo)), int(hi)) if int(hi) >= int(lo) else None
        if c is None:
            continue
        xs = sorted(rng.sample(range(1, 12), 10))
        sigma = rng.uniform(1.0, 2.2)
        ys = [_clip(c + m * x + rng.gauss(0, sigma)) for x in xs]
        oc, om = _ols(xs, ys)
        if abs(om - m) > 0.2 or abs(oc - c) > 1.0 or abs(corr(xs, ys)) < 0.9:
            continue
        return Fit(ctx, c, m, xs, ys)
    raise AssertionError  # pragma: no cover


def _whole(fit, x):
    return (fit.m * x) == int(fit.m * x)


# -- easy -------------------------------------------------------------------------------------------------------

_EASY_ASK = (
    "The line of best fit is drawn on the scatterplot. What is the gradient of the line?",
    "A line of best fit has been drawn on the scatterplot. Find its gradient.",
)


def _easy(rng):
    for _ in attempts(100, "an easy line-of-best-fit question"):
        fit = _draw(rng)
        m, c = fit.m, fit.c
        wrong = [
            (-m, "sr2a-fl-slope-sign"),
            (c, "sr2a-fl-slope-as-intercept"),
            (round(1 / abs(m), 1) * (1 if m > 0 else -1), "sr2a-fl-slope-run-over-rise"),
            (fit.y2 - c, "sr2a-fl-slope-whole-rise"),
            (abs(m) * 2, "sr2a-fl-slope-whole-rise"),
            (m + 1 if m > 0 else m - 1, "sr2a-fl-slope-whole-rise"),
        ]
        working = [
            f"The line passes through (0, {c}) and (10, {_fmt(fit.y2)}).",
            f"Gradient = rise / run = ({_fmt(fit.y2)} - {c}) / 10 = {_fmt(m)}.",
        ]
        q = single(
            f"{fit.ctx['lead']} " + phrase(rng, _EASY_ASK),
            m,
            working,
            wrong,
            dp=_dp(m),
            lo=None,
            figure=fit.figure(),
        )
        if q:
            return q
    raise AssertionError  # pragma: no cover


# -- medium -----------------------------------------------------------------------------------------------------

_MEDIUM_ASK = (
    "The line of best fit is drawn on the scatterplot. Use the line to predict the {yq} for {xat}.",
    "A line of best fit is drawn on the scatterplot. Read from the line the predicted {yq} for {xat}.",
)


def _medium(rng):
    for _ in attempts(200, "a medium line-of-best-fit question"):
        fit = _draw(rng)
        ks = [k for k, y in zip(fit.xs, fit.ys) if k >= 2 and _whole(fit, k) and y != fit.at(k)]
        if not ks:
            continue
        k = rng.choice(ks)
        key = fit.at(k)
        point = fit.ys[fit.xs.index(k)]
        wrong = [
            (point, "sr2a-fl-predict-nearest-point"),
            (fit.m * k, "sr2a-fl-predict-forgets-intercept"),
            (fit.c + k, "sr2a-fl-predict-slope-one"),
            (key + 1, "sr2a-fl-predict-gridline-slip"),
            (key - 1, "sr2a-fl-predict-gridline-slip"),
            (fit.c * k, "sr2a-fl-predict-intercept-times-x"),
        ]
        ask = phrase(rng, _MEDIUM_ASK, yq=fit.ctx["yq"], xat=fit.ctx["xat"].format(k=k, Y=0))
        working = [
            f"The line crosses the vertical axis at {fit.c} and has gradient {_fmt(fit.m)}.",
            f"At {k}: {fit.c} + {_fmt_paren(fit.m)} x {k} = {_fmt(key)}.",
        ]
        q = single(f"{fit.ctx['lead']} {ask}", key, working, wrong, dp=_dp(key), lo=0, figure=fit.figure())
        if q:
            return q
    raise AssertionError  # pragma: no cover


# -- hard -------------------------------------------------------------------------------------------------------

_RESIDUAL_ASK = (
    "The line of best fit is drawn on the scatterplot. The point labelled P is one of the data points. Find the "
    "residual of P, where residual = actual value - predicted value. Give a negative number if P is below the line.",
    "A line of best fit is drawn and one data point is labelled P. Calculate the residual for P, using residual = "
    "actual value - predicted value; the residual is negative when P lies below the line.",
)
_INVERSE_ASK = (
    "The line of best fit is drawn on the scatterplot. For what {xq} does the line predict {yat}? Give the "
    "{xq} as a number.",
    "A line of best fit is drawn on the scatterplot. The line predicts {yat} for what {xq}? Give the number.",
)


def _hard(rng):
    for _ in attempts(300, "a hard line-of-best-fit question"):
        fit = _draw(rng)
        if rng.random() < 0.5:
            idx = [i for i, x in enumerate(fit.xs) if _whole(fit, x) and abs(fit.ys[i] - fit.at(x)) >= 2]
            if not idx:
                continue
            i = rng.choice(idx)
            fit.p = i
            x, y = fit.xs[i], fit.ys[i]
            pred = fit.at(x)
            key = y - pred
            wrong = [
                (-key, "sr2a-fl-residual-sign"),
                (y, "sr2a-fl-residual-actual-value"),
                (pred, "sr2a-fl-residual-predicted-value"),
                (abs(key), "sr2a-fl-residual-sign"),
                (key + 1, "sr2a-fl-predict-gridline-slip"),
            ]
            working = [
                f"P is at ({x}, {y}). The line predicts {fit.c} + {_fmt_paren(fit.m)} x {x} = {_fmt(pred)} at {x}.",
                f"Residual = {y} - {_fmt(pred)} = {_fmt(key)}.",
            ]
            q = single(
                f"{fit.ctx['lead']} " + phrase(rng, _RESIDUAL_ASK),
                key,
                working,
                wrong,
                dp=_dp(key),
                lo=None,
                figure=fit.figure(),
            )
        else:
            x0 = rng.randint(2, 9)
            Y = fit.at(x0)
            if Y != int(Y) or not 1 <= Y <= 23:
                continue
            Y = int(Y)
            wrong = [
                ((Y - fit.c) * fit.m, "sr2a-fl-inverse-multiplies"),
                (Y / fit.m, "sr2a-fl-inverse-no-intercept"),
                (Y - fit.c, "sr2a-fl-inverse-forgets-divide"),
                (x0 + 1, "sr2a-fl-predict-gridline-slip"),
                (x0 - 1, "sr2a-fl-predict-gridline-slip"),
            ]
            ask = phrase(rng, _INVERSE_ASK, xq=fit.ctx["xq"], yat=fit.ctx["yat"].format(Y=Y, k=0))
            working = [
                f"The line is y = {fit.c} + {_fmt_paren(fit.m)} x. Set it equal to {Y}: {fit.c} + {_fmt_paren(fit.m)} x = {Y}.",
                f"{_fmt(fit.m)} x = {Y - fit.c}, so x = {x0}.",
            ]
            q = single(
                f"{fit.ctx['lead']} {ask}",
                x0,
                working,
                [(round(v, 1), t) for v, t in wrong],
                dp=0,
                lo=0,
                figure=fit.figure(),
            )
        if q:
            return q
    raise AssertionError  # pragma: no cover


@generator(
    "sr2a_scatter_fit",
    level=12,
    presets={"easy": dict(tier="easy"), "medium": dict(tier="medium"), "hard": dict(tier="hard")},
)
def sr2a_scatter_fit(rng, tier="easy"):
    """Read a drawn line of best fit; the tiers are described in the module docstring."""
    if tier == "easy":
        return _easy(rng)
    if tier == "medium":
        return _medium(rng)
    check(tier == "hard", f"unknown tier {tier!r}")
    return _hard(rng)


# -- exam -------------------------------------------------------------------------------------------------------


@generator("sr2a_scatter_fit_chain", level=12, presets={"exam": dict(tier="exam")})
def sr2a_scatter_fit_chain(rng, tier="exam"):
    """Exam chain on one scatterplot: the gradient, a prediction, a residual, and the risk of extrapolating."""
    check(tier == "exam", f"unknown tier {tier!r}")
    for _ in attempts(300, "a line-of-best-fit chain with enough distractors"):
        fit = _draw(rng)
        cands = [i for i, x in enumerate(fit.xs) if x % 2 == 0 and x >= 2 and abs(fit.ys[i] - fit.at(x)) >= 2]
        if not cands:
            continue
        i = rng.choice(cands)
        fit.p = i
        k, actual = fit.xs[i], fit.ys[i]
        pred = int(fit.at(k))
        res = actual - pred
        far = rng.choice([15, 16, 18, 20])
        ctx = fit.ctx
        stem = f"{ctx['lead']} A line of best fit is drawn on the scatterplot. One of the data points is labelled P."
        part_a = number_part(
            "What is the gradient of the line of best fit?",
            fit.m,
            1,
            [
                f"Rise over run between (0, {fit.c}) and (10, {_fmt(fit.y2)}): ({_fmt(fit.y2)} - {fit.c}) / 10 = {_fmt(fit.m)}."
            ],
            [
                (-fit.m, "sr2a-fl-slope-sign"),
                (fit.c, "sr2a-fl-slope-as-intercept"),
                (round(1 / abs(fit.m), 1) * (1 if fit.m > 0 else -1), "sr2a-fl-slope-run-over-rise"),
                (fit.y2 - fit.c, "sr2a-fl-slope-whole-rise"),
                (abs(fit.m) * 2, "sr2a-fl-slope-whole-rise"),
            ],
            dp=_dp(fit.m),
            sensible=(None, None),
        )
        part_b = number_part(
            f"Use the line to predict the {ctx['yq']} for {ctx['xat'].format(k=k, Y=0)}.",
            pred,
            2,
            [f"{fit.c} + {_fmt_paren(fit.m)} x {k} = {pred}."],
            [
                (actual, "sr2a-fl-predict-nearest-point"),
                (int(fit.m * k), "sr2a-fl-predict-forgets-intercept"),
                (fit.c + k, "sr2a-fl-predict-slope-one"),
                (pred + 1, "sr2a-fl-predict-gridline-slip"),
                (pred - 1, "sr2a-fl-predict-gridline-slip"),
            ],
            follow=f"{fit.c} + {k}*part_a",
            lo=0,
        )
        part_c = number_part(
            "Find the residual of P, where residual = actual value - predicted value. Use your answer to part (b).",
            res,
            2,
            [f"P is at ({k}, {actual}). Residual = {actual} - {pred} = {res}."],
            [
                (-res, "sr2a-fl-residual-sign"),
                (actual, "sr2a-fl-residual-actual-value"),
                (pred, "sr2a-fl-residual-predicted-value"),
                (abs(res), "sr2a-fl-residual-sign"),
                (res + 1, "sr2a-fl-predict-gridline-slip"),
            ],
            follow=f"{actual} - part_b",
            lo=None,
            sensible=(None, None),
        )
        key = f"The prediction is unreliable, because {far} is outside the range of the data."
        part_d = mcq_part(
            f"A student uses the line to predict the {ctx['yq']} for {ctx['xat'].format(k=far, Y=0)}. "
            "Which statement about this prediction is correct?",
            key,
            1,
            [
                "The data shown only go as far as 11, so using the line at a larger value is extrapolation and may be unreliable."
            ],
            [
                (
                    f"The prediction is reliable, because the points lie close to the line.",
                    "sr2a-fl-reliable-because-close",
                ),
                (
                    f"The prediction is reliable, because a line can be extended as far as needed.",
                    "sr2a-fl-extrapolation-reliable",
                ),
                (
                    f"The prediction is exactly right, because the line passes through the points.",
                    "sr2a-fl-line-passes-all-points",
                ),
                (
                    f"The prediction is unreliable, because the line has a negative gradient.",
                    "sr2a-fl-wrong-reason-unreliable",
                ),
            ],
        )
        if None in (part_a, part_b, part_c, part_d):
            continue
        return dict(text=stem, parts=[part_a, part_b, part_c, part_d], figure=fit.figure())
    raise AssertionError  # pragma: no cover


# -- the figure readers -----------------------------------------------------------------------------------------


def _line(question):
    (x1, y1), (x2, y2) = question.figure["lines"][0]["through"]
    m = (y2 - y1) / (x2 - x1)
    return y1 - m * x1, m


def _points(question):
    pts = question.figure["points"]
    return [(p["at"][0], p["at"][1], p.get("label")) for p in pts]


def _num(v):
    return _fmt(float(v))


def _read_fit(question) -> str:
    c, m = _line(question)
    ask = question.text.split("best fit", 1)[-1]
    if "gradient" in ask:
        return _num(m)
    if "residual" in ask:
        x, y, _ = next(p for p in _points(question) if p[2] == "P")
        return _num(y - (c + m * x))
    nums = [int(v) for v in re.findall(r"\b(\d+)\b", ask)]
    if "predict" in ask and ("for what" in ask.lower() or "predicts" in ask):
        return _num((nums[0] - c) / m)
    return _num(c + m * nums[0])


def _read_chain(question) -> str:
    c, m = _line(question)
    x, y, _ = next(p for p in _points(question) if p[2] == "P")
    pred = c + m * x
    far = int(re.findall(r"\b(\d+)\b", question.parts[3].prompt.split("predict", 1)[1])[0])
    return (
        f"(a) {_num(m)}; (b) {_num(pred)}; (c) {_num(y - pred)}; "
        f"(d) The prediction is unreliable, because {far} is outside the range of the data."
    )


figures.register_reader("sr2a_scatter_fit", _read_fit)
figures.register_reader("sr2a_scatter_fit_chain", _read_chain)
