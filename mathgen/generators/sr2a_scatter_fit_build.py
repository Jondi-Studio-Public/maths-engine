"""Generates `scatterplot-fit-line-read-predict` questions (easy, medium, hard) and the exam chain `sr2a_scatter_fit_chain`.

Reading a line of best fit that is drawn on a scatterplot (ACMGM053 and ACMGM054, with the residual that comes with
using a fitted line), `statistics-probability`, answer ``number``. The figure is a ``cartesian`` scatterplot of ten
points with the line drawn through two of its gridline crossings, so the learner reads the gradient and the intercept
off the picture; the prompt never states them. Each drawn line is accepted only when it is close to the least-squares
line of the plotted points, so it is honestly "the line of best fit".

* easy: the gradient of the line (a falling line has a negative gradient);
* medium: predict the value of the vertical variable for an x that has a plotted point (so reading the point instead
  of the line is a real mistake), a value inside the range of the data;
* hard: either the residual (actual minus predicted) of the labelled point P, or the x at which the line predicts a
  stated value;
* exam (``sr2a_scatter_fit_chain``): (a) the gradient, (b) the predicted value at the x of P (follow-through from (a)),
  (c) the residual of P (follow-through from (b)), (d) which statement about predicting far outside the data is right.

The registered figure readers recover the line from the two points it passes through and the points from the plot.
"""

