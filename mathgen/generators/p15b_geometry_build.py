"""Generates two `advanced-geometry-and-topology` skills, including `simplex-homology`, whose answer is one of
three fixed Betti lists.

Both sit in `advanced-geometry-and-topology`. The answer-space requirements bind
`simplex-homology`: its honest answer space is the three FIXED Betti lists
the contract names (a filled triangle, the boundary of a triangle, a single
edge) -- there is nothing further to randomise about the mathematics itself,
so variety comes from the METHOD of presentation, never a fourth answer.
"""

from __future__ import annotations

import random

import sympy

from ..core import check, check_equivalent, generator, rational_text

# ---------------------------------------------------------------------------
# ucv1-fundamental-group-map
# ---------------------------------------------------------------------------

# The skill's contract: "Select the induced map on the fundamental group
# for one supplied circle or interval map from finite labelled options." No
# formal_verification gate is needed because this is already
# a closed-set mcq lookup, never a proof. Convention stated in every prompt:
# pi_1(S^1, 1) = Z, generated by the standard positively-oriented loop
# gamma(t) = e^{2 pi i t}.


def _exp(n: int) -> str:
    """An exponent written as plain text: ``4``, or ``(-4)`` for a negative power."""
    return f"({n})" if n < 0 else str(n)


def _zero_map_text() -> str:
    return "the zero map"


def _mult_text(k: int) -> str:
    return f"multiplication by {k}"


def _draw_distinct_mult_labels(rng: random.Random, exclude: set[int], count: int, lo=-6, hi=6):
    pool = [k for k in range(lo, hi + 1) if k != 0 and k not in exclude]
    rng.shuffle(pool)
    check(len(pool) >= count, "fundamental-group-map: not enough distinct nonzero multiplier candidates")
    return pool[:count]


_INDUCED_MAP_PHRASINGS = [
    "Which map does f induce on pi_1(S^1) = Z?",
    "What is the induced homomorphism f_*: pi_1(S^1) -> pi_1(S^1)?",
    "Which of the following is f_*, the map f induces on pi_1(S^1) = Z?",
]

#: The composed map's phrasings ask about h = g o f specifically, never f
#: alone -- f_* and h_* are different maps in general (f_* = multiplication
#: by a, h_* = multiplication by a*b), so a phrasing borrowed from the
#: single-map branch would ask a different question than the one the answer
#: key actually answers.
_COMPOSED_MAP_PHRASINGS = [
    "Which map does h = g o f induce on pi_1(S^1) = Z?",
    "What is the induced homomorphism h_* = (g o f)_*: pi_1(S^1) -> pi_1(S^1)?",
    "Which of the following is h_*, the map h = g o f induces on pi_1(S^1) = Z?",
]


@generator(
    "p15b_fundamental_group_map",
    level=20,
    presets={
        "easy": dict(m_lo=1, m_hi=5, allow_zero=False, allow_interval=False, compose=False),
        "medium": dict(m_lo=1, m_hi=6, allow_zero=False, allow_interval=False, compose=False),
        "hard": dict(m_lo=1, m_hi=4, allow_zero=True, allow_interval=True, compose=False),
        "exam": dict(m_lo=1, m_hi=4, allow_zero=False, allow_interval=False, compose=True),
    },
)
def p15b_fundamental_group_map(rng, m_lo=1, m_hi=2, allow_zero=False, allow_interval=False, compose=False):
    """Select the induced map on pi_1(S^1) = Z for one supplied circle or
    interval map (the skill's contract).

    A degree-n circle map z -> z^n induces multiplication by n. A map that
    factors through a contractible space (an interval) induces the zero map
    -- and so, consistently, does the degenerate degree-0 circle map
    z -> z^0 = 1 (a constant map), which the hard tier also draws so the two
    equal-in-substance cases are never given separate, colliding option
    text.

    easy/medium: a single circle map z -> z^n is read directly.
    hard: the SAME family, now also drawing n = 0 and, separately, maps that
    literally factor through an interval -- both render "the zero map".
    exam: a COMPOSITION of two circle maps, z -> z^a then z -> z^b; the
    induced map is multiplication by a*b (deg(g o f) = deg(g) deg(f)), a
    genuinely different METHOD (multiply two degrees) rather than reading
    one exponent off the page.
    """
    if compose:
        pool = [k for k in range(m_lo, m_hi + 1) if k != 0] + [k for k in range(-m_hi, -m_lo + 1) if k != 0]
        a = rng.choice(pool)
        b = rng.choice(pool)
        true_m = a * b
        check(true_m != 0, "fundamental-group-map exam: composed degree must be nonzero")
        text_body = f"f: S^1 -> S^1, f(z) = z^{{{a}}}; g: S^1 -> S^1, g(z) = z^{{{b}}}. h = g o f."
        latex_body = rf"f(z)=z^{{{a}}},\ g(z)=z^{{{b}}},\ h=g\circ f"
        working_kind = "compose"
        interval = False
        true_n = None
    elif allow_interval and rng.random() < 0.2:
        interval = True
        interval_wordings = [
            "f: S^1 -> S^1 first maps into the interval [0, 1] (a contractible space), "
            "then includes [0, 1] back into S^1.",
            "f: S^1 -> S^1 is the composite of a map into the contractible interval [0, 1] "
            "followed by an inclusion of [0, 1] into S^1.",
        ]
        text_body = rng.choice(interval_wordings)
        latex_body = r"f: S^1 \to [0,1] \to S^1"
        working_kind = "interval"
        true_n = None
        true_m = 0  # placeholder, resolved to zero map below
    else:
        interval = False
        # Nonzero range plus, when allowed, EXACTLY one zero entry -- never
        # built from two ranges that both happen to touch 0, which silently
        # doubled (then, with the old separate allow_zero append, TRIPLED)
        # the draw weight on the zero-map class relative to every other
        # value.
        pool = list(range(m_lo, m_hi + 1)) + list(range(-m_hi, -m_lo + 1))
        check(0 not in pool, "fundamental-group-map: nonzero pool unexpectedly contains 0")
        if allow_zero:
            pool.append(0)
        true_n = rng.choice(pool)
        true_m = true_n
        text_body = f"f: S^1 -> S^1, f(z) = z^{{{true_n}}}."
        latex_body = rf"f(z)=z^{{{true_n}}}"
        working_kind = "degree"

    if interval or true_m == 0:
        answer_text = _zero_map_text()
    else:
        answer_text = _mult_text(true_m)

    # Independent re-derivation: the induced map on pi_1 is multiplication by
    # the map's TOPOLOGICAL DEGREE. A degree-n circle self-map has degree n
    # by definition; a composition's degree is deg(g) deg(f) (checked via
    # sympy as a second, symbolic route, never trusting the Python int
    # multiplication alone); a map through a contractible space has degree
    # 0 because pi_1 of a point is trivial, so the induced map is forced to
    # be the zero homomorphism regardless of the two factor maps' own
    # degrees.
    if working_kind == "compose":
        check_equivalent(
            sympy.Integer(a) * sympy.Integer(b),
            sympy.Integer(true_m),
            "fundamental-group-map exam: composed degree mismatch",
        )
        derived_zero = true_m == 0
    elif working_kind == "degree":
        derived_zero = true_n == 0
    else:
        derived_zero = True
    check(
        derived_zero == (answer_text == _zero_map_text()),
        "fundamental-group-map: zero-map classification disagrees with the derived degree",
    )

    exclude = {0}
    if answer_text != _zero_map_text():
        exclude.add(true_m)
    mult_distractor_count = 3 if answer_text == _zero_map_text() else 2
    mult_values = _draw_distinct_mult_labels(rng, exclude, mult_distractor_count)

    options = []
    if answer_text == _zero_map_text():
        options = [_mult_text(k) for k in mult_values] + [_zero_map_text()]
    else:
        options = [_mult_text(true_m)] + [_mult_text(k) for k in mult_values] + [_zero_map_text()]
    check(len(set(options)) == len(options), "fundamental-group-map: option collision")
    distractors = [o for o in options if o != answer_text]
    check(len(distractors) == 3, "fundamental-group-map: expected exactly three distractors")

    convention = "The standard generator of pi_1(S^1, 1) = Z is the loop gamma(t) = e^(2 pi i t), t in [0, 1]."
    question = rng.choice(_COMPOSED_MAP_PHRASINGS if working_kind == "compose" else _INDUCED_MAP_PHRASINGS)
    text = f"{convention} {text_body} {question}"
    latex = rf"\text{{{convention}}}\quad {latex_body}\quad\text{{{question}}}"

    if working_kind == "compose":
        working = [
            f"deg(f) = {a}, deg(g) = {b}. deg(g o f) = deg(g) times deg(f) = {a} times {b} = {true_m}, "
            f"so h induces {answer_text}."
        ]
    elif working_kind == "interval":
        working = [
            "f factors through the interval [0, 1], which is contractible, so pi_1([0,1]) = 0 "
            "and the induced map on pi_1(S^1) must be the zero map."
        ]
    else:
        working = [f"f(z) = z^{_exp(true_n)} has degree {true_n}, so f induces {answer_text} on pi_1(S^1) = Z."]

    return dict(
        text=text,
        latex=latex,
        answer=answer_text,
        answer_text=answer_text,
        answer_latex=rf"\text{{{answer_text}}}",
        working=working,
        distractors=distractors,
    )


# ---------------------------------------------------------------------------
# ucv1-simplex-homology
# ---------------------------------------------------------------------------

# The skill's contract: "Compute the Betti-number list of a supplied
# triangle, boundary triangle or single edge using its boundary matrices."
# The honest answer space is exactly these THREE fixed
# lists (one per complex), never a fourth -- escalation is by presentation
# METHOD only (name the complex -> list its simplices -> read boundary
# matrices with relabelled, reoriented vertices), never by inventing a new
# complex or a new answer.

_COMPLEXES = ("filled_triangle", "boundary_triangle", "single_edge")


def _canonical_chain(complex_kind: str):
    """Canonical (0-indexed) vertices/edges/faces and boundary matrices for
    one of the three fixed complexes, using sympy.Matrix for exact rational
    rank computation."""
    if complex_kind == "single_edge":
        vertices = [0, 1]
        edges = [(0, 1)]
        faces = []
    elif complex_kind == "boundary_triangle":
        vertices = [0, 1, 2]
        edges = [(0, 1), (1, 2), (0, 2)]
        faces = []
    elif complex_kind == "filled_triangle":
        vertices = [0, 1, 2]
        edges = [(0, 1), (1, 2), (0, 2)]
        faces = [(0, 1, 2)]
    else:
        raise ValueError(complex_kind)

    d1 = sympy.zeros(len(vertices), len(edges))
    for col, (i, j) in enumerate(edges):
        d1[i, col] = -1
        d1[j, col] = 1

    d2 = sympy.zeros(len(edges), len(faces))
    edge_index = {e: k for k, e in enumerate(edges)}
    for col, (i, j, k) in enumerate(faces):
        # standard alternating boundary: d(face) = (j,k) - (i,k) + (i,j)
        d2[edge_index[(j, k)], col] += 1
        d2[edge_index[(i, k)], col] += -1
        d2[edge_index[(i, j)], col] += 1

    check(
        (d1 * d2).is_zero_matrix if faces else True,
        f"simplex-homology: boundary composition d1 d2 != 0 for {complex_kind}",
    )
    return vertices, edges, faces, d1, d2


def _betti_numbers(vertices, edges, faces, d1, d2):
    n0, n1, n2 = len(vertices), len(edges), len(faces)
    r1 = d1.rank() if n1 else 0
    r2 = d2.rank() if n2 else 0
    b0 = n0 - r1
    b1 = (n1 - r1) - r2
    if n2:
        b2 = n2 - r2
        return [b0, b1, b2]
    return [b0, b1]


_TRUE_BETTI = {kind: _betti_numbers(*_canonical_chain(kind)[:3], *_canonical_chain(kind)[3:]) for kind in _COMPLEXES}


def _apply_display_transform(vertices, edges, faces, d1, d2, rng: random.Random, labels):
    """Relabel vertices (display only) and, when there are edges to flip,
    reorient a random subset -- flipping the sign of column e of d1 AND row
    e of d2 together, which is a change of basis in C1 and leaves the
    product d1 @ d2 (and every rank) exactly unchanged. Verified below by
    literally recomputing d1_display @ d2_display == 0, never assumed."""
    vertex_labels = {v: labels[v] for v in vertices}
    d1_disp = d1.copy()
    d2_disp = d2.copy()
    signs = []
    for e_index in range(len(edges)):
        s = rng.choice([1, -1])
        signs.append(s)
        d1_disp[:, e_index] = s * d1_disp[:, e_index]
        if d2_disp.shape[1]:
            d2_disp[e_index, :] = s * d2_disp[e_index, :]
    if d2_disp.shape[1] and d1_disp.shape[1]:
        check((d1_disp * d2_disp).is_zero_matrix, "simplex-homology: reoriented boundary composition is no longer zero")
    return vertex_labels, signs, d1_disp, d2_disp


def _render_named(kind: str, labels) -> str:
    names = {
        "filled_triangle": "a filled triangle (2-simplex, with its 2-dimensional face included)",
        "boundary_triangle": "the boundary of a triangle (three vertices and three edges, no face)",
        "single_edge": "a single edge (two vertices joined by one edge)",
    }
    return f"The simplicial complex X is {names[kind]}, on vertices ({', '.join(labels)})."


def _render_simplex_list(kind: str, vertices, edges, faces, vertex_labels) -> str:
    v_text = ", ".join(vertex_labels[v] for v in vertices)
    e_text = "; ".join(f"({vertex_labels[i]}, {vertex_labels[j]})" for i, j in edges)
    parts = [f"vertices ({v_text})", f"edges [{e_text}]" if edges else "no edges"]
    if faces:
        f_text = "; ".join(f"({vertex_labels[i]}, {vertex_labels[j]}, {vertex_labels[k]})" for i, j, k in faces)
        parts.append(f"one 2-dimensional face [{f_text}]")
    else:
        parts.append("no 2-dimensional face")
    return "X has " + ", ".join(parts) + "."


def _matrix_latex(m: sympy.Matrix) -> str:
    if m.shape[1] == 0:
        return r"\text{(no columns)}"
    rows = " \\\\ ".join(" & ".join(str(m[i, j]) for j in range(m.shape[1])) for i in range(m.shape[0]))
    return rf"\begin{{bmatrix}}{rows}\end{{bmatrix}}"


def _matrix_plain(m: sympy.Matrix) -> str:
    """Plain-ASCII rendering of the same matrix, so the boundary matrix is
    also visible in `question.text` -- never only in `latex` -- for any
    consumer (e.g. a spoken/text-only path) that does not render LaTeX."""
    if m.shape[1] == 0:
        return "(no columns)"
    rows = "; ".join(", ".join(str(m[i, j]) for j in range(m.shape[1])) for i in range(m.shape[0]))
    return f"[{rows}]"


def _distractor_lists(kind: str, true_list: list[int]) -> list[list[int]]:
    """Plausible wrong Betti lists (dropping b0, an off-by-one b1, or a
    miscounted b0), by name, per complex -- never another complex's own
    correct list, checked below."""
    catalogue = {
        "single_edge": [[0, 0], [2, 0], [0, 1]],
        "boundary_triangle": [[0, 1], [2, 1], [1, 2]],
        "filled_triangle": [[0, 0, 0], [1, 1, 0], [1, 0, 1]],
    }
    candidates = catalogue[kind]
    for other_kind, other_list in _TRUE_BETTI.items():
        check(
            other_list not in candidates,
            f"simplex-homology: a distractor for {kind} literally equals {other_kind}'s true answer",
        )
    check(true_list not in candidates, f"simplex-homology: a distractor for {kind} equals its own true answer")
    return candidates


def _fmt_list(values: list[int]) -> str:
    return ", ".join(rational_text(v) for v in values)


@generator(
    "p15b_simplex_homology",
    level=20,
    presets={
        "easy": dict(method="named"),
        "medium": dict(method="simplex_list"),
        "hard": dict(method="matrix"),
        "exam": dict(method="matrix_reoriented"),
    },
)
def p15b_simplex_homology(rng, method="named"):
    """Compute the Betti-number list [b0, b1(, b2)] of a supplied fixed
    simplicial complex (the skill's own three: a filled triangle, the
    boundary of a triangle, a single edge) -- the honest answer space is
    exactly these three lists, drawn uniformly, never a fourth.

    Escalates by METHOD, never by a new answer: easy names the complex;
    medium lists its simplices; hard reads an explicit boundary matrix
    (relabelled vertices); exam reads the SAME matrices with a random
    per-edge reorientation (a genuine change of basis, verified to leave
    d1 @ d2 = 0 and every rank exactly unchanged), so a memorised "standard"
    matrix shape no longer matches.
    """
    kind = rng.choice(_COMPLEXES)
    vertices, edges, faces, d1, d2 = _canonical_chain(kind)
    true_list = _betti_numbers(vertices, edges, faces, d1, d2)
    check(true_list == _TRUE_BETTI[kind], "simplex-homology: recomputed Betti list disagrees with the cached one")

    label_pool = list("ABCDEFGH")
    rng.shuffle(label_pool)
    labels = label_pool[: len(vertices)]

    if method == "named":
        text_body = _render_named(kind, labels)
    elif method == "simplex_list":
        vertex_labels = {v: labels[v] for v in vertices}
        text_body = _render_simplex_list(kind, vertices, edges, faces, vertex_labels)
    else:
        reoriented = method == "matrix_reoriented"
        vertex_labels, signs, d1_disp, d2_disp = (
            _apply_display_transform(vertices, edges, faces, d1, d2, rng, labels)
            if reoriented
            else ({v: labels[v] for v in vertices}, [1] * len(edges), d1, d2)
        )
        recomputed = _betti_numbers(vertices, edges, faces, d1_disp, d2_disp)
        check(
            recomputed == true_list,
            "simplex-homology: displayed (relabelled/reoriented) matrices give a different Betti list",
        )
        v_text = ", ".join(vertex_labels[v] for v in vertices)
        e_text = ", ".join(f"e{i + 1}" for i in range(len(edges)))
        latex_pieces = [rf"\partial_1 = {_matrix_latex(d1_disp)}"]
        plain_pieces = [f"d1 (rows {v_text}; columns {e_text}) = {_matrix_plain(d1_disp)}"]
        if faces:
            f_text = ", ".join(f"f{i + 1}" for i in range(len(faces)))
            latex_pieces.append(rf"\partial_2 = {_matrix_latex(d2_disp)}")
            plain_pieces.append(f"d2 (rows {e_text}; columns {f_text}) = {_matrix_plain(d2_disp)}")
        text_body = (
            f"X's boundary matrices, with rows and columns in the stated order (vertices "
            f"{v_text}; edges {e_text}), are: " + "; ".join(plain_pieces) + "."
        )
        latex_intro = (
            f"X's boundary matrices, with rows and columns in the stated order "
            f"(vertices {v_text}; edges {e_text}), are:"
        )
        matrix_latex = r"\quad ".join(latex_pieces)

    length = len(true_list)
    instruction = (
        f"Give your answer as the ordered list [b0, b1{', b2' if length == 3 else ''}] "
        f"of Betti numbers ({length} value{'s' if length != 1 else ''}, in that order)."
    )
    text = f"{text_body} {instruction}"
    if method in ("matrix", "matrix_reoriented"):
        latex = rf"\text{{{latex_intro}}}\quad {matrix_latex}\quad\text{{{instruction}}}"
    else:
        latex = rf"\text{{{text_body}}}\quad\text{{{instruction}}}"

    answer_text = _fmt_list(true_list)
    distractor_lists = _distractor_lists(kind, true_list)
    distractor_texts = [_fmt_list(d) for d in distractor_lists]
    check(len(set([answer_text, *distractor_texts])) == 4, "simplex-homology: distractor collision")

    if kind == "filled_triangle":
        working = [
            f"rank(d1) = {d1.rank()}, rank(d2) = {d2.rank()}. b0 = {len(vertices)} - {d1.rank()} = "
            f"{true_list[0]}; b1 = ({len(edges)} - {d1.rank()}) - {d2.rank()} = {true_list[1]}; "
            f"b2 = {len(faces)} - {d2.rank()} = {true_list[2]}."
        ]
    elif kind == "boundary_triangle":
        working = [
            f"rank(d1) = {d1.rank()}. b0 = {len(vertices)} - {d1.rank()} = {true_list[0]}; "
            f"b1 = {len(edges)} - {d1.rank()} = {true_list[1]} (no 2-cells, so rank(d2) = 0)."
        ]
    else:
        working = [
            f"rank(d1) = {d1.rank()}. b0 = {len(vertices)} - {d1.rank()} = {true_list[0]}; "
            f"b1 = {len(edges)} - {d1.rank()} = {true_list[1]}."
        ]

    return dict(
        text=text,
        latex=latex,
        answer=[*true_list],
        answer_text=answer_text,
        answer_latex=rf"\text{{{answer_text}}}",
        working=working,
        distractors=distractor_texts,
    )
