@generator("exd_x_r4c_quotient_group_order_and_structure", level=19, presets={"exam": dict(tier="exam")})
def exd_x_r4c_quotient_group_order_and_structure(rng, tier="exam"):
    """Exam chain: order of a generator, order of the quotient, order of a coset, invariant factors."""
    check(tier == "exam", f"unknown tier {tier!r}")
    for _ in attempts(1000, "a quotient with a non-trivial coset order and a non-cyclic shape"):
        m, n, a, b, o, d1, d2 = _pair(rng, _SIZES, want_rank_two=True)
        c, d = rng.randrange(m), rng.randrange(n)
        coset = _coset_order(m, n, a, b, c, d)
        if coset >= 3 and (c, d) != (a, b) and coset != d2:
            break
    order = m * n // o
    pair_order = _pair_order(m, n, c, d)
    return dict(
        text=rng.choice(
            [
                f"Let G = Z_{m} × Z_{n} and let H be the subgroup of G generated by ({a}, {b}).",
                f"The group G = Z_{m} × Z_{n} has a subgroup H = ⟨({a}, {b})⟩.",
                f"Consider G = Z_{m} × Z_{n} under componentwise addition, and the cyclic subgroup H of G generated by ({a}, {b}).",
            ]
        ),
        parts=[
            number_part(
                f"Find the order of ({a}, {b}) in G.",
                o,
                2,
                [f"lcm({m} / gcd({m}, {a}), {n} / gcd({n}, {b})) = lcm({m // gcd(m, a)}, {n // gcd(n, b)}) = {o}."],
                [
                    ((m // gcd(m, a)) * (n // gcd(n, b)), "pair-order-taken-as-product-of-component-orders"),
                    (max(m // gcd(m, a), n // gcd(n, b)), None),
                    (m * n // o, "subgroup-order-is-index"),
                    (o + 1, None),
                    (o * 2, None),
                    (o + 2, None),
                ],
                sensible_range=(0, m * n),
            ),
            number_part(
                "Find the order of the quotient group G / H.",
                order,
                1,
                [f"|G / H| = {m * n} / {o} = {order}."],
                [
                    (o, "quotient-order-is-subgroup-order"),
                    (m * n, "quotient-order-forgets-the-subgroup"),
                    (order + 1, None),
                    (order * 2, None),
                ],
                follow_through=f"{m * n} / part_a",
                sensible_range=(0, m * n),
            ),
            number_part(
                f"Find the order of the element ({c}, {d}) + H in G / H.",
                coset,
                3,
                [f"It is the least k > 0 with k({c}, {d}) in H. That is k = {coset}."],
                [
                    (pair_order, "coset-order-ignores-the-subgroup"),
                    (order, "quotient-element-order-is-group-order"),
                    (d2, "coset-order-is-exponent"),
                    (coset + 1, None),
                    (coset * 2, None),
                ],
                sensible_range=(0, m * n),
            ),
            ordered_part(
                "Write G / H as Z_d1 × Z_d2 with d1 dividing d2 (d1 = 1 is allowed). Give the pair (d1, d2).",
                [d1, d2],
                3,
                [f"d1 = gcd({m}, {n}, {a}, {b}) = {d1}.", f"d1·d2 = |G / H| = {order}, so d2 = {d2}."],
                [
                    ([1, order], "quotient-assumed-cyclic"),
                    ([d2, d1], "invariant-factors-order-swapped"),
                    ([d1, d2 * 2], None),
                    ([gcd(m, a) if a else m, gcd(n, b) if b else n], "quotient-factorwise-instead-of-by-lattice"),
                ],
            ),
        ],
    )
