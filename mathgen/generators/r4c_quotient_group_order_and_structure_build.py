"""Generates `r4c_quotient_group_order_and_structure` questions and the exam chain `exd_x_r4c_quotient_group_order_and_structure`.

``uc2-quotient-group-order-and-structure`` (``abstract-algebra``): order and structure of quotients of abelian groups.

* easy (number): in Z_n / ⟨k⟩, the order of the element a + ⟨k⟩. The quotient is cyclic of order gcd(n, k), so the element
  has order d / gcd(d, a) with d = gcd(n, k).
* medium (number): the order of (Z_m × Z_n) / ⟨(a, b)⟩, which is mn divided by the order of (a, b).
* hard (number): in the same quotient Q, how many elements g satisfy kg = 0. Q is Z_d1 × Z_d2 with d1 dividing d2, the
  invariant factors coming from the relation lattice: d1 = gcd(m, n, a, b) and d1·d2 = gcd(mn, mb, na); the count is
  gcd(k, d1)·gcd(k, d2), which is not what a cyclic quotient of the same order would give.
* exam: Z_m × Z_n with H = ⟨(a, b)⟩: (a) the order of (a, b), (b) the order of the quotient (follows from (a)), (c) the
  order of a given coset in the quotient, (d) the invariant factors.

The tests build the quotient as a set of cosets and read the exponent and order off it.
"""

from __future__ import annotations

from math import gcd, lcm

from ..core import attempts, check, generator
from ._r4c_kit import int_options, number_part, number_question, ordered_part


def _pair_order(m, n, a, b):
    return lcm(m // gcd(m, a), n // gcd(n, b))


def _factors(m, n, a, b):
    d1 = gcd(gcd(m, n), gcd(a, b))
    total = gcd(gcd(m * n, m * b), n * a)
    check(total % d1 == 0, "the first invariant factor does not divide the product")
    return d1, total // d1


def _coset_order(m, n, a, b, c, d):
    """Least k > 0 with k(c, d) in <(a, b)>."""
    h = {((j * a) % m, (j * b) % n) for j in range(_pair_order(m, n, a, b))}
    for k in range(1, m * n + 1):
        if ((k * c) % m, (k * d) % n) in h:
            return k
    raise AssertionError("no power of the coset is trivial")  # pragma: no cover


def _easy(rng):
    for _ in attempts(500, "a quotient Z_n / <k> where the generator is not a divisor and the coset has order above 1"):
        n = rng.choice([24, 30, 36, 40, 42, 48, 60, 72, 84, 90, 96, 108, 120, 144])
        d = rng.choice([x for x in range(4, n) if n % x == 0 and x <= 36])
        units = [u for u in range(1, n // d + 1) if gcd(u, n) == 1 and u * d < n]
        k = d * rng.choice(units)
        a = rng.randrange(1, n)
        order = d // gcd(d, a)
        slips = [
            (d, "quotient-element-order-is-group-order"),
            (n // gcd(n, a), "quotient-element-order-in-the-big-group"),
            (n // d, "quotient-element-order-is-subgroup-order"),
            (d // gcd(d, a % d if a % d else d) if (a % d) and d // gcd(d, a % d) != order else None, None),
            (order + 1, None),
            (order * 2 if order * 2 <= d else None, None),
        ]
        if order >= 3 and (k != d or rng.random() < 0.2):
            if len(int_options(order, slips, 4)) >= 2:  # redraw when the slips collapse onto the answer
                break
    check(gcd(n, k) == d, "the gcd differs from the planned divisor")
    # second route: the least multiple of a that lands in <k> (the multiples of d)
    check(
        order == next(j for j in range(1, n + 1) if (j * a) % d == 0), "the coset order differs from the direct search"
    )
    stem = rng.choice(
        [
            f"In the quotient group Z_{n} / ⟨{k}⟩, find the order of the element {a} + ⟨{k}⟩.",
            f"Let Q = Z_{n} / ⟨{k}⟩. What is the order of the coset {a} + ⟨{k}⟩ in Q?",
            f"The coset {a} + ⟨{k}⟩ is an element of the quotient group Z_{n} / ⟨{k}⟩. How many times must it be added to "
            "itself to reach the identity coset?",
        ]
    )
    return number_question(
        stem,
        order,
        [
            f"⟨{k}⟩ = ⟨gcd({k}, {n})⟩ = ⟨{d}⟩, so the quotient is Z_{d}.",
            f"{a} + ⟨{k}⟩ has order {d} / gcd({d}, {a}) = {order}.",
        ],
        slips,
    )


def _pair(rng, sizes, want_rank_two=None):
    for _ in attempts(1000, "a pair (a, b) giving a quotient with the wanted shape"):
        m, n = rng.choice(sizes), rng.choice(sizes)
        a, b = rng.randrange(m), rng.randrange(n)
        if (a, b) == (0, 0) or m * n > 400:
            continue
        o = _pair_order(m, n, a, b)
        if m * n // o < 4 or o < 3:
            continue
        d1, d2 = _factors(m, n, a, b)
        if want_rank_two is not None and (d1 > 1) != want_rank_two:
            continue
        return m, n, a, b, o, d1, d2
    raise AssertionError  # pragma: no cover


_SIZES = [4, 6, 8, 9, 10, 12, 15, 16, 18, 20, 24, 30]


def _medium(rng):
    m, n, a, b, o, d1, d2 = _pair(rng, _SIZES)
    key = m * n // o
    check(key == d1 * d2, "the quotient order differs from the product of the invariant factors")
    stem = rng.choice(
        [
            f"Let H be the subgroup of Z_{m} × Z_{n} generated by ({a}, {b}). Find the order of the quotient group (Z_{m} × Z_{n}) / H.",
            f"Find |G / H|, where G = Z_{m} × Z_{n} and H = ⟨({a}, {b})⟩.",
            f"The element ({a}, {b}) of Z_{m} × Z_{n} generates a subgroup H. How many cosets of H are there in Z_{m} × Z_{n}?",
        ]
    )
    return number_question(
        stem,
        key,
        [
            f"The order of ({a}, {b}) is lcm({m} / gcd({m}, {a}), {n} / gcd({n}, {b})) = {o}.",
            f"|G / H| = {m * n} / {o} = {key}.",
        ],
        [
            (o, "quotient-order-is-subgroup-order"),
            (m * n // ((m // gcd(m, a)) * (n // gcd(n, b))), "pair-order-taken-as-product-of-component-orders"),
            (m * n, "quotient-order-forgets-the-subgroup"),
            (m * n // (m // gcd(m, a)), None),
            (m * n // (n // gcd(n, b)), None),
            (key * 2, None),
        ],
    )


def _hard(rng):
    for _ in attempts(500, "a non-cyclic quotient and a multiplier sharing a factor with d1"):
        m, n, a, b, o, d1, d2 = _pair(rng, _SIZES, want_rank_two=True)
        k = rng.choice([x for x in range(2, 25) if gcd(x, d1) > 1 and x != d2 and x != d1])
        key = gcd(k, d1) * gcd(k, d2)
        if key != gcd(k, d1 * d2):
            break
    order = d1 * d2
    stem = rng.choice(
        [
            f"Let H be the subgroup of Z_{m} × Z_{n} generated by ({a}, {b}), and let Q = (Z_{m} × Z_{n}) / H. "
            f"How many elements g of Q satisfy {k}g = 0?",
            f"With G = Z_{m} × Z_{n}, H = ⟨({a}, {b})⟩ and Q = G / H, count the elements g of Q for which {k}g is the identity.",
            f"How many cosets g + H of H = ⟨({a}, {b})⟩ in Z_{m} × Z_{n} satisfy {k}(g + H) = H?",
        ]
    )
    return number_question(
        stem,
        key,
        [
            f"|Q| = {m * n} / {o} = {order}. The relations give d1 = gcd({m}, {n}, {a}, {b}) = {d1}, so Q is Z_{d1} × Z_{d2}.",
            f"{k}g = 0 in each factor has gcd({k}, {d1}) = {gcd(k, d1)} and gcd({k}, {d2}) = {gcd(k, d2)} solutions: {key} in all.",
        ],
        [
            (gcd(k, order), "quotient-assumed-cyclic"),
            (gcd(k, d1) + gcd(k, d2), "solution-counts-added-not-multiplied"),
            (gcd(k, d2), "quotient-solutions-from-largest-factor-only"),
            (k, "elements-killed-by-k-taken-as-k"),
            (key * 2, None),
            (key + 1, None),
        ],
    )


@generator(
    "r4c_quotient_group_order_and_structure",
    level=19,
    presets={"easy": dict(tier="easy"), "medium": dict(tier="medium"), "hard": dict(tier="hard")},
)
def r4c_quotient_group_order_and_structure(rng, tier="easy"):
    """Order and structure of a quotient of an abelian group; the tiers are described in the module docstring."""
    if tier == "easy":
        return _easy(rng)
    if tier == "medium":
        return _medium(rng)
    check(tier == "hard", f"unknown tier {tier!r}")
    return _hard(rng)


